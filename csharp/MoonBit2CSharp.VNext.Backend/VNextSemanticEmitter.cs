    private StatementSyntax EmitForLoop(JsonElement expr, string? resultDestination = null)
    {
        var statements = new List<StatementSyntax>();
        foreach (var binding in expr.GetProperty("bindings").EnumerateArray())
            statements.Add(
                LocalDeclarationStatement(
                    VariableDeclaration(EmitType(binding.GetProperty("type")))
                        .WithVariables(
                            SingletonSeparatedList(
                                VariableDeclarator(Identifier(LocalIdentifier(binding)))
                                    .WithInitializer(
                                        EqualsValueClause(EmitExpr(binding.GetProperty("value")))
                                    )
                            )
                        )
                )
            );

        var bodyStatements = new List<StatementSyntax>();
        currentForLoops.Push(new(expr, resultDestination, null));
        try
        {
            EmitForLoopBodyStatement(
                expr.GetProperty("body"),
                expr,
                bodyStatements,
                resultDestination
            );
        }
        finally
        {
            currentForLoops.Pop();
        }

        if (!StatementListTerminates(bodyStatements))
            EmitForLoopUpdates(expr, bodyStatements);

        var condition = expr.GetProperty("condition");
        statements.Add(
            WhileStatement(
                condition.ValueKind == JsonValueKind.Null
                    ? LiteralExpression(SyntaxKind.TrueLiteralExpression)
                    : EmitExpr(condition),
                Block(bodyStatements)
            )
        );
        return Block(statements);
    }

    private StatementSyntax EmitForIn(JsonElement expr, string? resultDestination = null)
    {
        var statements = new List<StatementSyntax>();
        foreach (var binding in expr.GetProperty("bindings").EnumerateArray())
            statements.Add(
                LocalDeclarationStatement(
                    VariableDeclaration(EmitType(binding.GetProperty("type")))
                        .WithVariables(
                            SingletonSeparatedList(
                                VariableDeclarator(Identifier(LocalIdentifier(binding)))
                                    .WithInitializer(
                                        EqualsValueClause(EmitExpr(binding.GetProperty("value")))
                                    )
                            )
                        )
                )
            );

        var breakFlagName =
            ForInHasNoBreak(expr) && resultDestination is not null
                ? FreshEmitterTempName("__mbt_loop_broke")
                : null;
        if (breakFlagName is not null)
            statements.Add(
                LocalDeclarationStatement(
                    VariableDeclaration(PredefinedType(Token(SyntaxKind.BoolKeyword)))
                        .WithVariables(
                            SingletonSeparatedList(
                                VariableDeclarator(breakFlagName)
                                    .WithInitializer(
                                        EqualsValueClause(
                                            LiteralExpression(SyntaxKind.FalseLiteralExpression)
                                        )
                                    )
                            )
                        )
                )
            );

        currentForLoops.Push(new(expr, resultDestination, breakFlagName));
        try
        {
            statements.Add(
                TryEmitSpecializedForIn(expr, out var specialized)
                    ? specialized
                    : EmitIteratorForIn(expr)
            );
        }
        finally
        {
            currentForLoops.Pop();
        }

        EmitForInNoBreakAssignment(expr, resultDestination, breakFlagName, statements);
        return Block(statements);
    }

    private StatementSyntax EmitIteratorForIn(JsonElement expr)
    {
        var iterator = EmitExpr(expr.GetProperty("iterator"));
        var bodyStatements = new List<StatementSyntax>();
        EmitExprAsStatement(expr.GetProperty("body"), bodyStatements);
        var valueSymbols = ForInValueSymbols(expr);
        var iteratorName =
            "__mbt_for_in_iter" + tempNameIndex++.ToString(CultureInfo.InvariantCulture);
        var nextName = "__mbt_for_in_next" + tempNameIndex++.ToString(CultureInfo.InvariantCulture);
        var iteratorDeclaration = LocalDeclarationStatement(
            VariableDeclaration(EmitType(expr.GetProperty("iterator").GetProperty("type")))
                .WithVariables(
                    SingletonSeparatedList(
                        VariableDeclarator(iteratorName)
                            .WithInitializer(EqualsValueClause(iterator))
                    )
                )
        );
        var nextDeclaration = LocalDeclarationStatement(
            VariableDeclaration(IdentifierName("var"))
                .WithVariables(
                    SingletonSeparatedList(
                        VariableDeclarator(nextName)
                            .WithInitializer(EqualsValueClause(EmitForInNext(expr, iteratorName)))
                    )
                )
        );
        var exitIfDone = IfStatement(
            MemberAccessExpression(
                SyntaxKind.SimpleMemberAccessExpression,
                IdentifierName(nextName),
                IdentifierName("IsNone")
            ),
            Block(BreakStatement())
        );
        var loopStatements = new List<StatementSyntax> { nextDeclaration, exitIfDone };
        AddForInValueDeclarations(valueSymbols, ForInNextValueExpression(nextName), loopStatements);
        loopStatements.AddRange(bodyStatements);
        return Block(
            iteratorDeclaration,
            WhileStatement(
                LiteralExpression(SyntaxKind.TrueLiteralExpression),
                Block(loopStatements)
            )
        );
    }

    private static JsonElement[] ForInValueSymbols(JsonElement expr)
    {
        return expr.GetProperty("valueSymbols").EnumerateArray().ToArray();
    }

    private static bool ForInHasIndexValueSymbols(JsonElement expr)
    {
        return ForInValueSymbols(expr).Length == 2;
    }

    private static ExpressionSyntax ForInNextValueExpression(string nextName)
    {
        return MemberAccessExpression(
            SyntaxKind.SimpleMemberAccessExpression,
            IdentifierName(nextName),
            IdentifierName("Value")
        );
    }

    private void AddForInValueDeclarations(
        IReadOnlyList<JsonElement> valueSymbols,
        ExpressionSyntax valueExpression,
        List<StatementSyntax> statements
    )
    {
        if (valueSymbols.Count == 1)
        {
            AddForInValueDeclaration(valueSymbols[0], valueExpression, statements);
            return;
        }

        if (valueSymbols.Count == 2)
        {
            AddForInValueDeclaration(
                valueSymbols[0],
                MemberAccessExpression(
                    SyntaxKind.SimpleMemberAccessExpression,
                    valueExpression,
                    IdentifierName("Item1")
                ),
                statements
            );
            AddForInValueDeclaration(
                valueSymbols[1],
                MemberAccessExpression(
                    SyntaxKind.SimpleMemberAccessExpression,
                    valueExpression,
                    IdentifierName("Item2")
                ),
                statements
            );
        }
    }

    private void AddForInValueDeclaration(
        JsonElement symbol,
        ExpressionSyntax value,
        List<StatementSyntax> statements
    )
    {
        if (LocalIdentifier(symbol) == "_")
            return;

        statements.Add(
            LocalDeclarationStatement(
                VariableDeclaration(EmitType(symbol.GetProperty("type")))
                    .WithVariables(
                        SingletonSeparatedList(
                            VariableDeclarator(LocalIdentifier(symbol))
                                .WithInitializer(EqualsValueClause(value))
                        )
                    )
            )
        );
    }

    private void AddForInExistingIndexDeclaration(
        JsonElement symbol,
        ExpressionSyntax value,
        List<StatementSyntax> statements
    )
    {
        if (LocalIdentifier(symbol) == "_")
            return;

        statements.Add(
            LocalDeclarationStatement(
                VariableDeclaration(EmitType(symbol.GetProperty("type")))
                    .WithVariables(
                        SingletonSeparatedList(
                            VariableDeclarator(LocalIdentifier(symbol))
                                .WithInitializer(EqualsValueClause(value))
                        )
                    )
            )
        );
    }

    private static bool ForInHasNoBreak(JsonElement expr)
    {
        return expr.TryGetProperty("noBreak", out var noBreak)
            && noBreak.ValueKind != JsonValueKind.Null;
    }

    private void EmitForInNoBreakAssignment(
        JsonElement expr,
        string? resultDestination,
        string? breakFlagName,
        List<StatementSyntax> statements
    )
    {
        if (
            resultDestination is null
            || !expr.TryGetProperty("noBreak", out var noBreak)
            || noBreak.ValueKind == JsonValueKind.Null
        )
            return;

        var assignment = ExpressionStatement(
            AssignmentExpression(
                SyntaxKind.SimpleAssignmentExpression,
                IdentifierName(resultDestination),
                EmitExpr(noBreak)
            )
        );
        statements.Add(
            breakFlagName is null
                ? assignment
                : IfStatement(
                    PrefixUnaryExpression(
                        SyntaxKind.LogicalNotExpression,
                        IdentifierName(breakFlagName)
                    ),
                    Block(assignment)
                )
        );
    }

    private bool TryEmitSpecializedForIn(JsonElement expr, out StatementSyntax statement)
    {
        statement = EmptyStatement();
        if (!TryGetSpecializedForInSource(expr.GetProperty("iterator"), out var source))
            return false;

        statement = source.Kind switch
        {
            ForInSourceKind.ArrayLike or ForInSourceKind.BytesLike => EmitIndexedForIn(
                expr,
                source
            ),
            ForInSourceKind.StringLike => EmitStringForIn(expr, source),
            _ => EmptyStatement(),
        };
        return true;
    }

    private StatementSyntax EmitIndexedForIn(JsonElement expr, ForInSource source)
    {
        var sourceName =
            "__mbt_for_in_source" + tempNameIndex++.ToString(CultureInfo.InvariantCulture);
        var offsetName =
            "__mbt_for_in_offset" + tempNameIndex++.ToString(CultureInfo.InvariantCulture);
        var valueSymbols = ForInValueSymbols(expr);
        var bodyStatements = new List<StatementSyntax>();
        if (valueSymbols.Length == 2)
        {
            AddForInExistingIndexDeclaration(
                valueSymbols[0],
                IdentifierName(offsetName),
                bodyStatements
            );
            AddForInValueDeclaration(
                valueSymbols[1],
                ElementAccessExpression(IdentifierName(sourceName))
                    .WithArgumentList(
                        BracketedArgumentList(
                            SingletonSeparatedList(Argument(IdentifierName(offsetName)))
                        )
                    ),
                bodyStatements
            );
        }
        else if (valueSymbols.Length == 1)
        {
            AddForInValueDeclaration(
                valueSymbols[0],
                ElementAccessExpression(IdentifierName(sourceName))
                    .WithArgumentList(
                        BracketedArgumentList(
                            SingletonSeparatedList(Argument(IdentifierName(offsetName)))
                        )
                    ),
                bodyStatements
            );
        }

        EmitExprAsStatement(expr.GetProperty("body"), bodyStatements);

        var declarations = new List<StatementSyntax>
        {
            LocalDeclarationStatement(
                VariableDeclaration(EmitType(source.Expression.GetProperty("type")))
                    .WithVariables(
                        SingletonSeparatedList(
                            VariableDeclarator(sourceName)
                                .WithInitializer(EqualsValueClause(EmitExpr(source.Expression)))
                        )
                    )
            ),
        };
        declarations.Add(
            ForStatement(Block(bodyStatements))
                .WithDeclaration(
                    VariableDeclaration(PredefinedType(Token(SyntaxKind.IntKeyword)))
                        .WithVariables(
                            SingletonSeparatedList(
                                VariableDeclarator(offsetName)
                                    .WithInitializer(
                                        EqualsValueClause(
                                            LiteralExpression(
                                                SyntaxKind.NumericLiteralExpression,
                                                Literal(0)
                                            )
                                        )
                                    )
                            )
                        )
                )
                .WithCondition(
                    BinaryExpression(
                        SyntaxKind.LessThanExpression,
                        IdentifierName(offsetName),
                        MemberAccessExpression(
                            SyntaxKind.SimpleMemberAccessExpression,
                            IdentifierName(sourceName),
                            IdentifierName("Length")
                        )
                    )
                )
                .WithIncrementors(
                    SingletonSeparatedList<ExpressionSyntax>(
                        PostfixUnaryExpression(
                            SyntaxKind.PostIncrementExpression,
                            IdentifierName(offsetName)
                        )
                    )
                )
        );
        return Block(declarations);
    }

    private StatementSyntax EmitStringForIn(JsonElement expr, ForInSource source)
    {
        var sourceName =
            "__mbt_for_in_source" + tempNameIndex++.ToString(CultureInfo.InvariantCulture);
        var offsetName =
            "__mbt_for_in_offset" + tempNameIndex++.ToString(CultureInfo.InvariantCulture);
        var endName = "__mbt_for_in_end" + tempNameIndex++.ToString(CultureInfo.InvariantCulture);
        var charName = "__mbt_for_in_char" + tempNameIndex++.ToString(CultureInfo.InvariantCulture);
        var valueSymbols = ForInValueSymbols(expr);
        var sourceIsView = IsBuiltinType(source.Expression.GetProperty("type"), "StringView");
        ExpressionSyntax sourceData = sourceIsView
            ? MemberAccessExpression(
                SyntaxKind.SimpleMemberAccessExpression,
                IdentifierName(sourceName),
                IdentifierName("Data")
            )
            : IdentifierName(sourceName);
        ExpressionSyntax sourceStart = sourceIsView
            ? MemberAccessExpression(
                SyntaxKind.SimpleMemberAccessExpression,
                IdentifierName(sourceName),
                IdentifierName("Start")
            )
            : LiteralExpression(SyntaxKind.NumericLiteralExpression, Literal(0));
        var sourceEnd = sourceIsView
            ? MemberAccessExpression(
                SyntaxKind.SimpleMemberAccessExpression,
                IdentifierName(sourceName),
                IdentifierName("End")
            )
            : MemberAccessExpression(
                SyntaxKind.SimpleMemberAccessExpression,
                IdentifierName(sourceName),
                IdentifierName("Length")
            );
        var bodyStatements = new List<StatementSyntax>
        {
            LocalDeclarationStatement(
                VariableDeclaration(PredefinedType(Token(SyntaxKind.CharKeyword)))
                    .WithVariables(
                        SingletonSeparatedList(
                            VariableDeclarator(charName)
                                .WithInitializer(
                                    EqualsValueClause(
                                        ElementAccessExpression(sourceData)
                                            .WithArgumentList(
                                                BracketedArgumentList(
                                                    SingletonSeparatedList(
                                                        Argument(
                                                            PostfixUnaryExpression(
                                                                SyntaxKind.PostIncrementExpression,
                                                                IdentifierName(offsetName)
                                                            )
                                                        )
                                                    )
                                                )
                                            )
                                    )
                                )
                        )
                    )
            ),
        };
        var valueExpression = ConditionalExpression(
            ParenthesizedExpression(
                BinaryExpression(
                    SyntaxKind.LogicalAndExpression,
                    InvocationExpression(
                            MemberAccessExpression(
                                SyntaxKind.SimpleMemberAccessExpression,
                                IdentifierName("char"),
                                IdentifierName("IsHighSurrogate")
                            )
                        )
                        .WithArgumentList(
                            ArgumentList(SingletonSeparatedList(Argument(IdentifierName(charName))))
                        ),
                    BinaryExpression(
                        SyntaxKind.LessThanExpression,
                        IdentifierName(offsetName),
                        IdentifierName(endName)
                    )
                )
            ),
            InvocationExpression(
                    MemberAccessExpression(
                        SyntaxKind.SimpleMemberAccessExpression,
                        IdentifierName("char"),
                        IdentifierName("ConvertToUtf32")
                    )
                )
                .WithArgumentList(
                    ArgumentList(
                        SeparatedList([
                            Argument(IdentifierName(charName)),
                            Argument(
                                ElementAccessExpression(sourceData)
                                    .WithArgumentList(
                                        BracketedArgumentList(
                                            SingletonSeparatedList(
                                                Argument(
                                                    PostfixUnaryExpression(
                                                        SyntaxKind.PostIncrementExpression,
                                                        IdentifierName(offsetName)
                                                    )
                                                )
                                            )
                                        )
                                    )
                            ),
                        ])
                    )
                ),
            CastExpression(PredefinedType(Token(SyntaxKind.IntKeyword)), IdentifierName(charName))
        );
        if (valueSymbols.Length == 2)
        {
            AddForInExistingIndexDeclaration(
                valueSymbols[0],
                BinaryExpression(
                    SyntaxKind.SubtractExpression,
                    IdentifierName(offsetName),
                    LiteralExpression(SyntaxKind.NumericLiteralExpression, Literal(1))
                ),
                bodyStatements
            );
            AddForInValueDeclaration(valueSymbols[1], valueExpression, bodyStatements);
        }
        else if (valueSymbols.Length == 1)
        {
            AddForInValueDeclaration(valueSymbols[0], valueExpression, bodyStatements);
        }

        EmitExprAsStatement(expr.GetProperty("body"), bodyStatements);

        var declarations = new List<StatementSyntax>
        {
            LocalDeclarationStatement(
                VariableDeclaration(EmitType(source.Expression.GetProperty("type")))
                    .WithVariables(
                        SingletonSeparatedList(
                            VariableDeclarator(sourceName)
                                .WithInitializer(EqualsValueClause(EmitExpr(source.Expression)))
                        )
                    )
            ),
            LocalDeclarationStatement(
                VariableDeclaration(PredefinedType(Token(SyntaxKind.IntKeyword)))
                    .WithVariables(
                        SingletonSeparatedList(
                            VariableDeclarator(endName)
                                .WithInitializer(EqualsValueClause(sourceEnd))
                        )
                    )
            ),
        };
        declarations.Add(
            ForStatement(Block(bodyStatements))
                .WithDeclaration(
                    VariableDeclaration(PredefinedType(Token(SyntaxKind.IntKeyword)))
                        .WithVariables(
                            SingletonSeparatedList(
                                VariableDeclarator(offsetName)
                                    .WithInitializer(EqualsValueClause(sourceStart))
                            )
                        )
                )
                .WithCondition(
                    BinaryExpression(
                        SyntaxKind.LessThanExpression,
                        IdentifierName(offsetName),
                        IdentifierName(endName)
                    )
                )
        );
        return Block(declarations);
    }

    private void AddForInIndexDeclaration(JsonElement expr, List<StatementSyntax> statements)
    {
        var indexSymbol = expr.GetProperty("indexSymbol");
        if (indexSymbol.ValueKind == JsonValueKind.Null)
            return;

        statements.Add(
            LocalDeclarationStatement(
                VariableDeclaration(PredefinedType(Token(SyntaxKind.IntKeyword)))
                    .WithVariables(
                        SingletonSeparatedList(
                            VariableDeclarator(LocalIdentifier(indexSymbol))
                                .WithInitializer(
                                    EqualsValueClause(
                                        LiteralExpression(
                                            SyntaxKind.NumericLiteralExpression,
                                            Literal(0)
                                        )
                                    )
                                )
                        )
                    )
            )
        );
    }

