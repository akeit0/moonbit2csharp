    private string QualifiedTypeDefinitionName(JsonElement symbol)
    {
        var symbolId = symbol.GetProperty("id").GetString() ?? "";
        return QualifyPackageTypeName(symbolId, TypeDefinitionName(symbol));
    }

    private string FunctionMethodName(string functionId, string fallbackName)
    {
        return functionNames.TryGetValue(functionId, out var name)
            ? name
            : ToPublicIdentifier(UnqualifiedMoonBitFunctionName(fallbackName));
    }

    private string FunctionMethodName(string functionId)
    {
        return functionNames.TryGetValue(functionId, out var name)
            ? name
            : ToPublicIdentifier(UnqualifiedMoonBitFunctionName(FunctionName(functionId)));
    }

    private static string FunctionName(string functionId)
    {
        var index = functionId.LastIndexOf(':');
        return index < 0 ? functionId : functionId[(index + 1)..];
    }

    private static string UnqualifiedMoonBitFunctionName(string name)
    {
        var receiverSeparator = name.LastIndexOf("::", StringComparison.Ordinal);
        return receiverSeparator < 0 ? name : name[(receiverSeparator + 2)..];
    }

    private static string StableIdentifierSuffix(string value)
    {
        const uint offset = 2166136261;
        const uint prime = 16777619;
        var hash = offset;
        foreach (var ch in value)
        {
            hash ^= ch;
            hash *= prime;
        }

        return hash.ToString("x8", CultureInfo.InvariantCulture);
    }

    private static string SafeIdentifier(string name)
    {
        if (string.IsNullOrWhiteSpace(name))
            return "_";

        var chars = name.Select(
                (ch, index) =>
                    index == 0
                        ? char.IsLetter(ch) || ch == '_'
                            ? ch
                            : '_'
                        : char.IsLetterOrDigit(ch) || ch == '_'
                            ? ch
                            : '_'
            )
            .ToArray();
        var result = new string(chars);
        return SyntaxFacts.GetKeywordKind(result) == SyntaxKind.None ? result : "@" + result;
    }

    private static string ToUpperPascalCase(string name)
    {
        var result = new StringBuilder();
        var capitalize = true;
        foreach (var ch in name)
        {
            if (ch is '_' or '-' or ' ' or '.' or '/' or ':')
            {
                capitalize = true;
                continue;
            }

            result.Append(capitalize ? char.ToUpperInvariant(ch) : ch);
            capitalize = false;
        }

        return result.Length == 0 ? name : result.ToString();
    }

