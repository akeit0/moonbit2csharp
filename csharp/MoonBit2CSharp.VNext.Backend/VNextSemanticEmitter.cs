    private string TraitDispatcherMethod(string traitName, JsonElement method)
    {
        var name = ToTraitMethodIdentifier(method.GetProperty("name").GetString() ?? "");
        return $"public static {TraitMethodType(method.GetProperty("returnType"), "T")} {name}<T, TImpl>({TraitInstanceMethodParameters(method)}) where TImpl : {TraitImplInterfaceName(traitName)}<T, TImpl> => TImpl.{name}({TraitMethodArgumentList(method)});";
    }

    private string TraitGenericInterfaceMethod(string traitName, JsonElement method)
    {
        var returnType = TraitMethodType(method.GetProperty("returnType"), "T");
        var name = ToTraitMethodIdentifier(method.GetProperty("name").GetString() ?? "");
        var parameters = TraitInstanceMethodParameters(method);
        if (TraitMethodHasDefault(method))
        {
            if (TryGetTraitMethodDefaultFunctionId(method, out var defaultFunctionId))
            {
                var defaultBody = EmitTraitDefaultMethodBodyInline(traitName, defaultFunctionId);
                return defaultBody.StartsWith("{", StringComparison.Ordinal)
                    ? $"static virtual {returnType} {name}({parameters}) {defaultBody}"
                    : $"static virtual {returnType} {name}({parameters}) => {defaultBody};";
            }

            var fallbackBody = TraitDefaultInterfaceMethodBody(traitName, method);
            return fallbackBody.StartsWith("{", StringComparison.Ordinal)
                ? $"static virtual {returnType} {name}({parameters}) {fallbackBody}"
                : $"static virtual {returnType} {name}({parameters}) => {fallbackBody};";
        }

        return $"static abstract {returnType} {name}({parameters});";
    }

    private static bool TryGetTraitMethodDefaultFunctionId(
        JsonElement method,
        out string defaultFunctionId
    )
    {
        if (
            method.TryGetProperty("defaultFunctionId", out var camel)
            && camel.ValueKind == JsonValueKind.String
        )
        {
            defaultFunctionId = camel.GetString() ?? "";
            return defaultFunctionId.Length > 0;
        }

        if (
            method.TryGetProperty("default_function_id", out var snake)
            && snake.ValueKind == JsonValueKind.String
        )
        {
            defaultFunctionId = snake.GetString() ?? "";
            return defaultFunctionId.Length > 0;
        }

        defaultFunctionId = "";
        return false;
    }

    private string EmitTraitDefaultMethodBodyInline(string traitName, string defaultFunctionId)
    {
        if (!functionsBySymbolId.TryGetValue(defaultFunctionId, out var function))
            throw new InvalidOperationException(
                "VNXB001: unresolved default trait function in executable IR: " + defaultFunctionId
            );

        var previousTraitDefaultInlineTraitName = currentTraitDefaultInlineTraitName;
        var previousFunctionRaises = currentFunctionRaises;
        var previousFunctionErrorType = currentFunctionErrorType;
        currentTraitDefaultInlineTraitName = traitName;
        currentFunctionRaises = TryGetRaisingEffect(function, out var functionErrorType);
        currentFunctionErrorType = functionErrorType;
        try
        {
            return FormatTraitDefaultMethodBody(EmitFunctionBody(function.GetProperty("body")));
        }
        finally
        {
            currentTraitDefaultInlineTraitName = previousTraitDefaultInlineTraitName;
            currentFunctionRaises = previousFunctionRaises;
            currentFunctionErrorType = previousFunctionErrorType;
        }
    }

    private static string FormatTraitDefaultMethodBody(BlockSyntax body)
    {
        if (
            body.Statements.Count == 1
            && body.Statements[0] is ReturnStatementSyntax returnStatement
            && returnStatement.Expression is not null
        )
            return returnStatement.Expression.NormalizeWhitespace().ToFullString();

        return body.NormalizeWhitespace().ToFullString();
    }

    private string TraitDefaultImplTypeParam(string traitName, string implTypeParam)
    {
        if (currentTraitDefaultInlineTraitName is null)
            return implTypeParam;

        return implTypeParam == StaticTraitImplTypeParameterName("T", traitName)
            ? "TImpl"
            : implTypeParam;
    }

