    private static string PackageNameFromSymbolId(string symbolId)
    {
        var parts = PackageSymbolParts(symbolId);
        return parts.PackageName;
    }

    private static string ModuleNameFromSymbolId(string symbolId)
    {
        var parts = PackageSymbolParts(symbolId);
        return parts.ModuleName;
    }

    private static (string PackageName, string ModuleName) PackageSymbolParts(string symbolId)
    {
        const string packagePrefix = "pkg:";
        var packageStart = symbolId.IndexOf(packagePrefix, StringComparison.Ordinal);
        if (packageStart < 0)
            return ("", "");

        var valueStart = packageStart + packagePrefix.Length;
        var nameStart = symbolId.LastIndexOf(':');
        if (nameStart <= valueStart)
            return ("", "");

        var packageAndModule = symbolId[valueStart..nameStart];
        var split = packageAndModule.IndexOf(':');
        if (split < 0)
            return (packageAndModule, packageAndModule);

        return (packageAndModule[..split], packageAndModule[(split + 1)..]);
    }

    private static string LastPathSegment(string name)
    {
        var index = name.LastIndexOf('/');
        return index < 0 ? name : name[(index + 1)..];
    }

    private void BuildTypeNameMap(JsonElement root)
    {
        var types = EnumerateOptionalArray(root, "types").ToArray();
        var displayNameCounts = types
            .Select(type =>
                TypeDefinitionPackageName(type)
                + ":"
                + ToPublicIdentifier(
                    type.GetProperty("symbol").GetProperty("name").GetString() ?? ""
                )
            )
            .GroupBy(name => name, StringComparer.Ordinal)
            .ToDictionary(group => group.Key, group => group.Count(), StringComparer.Ordinal);
        var usedNames = new Dictionary<string, HashSet<string>>(StringComparer.Ordinal);
        foreach (var type in types)
        {
            var symbol = type.GetProperty("symbol");
            var symbolId = symbol.GetProperty("id").GetString() ?? "";
            if (symbolId.Length == 0)
                continue;

            var displayName = ToPublicIdentifier(
                symbol.GetProperty("name").GetString() ?? symbolId
            );
            var packageName = TypeDefinitionPackageName(type);
            var displayKey = packageName + ":" + displayName;
            var typeName =
                displayNameCounts[displayKey] == 1
                    ? displayName
                    : ToPublicIdentifier(displayName + "__" + StableIdentifierSuffix(symbolId));
            if (!usedNames.TryGetValue(packageName, out var packageUsedNames))
            {
                packageUsedNames = new(StringComparer.Ordinal);
                usedNames[packageName] = packageUsedNames;
            }

            if (!packageUsedNames.Add(typeName))
            {
                typeName = ToPublicIdentifier(typeName + "__" + StableIdentifierSuffix(symbolId));
                packageUsedNames.Add(typeName);
            }

            typeNames[symbolId] = typeName;
        }
    }

    private void BuildTraitNameMap(JsonElement root)
    {
        foreach (
            var group in EnumerateOptionalArray(root, "traits")
                .Select(trait => trait.GetProperty("symbol"))
                .Select(symbol => new
                {
                    Name = ToPublicIdentifier(symbol.GetProperty("name").GetString() ?? ""),
                    Id = symbol.GetProperty("id").GetString() ?? "",
                })
                .Where(symbol => symbol.Name.Length > 0 && symbol.Id.Length > 0)
                .GroupBy(symbol => symbol.Name, StringComparer.Ordinal)
        )
            traitSymbolIdsByName[group.Key] = group
                .Select(symbol => symbol.Id)
                .Distinct(StringComparer.Ordinal)
                .ToArray();
    }

