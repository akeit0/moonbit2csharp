    private ExpressionSyntax EmitEnumCase(JsonElement expr)
    {
        var typeId = expr.GetProperty("typeId").GetString() ?? "";
        if (!typeDefinitions.TryGetValue(typeId, out var typeDefinition))
            throw new NotSupportedException($"vnext enum case type is not declared: {typeId}");

        var typeName = EmitType(expr.GetProperty("type")).NormalizeWhitespace().ToFullString();
        var variantName = EnumVariantMemberName(
            typeName,
            expr.GetProperty("name").GetString() ?? ""
        );
        var args = expr.GetProperty("args").EnumerateArray().ToArray();
        if (IsAllConstantEnum(typeDefinition) || args.Length == 0)
            return MemberAccessExpression(
                SyntaxKind.SimpleMemberAccessExpression,
                IdentifierName(typeName),
                IdentifierName(variantName)
            );

        return InvocationExpression(
            MemberAccessExpression(
                SyntaxKind.SimpleMemberAccessExpression,
                IdentifierName(typeName),
                IdentifierName(variantName)
            ),
            ArgumentList(SeparatedList(args.Select(arg => Argument(EmitExpr(arg)))))
        );
    }

    private static bool IsAllConstantEnum(JsonElement typeDefinition)
    {
        if (typeDefinition.TryGetProperty("kind", out var kind) && kind.GetString() != "Enum")
            return false;

        return typeDefinition
            .GetProperty("variants")
            .EnumerateArray()
            .All(variant => variant.GetProperty("payloads").GetArrayLength() == 0);
    }

    private string EnumVariantMemberName(string containingTypeName, string sourceVariantName)
    {
        var variantName = ToPublicIdentifier(sourceVariantName);
        var typeName = containingTypeName;
        var genericStart = typeName.IndexOf('<', StringComparison.Ordinal);
        if (genericStart >= 0)
            typeName = typeName[..genericStart];
        var qualifierStart = typeName.LastIndexOf('.');
        if (qualifierStart >= 0)
            typeName = typeName[(qualifierStart + 1)..];

        return string.Equals(variantName, typeName, StringComparison.Ordinal)
            ? variantName + "Case"
            : variantName;
    }

    private bool TryEnumErrorNameExpression(
        JsonElement type,
        string valueExpression,
        out ExpressionSyntax displayName
    )
    {
        displayName = LiteralExpression(SyntaxKind.StringLiteralExpression, Literal(""));
        if (
            type.GetProperty("kind").GetString() != "Declared"
            || !type.TryGetProperty("symbol", out var symbol)
        )
            return false;

        var typeId = symbol.GetProperty("id").GetString() ?? "";
        if (
            !typeDefinitions.TryGetValue(typeId, out var typeDefinition)
            || typeDefinition.GetProperty("kind").GetString() != "Enum"
            || typeDefinition.GetProperty("typeParams").GetArrayLength() != 0
        )
            return false;

        var typeName = TypeDefinitionName(symbol);
        var typeDisplayName = MoonBitTypeDisplayNameFromSymbol(symbol);
        var variants = typeDefinition.GetProperty("variants").EnumerateArray().ToArray();
        var allConstant = variants.All(variant =>
            variant.GetProperty("payloads").GetArrayLength() == 0
        );
        var variantsRoundTrip = variants.All(variant =>
        {
            var sourceName = variant.GetProperty("name").GetString() ?? "";
            return string.Equals(
                ToPublicIdentifier(sourceName),
                EnumVariantMemberName(typeName, sourceName),
                StringComparison.Ordinal
            );
        });
        if (variantsRoundTrip)
        {
            var enumValueExpression = allConstant ? valueExpression : valueExpression + ".Kind";
            displayName = ParseExpression(
                $"{Literal(typeDisplayName + ".").NormalizeWhitespace()} + {enumValueExpression}.ToString()"
            );
            return true;
        }

        var switchTarget = allConstant ? valueExpression : valueExpression + ".Kind";
        var variantCases = variants.Select(variant =>
        {
            var sourceName = variant.GetProperty("name").GetString() ?? "";
            var variantName = EnumVariantMemberName(typeName, sourceName);
            var pattern = allConstant
                ? $"{typeName}.{variantName}"
                : $"{typeName}.Tag.{variantName}";
            return $"{pattern} => {Literal(typeDisplayName + "." + sourceName).NormalizeWhitespace()}";
        });
        displayName = ParseExpression(
            $$"""
            {{switchTarget}} switch
            {
                {{string.Join("," + Environment.NewLine + "    ", variantCases)}},
                _ => {{Literal(typeDisplayName).NormalizeWhitespace()}}
            }
            """
        );
        return true;
    }

