                    .Range(0, Math.Max(0, method.GetProperty("parameters").GetArrayLength() - 1))
                    .Select(i => $"arg{i}")
            )
        );
    }

    private string TraitObjectAdapterMethod(JsonElement method)
    {
        var name = ToTraitMethodIdentifier(method.GetProperty("name").GetString() ?? "");
        var arguments = string.Join(
            ", ",
            new[] { "(T)self" }.Concat(
                method
                    .GetProperty("parameters")
                    .EnumerateArray()
                    .Skip(1)
                    .Select((type, i) => $"({TraitMethodType(type, "T")})arg{i}")
            )
        );
        var resultNullability =
            TraitMethodType(method.GetProperty("returnType"), "object") == "object" ? "!" : "";
        return $"public {TraitMethodType(method.GetProperty("returnType"), "object")} {name}({TraitObjectMethodParameters(method)}) => TImpl.{name}({arguments}){resultNullability};";
    }

