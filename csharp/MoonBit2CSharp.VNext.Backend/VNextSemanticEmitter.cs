    private void BuildLocalNameCollisionMap(JsonElement function)
    {
        localSymbolIdsRequiringSuffix.Clear();
        var parameterNames = new HashSet<string>(StringComparer.Ordinal);
        var localDefinitionsByName = new Dictionary<string, List<string>>(StringComparer.Ordinal);
        var patternDefinitionsByName = new Dictionary<string, List<string>>(StringComparer.Ordinal);
        foreach (var param in function.GetProperty("params").EnumerateArray())
        {
            var name = param.TryGetProperty("name", out var nameElement)
                ? nameElement.GetString() ?? ""
                : "";
            if (name.Length != 0 && name != "_")
                parameterNames.Add(name);
        }

        CollectLocalDefinitions(
            function.GetProperty("body"),
            localDefinitionsByName,
            patternDefinitionsByName
        );
        foreach (var (name, ids) in localDefinitionsByName)
        {
            if (
                parameterNames.Contains(name)
                || ids.Count > 1
                || patternDefinitionsByName.ContainsKey(name)
            )
                foreach (var id in ids)
                    localSymbolIdsRequiringSuffix.Add(id);

            if (patternDefinitionsByName.TryGetValue(name, out var patternIds))
                foreach (var id in patternIds)
                    localSymbolIdsRequiringSuffix.Add(id);
        }

        foreach (var (name, ids) in patternDefinitionsByName)
        {
            if (
                ids.Count <= 1
                && !parameterNames.Contains(name)
                && !localDefinitionsByName.ContainsKey(name)
            )
                continue;
            foreach (var id in ids)
                localSymbolIdsRequiringSuffix.Add(id);
        }
    }

    private static void CollectLocalDefinitions(
        JsonElement value,
        Dictionary<string, List<string>> idsByName,
        Dictionary<string, List<string>> patternIdsByName
    )
    {
        if (value.ValueKind == JsonValueKind.Object)
        {
            TryCollectDefinitionSymbol(value, "local", idsByName);
            TryCollectDefinitionSymbols(value, "bindings", idsByName);
            TryCollectDefinitionSymbols(value, "valueSymbols", idsByName);
            if (
                value.TryGetProperty("kind", out var kindElement)
                && kindElement.ValueKind == JsonValueKind.String
                && kindElement.GetString() == "ForRange"
            )
                TryCollectLocalSymbol(value, idsByName);
            foreach (var property in value.EnumerateObject())
            {
                if (property.NameEquals("pattern"))
                {
                    CollectPatternDefinitions(property.Value, patternIdsByName);
                    continue;
                }

                CollectLocalDefinitions(property.Value, idsByName, patternIdsByName);
            }

            return;
        }

        if (value.ValueKind == JsonValueKind.Array)
            foreach (var item in value.EnumerateArray())
                CollectLocalDefinitions(item, idsByName, patternIdsByName);
    }

    private static void TryCollectDefinitionSymbol(
        JsonElement value,
        string propertyName,
        Dictionary<string, List<string>> idsByName
    )
    {
        if (
            value.TryGetProperty(propertyName, out var symbol)
            && symbol.ValueKind != JsonValueKind.Null
        )
            TryCollectLocalSymbol(symbol, idsByName);
    }

    private static void TryCollectDefinitionSymbols(
        JsonElement value,
        string propertyName,
        Dictionary<string, List<string>> idsByName
    )
    {
        if (
            !value.TryGetProperty(propertyName, out var symbols)
            || symbols.ValueKind != JsonValueKind.Array
        )
            return;

        foreach (var symbol in symbols.EnumerateArray())
            TryCollectLocalSymbol(symbol, idsByName);
    }

    private static void CollectPatternDefinitions(
        JsonElement value,
        Dictionary<string, List<string>> idsByName
    )
    {
        if (value.ValueKind == JsonValueKind.Object)
        {
            if (
                value.TryGetProperty("kind", out var kindElement)
                && kindElement.ValueKind == JsonValueKind.String
                && kindElement.GetString() == "Binding"
                && value.TryGetProperty("symbol", out var symbol)
            )
                TryCollectNamedSymbol(symbol, idsByName);
            if (
                value.TryGetProperty("rest", out var rest)
                && rest.ValueKind == JsonValueKind.Object
                && rest.TryGetProperty("symbol", out var restSymbol)
                && restSymbol.ValueKind == JsonValueKind.Object
            )
                TryCollectNamedSymbol(restSymbol, idsByName);

            foreach (var property in value.EnumerateObject())
                CollectPatternDefinitions(property.Value, idsByName);
            return;
        }

        if (value.ValueKind == JsonValueKind.Array)
            foreach (var item in value.EnumerateArray())
                CollectPatternDefinitions(item, idsByName);
    }

    private static void TryCollectLocalSymbol(
        JsonElement value,
        Dictionary<string, List<string>> idsByName
    )
    {
        var symbolId =
            value.TryGetProperty("symbolId", out var symbolIdElement)
                ? symbolIdElement.GetString() ?? ""
            : value.TryGetProperty("id", out var idElement) ? idElement.GetString() ?? ""
            : "";
        if (!symbolId.StartsWith("local:", StringComparison.Ordinal))
            return;
        TryCollectNamedSymbol(value, idsByName);
    }

    private static void TryCollectNamedSymbol(
        JsonElement value,
        Dictionary<string, List<string>> idsByName
    )
    {
        var symbolId =
            value.TryGetProperty("symbolId", out var symbolIdElement)
                ? symbolIdElement.GetString() ?? ""
            : value.TryGetProperty("id", out var idElement) ? idElement.GetString() ?? ""
            : "";
        var name = value.TryGetProperty("name", out var nameElement)
            ? nameElement.GetString() ?? ""
            : "";
        if (symbolId.Length == 0 || name.Length == 0)
            return;
        if (!idsByName.TryGetValue(name, out var ids))
        {
            ids = [];
            idsByName[name] = ids;
        }

        if (!ids.Contains(symbolId, StringComparer.Ordinal))
            ids.Add(symbolId);
    }

    private string LocalIdentifier(JsonElement symbol)
    {
        var name = symbol.TryGetProperty("name", out var nameElement)
            ? nameElement.GetString() ?? ""
            : "";
        var symbolId =
            symbol.TryGetProperty("symbolId", out var directSymbolId)
                ? directSymbolId.GetString() ?? ""
            : symbol.TryGetProperty("id", out var idElement) ? idElement.GetString() ?? ""
            : "";
        return LocalIdentifier(name, symbolId);
    }

    private string LocalIdentifier(string name, string symbolId)
    {
        var identifier = ToLocalIdentifier(name);
        if (!localSymbolIdsRequiringSuffix.Contains(symbolId))
            return identifier;

        return identifier + "__" + StableIdentifierSuffix(symbolId);
    }

    private void BuildFunctionNameMap(JsonElement root, string moduleName)
    {
        var functions = root.GetProperty("functions").EnumerateArray().ToArray();
        var displayNameCounts = functions
            .Select(function =>
                FunctionContainerName(function, moduleName) + ":" + FunctionDisplayName(function)
            )
            .GroupBy(name => name, StringComparer.Ordinal)
            .ToDictionary(group => group.Key, group => group.Count(), StringComparer.Ordinal);
        var usedNames = new Dictionary<string, HashSet<string>>(StringComparer.Ordinal);
        foreach (var function in functions)
        {
            var symbolId = function.GetProperty("symbolId").GetString() ?? "";
            if (symbolId.Length == 0)
                continue;

            var displayName = FunctionDisplayName(function);
            var containerName = FunctionContainerName(function, moduleName);
            var displayKey = containerName + ":" + displayName;
            var methodName =
                displayNameCounts[displayKey] == 1
                    ? displayName
                    : ToPublicIdentifier(displayName + "__" + StableIdentifierSuffix(symbolId));
            if (!usedNames.TryGetValue(containerName, out var containerUsedNames))
            {
                containerUsedNames = new(StringComparer.Ordinal);
                usedNames[containerName] = containerUsedNames;
            }

            if (!containerUsedNames.Add(methodName))
            {
                methodName = ToPublicIdentifier(
                    methodName + "__" + StableIdentifierSuffix(symbolId)
                );
                containerUsedNames.Add(methodName);
            }

            if (string.Equals(containerName, methodName, StringComparison.Ordinal))
                containerName = ToPublicIdentifier(containerName + "_module");

            functionNames[symbolId] = methodName;
            functionContainers[symbolId] = containerName;
            functionsBySymbolId[symbolId] = function;
            RememberStaticTraitImplAdapter(function, symbolId, containerName);
            functionTypeParams[symbolId] = function.TryGetProperty("typeParams", out var typeParams)
                ? ReadTypeParamInfos(typeParams)
                : [];
            if (function.TryGetProperty("effect", out var effect))
                functionEffects[symbolId] = effect;
        }
    }

    private string FunctionDisplayName(JsonElement function)
    {
        var name = UnqualifiedMoonBitFunctionName(function.GetProperty("name").GetString() ?? "");
        return TryReadTraitImplSymbol(function) is null
            ? ToPublicIdentifier(name)
            : ToTraitMethodIdentifier(name);
    }

    private void RememberStaticTraitImplAdapter(
        JsonElement function,
        string symbolId,
        string containerName
    )
    {
        var impl = TryReadTraitImplSymbol(function);
        if (impl is null || function.GetProperty("params").GetArrayLength() == 0)
            return;

        var selfType = function.GetProperty("params")[0].GetProperty("type");
        var key = StaticTraitImplAdapterKey(impl.Value.TraitName, selfType);
        if (ContainsTypeParameter(selfType))
        {
            RememberGenericStaticTraitImplAdapter(
                key,
                impl.Value,
                selfType,
                symbolId,
                containerName,
                function
            );
            return;
        }

        staticTraitImplAdapterTypes[key] = QualifyPackageTypeName(symbolId, containerName);
    }

    private void RememberGenericStaticTraitImplAdapter(
        string key,
        TraitImplSymbol impl,
        JsonElement selfType,
        string symbolId,
        string containerName,
        JsonElement function
    )
    {
        if (!genericStaticTraitImplAdapters.TryGetValue(key, out var adapter))
        {
            adapter = new(
                impl.TraitSymbolId,
                impl.TraitName,
                selfType,
                symbolId,
                containerName,
                GenericStaticTraitImplAdapterTypeName(impl.TraitName, selfType),
                function.TryGetProperty("typeParams", out var typeParams)
                    ? ReadTypeParamInfos(typeParams)
                    : []
            );
            genericStaticTraitImplAdapters[key] = adapter;
        }

        adapter.FunctionSymbolIds.Add(symbolId);
    }

    private string GenericStaticTraitImplAdapterTypeName(string traitName, JsonElement selfType)
    {
        var kind = selfType.GetProperty("kind").GetString() ?? "";
        var receiverName = kind switch
        {
            "Declared" when selfType.TryGetProperty("symbol", out var symbol) => TypeDefinitionName(
                symbol
            ),
            "Builtin" => selfType.GetProperty("name").GetString() ?? "Value",
            _ => "Value",
        };
        return ToPublicIdentifier(receiverName + traitName + "Impl");
    }

    private ExpressionSyntax FunctionMemberAccess(string functionId)
    {
        return FunctionMemberAccess(functionId, []);
    }

    private ExpressionSyntax FunctionMemberAccess(
        string functionId,
        IReadOnlyList<JsonElement> typeArgs
    )
    {
        var methodName = FunctionMethodName(functionId);
        var emittedTypeArgs = typeArgs
            .Select(arg => EmitType(arg).NormalizeWhitespace().ToFullString())
            .ToList();
        if (functionTypeParams.TryGetValue(functionId, out var calleeTypeParams))
            for (var i = 0; i < calleeTypeParams.Length && i < emittedTypeArgs.Count; i++)
                foreach (var trait in calleeTypeParams[i].Constraints)
                    emittedTypeArgs.Add(TraitEvidenceTypeArgument(typeArgs[i], trait));

        var memberName =
            emittedTypeArgs.Count == 0
                ? methodName
                : methodName + "<" + string.Join(", ", emittedTypeArgs) + ">";
        if (!functionContainers.TryGetValue(functionId, out var containerName))
            throw new InvalidOperationException(
                "VNXB001: unresolved function target in executable IR: " + functionId
            );

        var packageName = PackageNameFromSymbolId(functionId);
        var container =
            packageName.Length > 0 && packageName != currentPackageName
                ? "global::" + PackageNamespace(packageName) + "." + containerName
                : containerName;
        return ParseExpression(container + "." + memberName);
    }

    private ExpressionSyntax EmitRaise(JsonElement expr)
    {
        var typeName = EmitType(expr.GetProperty("type")).NormalizeWhitespace().ToFullString();
        var value = EmitRaisedErrorValue(expr).NormalizeWhitespace().ToFullString();
        return ParseExpression(
            $"MoonBitResult<{typeName}, {currentFunctionErrorType}>.Err({value})"
        );
    }

    private ExpressionSyntax EmitRaisedErrorValue(JsonElement raise)
    {
        var value = raise.GetProperty("value");
        var emitted = EmitExpr(value);
        if (currentFunctionErrorType != "MoonBitError")
            return emitted;

        var valueType = value.GetProperty("type");
        if (IsBuiltinType(valueType, "Error"))
            return emitted;

        var emittedText = emitted.NormalizeWhitespace().ToFullString();
        var displayName = MoonBitErrorDisplayName(value);
        if (
            raise.TryGetProperty("showObject", out var showObject)
            && showObject.ValueKind == JsonValueKind.Object
        )
        {
            var showType = showObject.GetProperty("type");
            var traitSymbol = showType.GetProperty("trait").GetProperty("symbol");
            var traitName = ToPublicIdentifier(traitSymbol.GetProperty("name").GetString() ?? "");
            var implObjectType = QualifyPackageTypeName(
                traitSymbol.GetProperty("id").GetString() ?? "",
                traitName + "ImplObject"
            );
            var valueTypeName = EmitType(valueType).NormalizeWhitespace().ToFullString();
            var implType = TraitEvidenceTypeArgument(valueType, traitName);
            return ParseExpression(
                $"MoonBitError.FromObject({emittedText}, {Literal(displayName)}, {implObjectType}<{valueTypeName}, {implType}>.Instance)"
            );
        }

        return ParseExpression($"MoonBitError.FromObject({emittedText}, {Literal(displayName)})");
    }

