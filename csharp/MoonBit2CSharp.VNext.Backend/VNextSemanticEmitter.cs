    private ExpressionSyntax EmitTraitMethodCall(JsonElement expr)
    {
        var receiver = EmitExpr(expr.GetProperty("receiver"));
        var methodName = ToTraitMethodIdentifier(expr.GetProperty("name").GetString() ?? "");
        var args = expr.GetProperty("args").EnumerateArray().Select(EmitExpr).ToArray();
        var dispatch = expr.GetProperty("dispatch");
        var dispatchKind = dispatch.GetProperty("kind").GetString();
        switch (dispatchKind)
        {
            case "TraitObject":
                return InvocationExpression(
                    MemberAccessExpression(
                        SyntaxKind.SimpleMemberAccessExpression,
                        MemberAccessExpression(
                            SyntaxKind.SimpleMemberAccessExpression,
                            receiver,
                            IdentifierName("Impl")
                        ),
                        IdentifierName(methodName)
                    ),
                    ArgumentList(
                        SeparatedList(
                            new[]
                            {
                                Argument(
                                    MemberAccessExpression(
                                        SyntaxKind.SimpleMemberAccessExpression,
                                        receiver,
                                        IdentifierName("Self")
                                    )
                                ),
                            }.Concat(args.Select(Argument))
                        )
                    )
                );
            case "TypeParamBound":
            {
                var traitName =
                    expr.GetProperty("trait").GetProperty("symbol").GetProperty("name").GetString()
                    ?? "";
                var traitSymbol = expr.GetProperty("trait").GetProperty("symbol");
                var traitPublicName = ToPublicIdentifier(traitName);
                var implTypeParam = dispatch.GetProperty("implTypeParam").GetString() ?? "";
                implTypeParam = TraitDefaultImplTypeParam(traitPublicName, implTypeParam);
                var receiverType = expr.GetProperty("receiver").GetProperty("type");
                var receiverTypeName = EmitType(receiverType).NormalizeWhitespace().ToFullString();
                return InvocationExpression(
                    MemberAccessExpression(
                        SyntaxKind.SimpleMemberAccessExpression,
                        ParseName(
                            QualifyPackageTypeName(
                                traitSymbol.GetProperty("id").GetString() ?? "",
                                TraitDispatcherTypeName(ToPublicIdentifier(traitName))
                            )
                        ),
                        GenericName(methodName)
                            .WithTypeArgumentList(
                                TypeArgumentList(
                                    SeparatedList([
                                        ParseTypeName(receiverTypeName),
                                        IdentifierName(SafeIdentifier(implTypeParam)),
                                    ])
                                )
                            )
                    ),
                    ArgumentList(
                        SeparatedList(new[] { Argument(receiver) }.Concat(args.Select(Argument)))
                    )
                );
            }

            case "ConcreteImpl":
            {
                var allArguments = new[] { Argument(receiver) }
                    .Concat(args.Select(Argument))
                    .ToArray();
                if (IsDerivedDebugTraitDispatch(expr, dispatch))
                    return EmitDebugImplReprCall(
                        receiver,
                        expr.GetProperty("receiver").GetProperty("type")
                    );

                if (dispatch.TryGetProperty("selectedIntrinsic", out var intrinsic))
                    if (intrinsic.ValueKind == JsonValueKind.String)
                    {
                        var intrinsicName = intrinsic.GetString() ?? "";
                        if (
                            IntrinsicBindings.TryEmit(
                                intrinsicName,
                                allArguments,
                                EmitType(expr.GetProperty("type")),
                                out var intrinsicExpr
                            )
                        )
                            return QualifySupportExpression(intrinsicExpr);

                        throw new NotSupportedException(
                            $"vnext concrete trait intrinsic is not supported: {intrinsicName}"
                        );
                    }

                var functionId = dispatch.GetProperty("functionId").GetString() ?? "";
                return InvocationExpression(
                    FunctionMemberAccess(
                        functionId,
                        TypeArgumentsForConcreteTraitImpl(
                            expr.GetProperty("receiver").GetProperty("type")
                        )
                    ),
                    ArgumentList(SeparatedList(allArguments))
                );
            }

            default:
                throw new NotSupportedException(
                    $"vnext trait dispatch is not supported: {dispatchKind}"
                );
        }
    }

    private bool IsDerivedDebugTraitDispatch(JsonElement expr, JsonElement dispatch)
    {
        if (
            (expr.GetProperty("trait").GetProperty("symbol").GetProperty("name").GetString() ?? "")
            != "Debug"
        )
            return false;

        var functionId = dispatch.GetProperty("functionId").GetString() ?? "";
        return functionId.StartsWith("derived:trait:", StringComparison.Ordinal);
    }

    private ExpressionSyntax EmitDebugImplReprCall(ExpressionSyntax value, JsonElement type)
    {
        var implType = DebugEvidenceTypeArgument(type);
        var receiverType = EmitType(type).NormalizeWhitespace().ToFullString();
        return ParseExpression(
            $"{CoreDebugTypeName("DebugTrait")}.to_repr<{receiverType}, {implType}>({value.NormalizeWhitespace()})"
        );
    }

    private string DebugEvidenceTypeArgument(JsonElement type)
    {
        if (type.GetProperty("kind").GetString() == "Declared")
        {
            var symbolId = type.GetProperty("symbol").GetProperty("id").GetString() ?? "";
            if (
                typeDefinitions.TryGetValue(symbolId, out var definition)
                && TypeDefinitionDerives(definition, "Debug")
            )
                return DerivedDebugImplTypeName(
                    TypeDefinitionName(definition.GetProperty("symbol"))
                );
        }

        return TraitEvidenceTypeArgument(type, "Debug");
    }

    private ExpressionSyntax EmitDerivedDebugRepr(ExpressionSyntax value, JsonElement type)
    {
        if (
            type.GetProperty("kind").GetString() == "Declared"
            && typeDefinitions.TryGetValue(
                type.GetProperty("symbol").GetProperty("id").GetString() ?? "",
                out var derivedDefinition
            )
            && TypeDefinitionDerives(derivedDefinition, "Debug")
        )
            return EmitDebugImplReprCall(value, type);

        var reprType = CoreDebugTypeName("Repr");
        var typeKind = type.GetProperty("kind").GetString();
        if (typeKind == "Struct")
            return EmitDerivedStructDebugRepr(value, type);
        if (typeKind == "Enum")
            return EmitDerivedEnumDebugRepr(value, type);

        if (typeKind == "Builtin")
            return BuiltinTypeName(type) switch
            {
                "Int" => ParseExpression(
                    $"{reprType}.Integer({value.NormalizeWhitespace().ToFullString()}.ToString(System.Globalization.CultureInfo.InvariantCulture))"
                ),
                "String" => ParseExpression(
                    $"{reprType}.StringLit({value.NormalizeWhitespace().ToFullString()})"
                ),
                "StringView" => ParseExpression(
                    $"{reprType}.Opaque({Literal("StringView").Text}, {reprType}.StringLit({value.NormalizeWhitespace().ToFullString()}.ToString()))"
                ),
                "Bool" => ParseExpression(
                    $"{reprType}.BoolLit({value.NormalizeWhitespace().ToFullString()})"
                ),
                "Char" => ParseExpression(
                    $"{reprType}.CharLit({value.NormalizeWhitespace().ToFullString()})"
                ),
                "Float" => ParseExpression(
                    $"{reprType}.FloatLit({value.NormalizeWhitespace().ToFullString()})"
                ),
                "Double" => ParseExpression(
                    $"{reprType}.DoubleLit({value.NormalizeWhitespace().ToFullString()})"
                ),
                "Unit" => ParseExpression($"{reprType}.UnitLit"),
                var name => ParseExpression(
                    $"{reprType}.Literal({Literal("<" + name + ">").Text})"
                ),
            };

        if (
            typeKind == "Declared"
            && typeDefinitions.TryGetValue(
                type.GetProperty("symbol").GetProperty("id").GetString() ?? "",
                out var definition
            )
        )
        {
            var kind = definition.TryGetProperty("kind", out var kindProperty)
                ? kindProperty.GetString()
                : "Struct";
            if (kind == "Struct")
                return EmitDerivedStructDebugRepr(value, definition);
            if (kind == "Enum")
                return EmitDerivedEnumDebugRepr(value, definition);
        }

        return ParseExpression(
            $"{reprType}.Literal({Literal("<" + EmitType(type).NormalizeWhitespace().ToFullString() + ">").Text})"
        );
    }

    private ExpressionSyntax EmitDerivedStructDebugRepr(
        ExpressionSyntax value,
        JsonElement definition
    )
    {
        var reprType = CoreDebugTypeName("Repr");
        var reprArrayType = $"MoonBitArray<{reprType}>";
        var fields = definition.GetProperty("fields").EnumerateArray().ToArray();
        var fieldExprs = fields.Select(field =>
        {
            var fieldName = field.GetProperty("name").GetString() ?? "";
            var member = ToPublicIdentifier(fieldName);
            var fieldValue = MemberAccessExpression(
                SyntaxKind.SimpleMemberAccessExpression,
                ParenthesizedExpression(value),
                IdentifierName(member)
            );
            var fieldRepr = EmitDebugImplReprCall(fieldValue, field.GetProperty("type"))
                .NormalizeWhitespace()
                .ToFullString();
            return $"{reprType}.RecordField({Literal(fieldName).Text}, {fieldRepr})";
        });
        return ParseExpression(
            $"{reprType}.Record(new {reprArrayType}(new {reprType}[] {{ {string.Join(", ", fieldExprs)} }}))"
        );
    }

    private ExpressionSyntax EmitDerivedEnumDebugRepr(
        ExpressionSyntax value,
        JsonElement definition
    )
    {
        var reprType = CoreDebugTypeName("Repr");
        var reprArrayType = $"MoonBitArray<{reprType}>";
        var typeName = QualifiedTypeDefinitionName(definition.GetProperty("symbol"));
        var variants = definition.GetProperty("variants").EnumerateArray().ToArray();
        var valueText = value.NormalizeWhitespace().ToFullString();
        if (variants.All(variant => variant.GetProperty("payloads").GetArrayLength() == 0))
        {
            var cases = variants.Select(variant =>
            {
                var sourceVariantName = variant.GetProperty("name").GetString() ?? "";
                var variantName = EnumVariantMemberName(typeName, sourceVariantName);
                return $"{typeName}.{variantName} => {reprType}.Enum({Literal(sourceVariantName).Text}, new {reprArrayType}(Array.Empty<{reprType}>()))";
            });
            return ParseExpression(
                $"({valueText} switch {{ {string.Join(", ", cases)}, _ => {reprType}.Omitted }})"
            );
        }

        var payloadCases = variants.Select(variant =>
        {
            var sourceVariantName = variant.GetProperty("name").GetString() ?? "";
            var variantName = EnumVariantMemberName(typeName, sourceVariantName);
            var variantType = PayloadVariantTypeName(typeName, variantName);
            var payloads = variant.GetProperty("payloads").EnumerateArray().ToArray();
            var payloadExprs = payloads.Select(
                (payload, index) =>
                {
                    var itemValue = ParseExpression(
                        $"(({variantType}){valueText}).Item{index.ToString(CultureInfo.InvariantCulture)}"
                    );
                    var itemRepr = EmitDebugImplReprCall(itemValue, EnumPayloadType(payload))
                        .NormalizeWhitespace()
                        .ToFullString();
                    var label = EnumPayloadLabel(payload);
                    return label is { Length: > 0 }
                        ? $"{reprType}.EnumLabeledArg({Literal(label).Text}, {itemRepr})"
                        : itemRepr;
                }
            );
            return $"{variantType} _ => {reprType}.Enum({Literal(sourceVariantName).Text}, new {reprArrayType}(new {reprType}[] {{ {string.Join(", ", payloadExprs)} }}))";
        });
        return ParseExpression(
            $"({valueText} switch {{ {string.Join(", ", payloadCases)}, _ => {reprType}.Omitted }})"
        );
    }

