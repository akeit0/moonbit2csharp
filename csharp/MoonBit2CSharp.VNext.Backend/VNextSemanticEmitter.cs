    private static bool TraitMethodHasDefault(JsonElement method)
    {
        return method.TryGetProperty("hasDefault", out var camel)
            ? camel.ValueKind == JsonValueKind.True
            : method.TryGetProperty("has_default", out var snake)
                && snake.ValueKind == JsonValueKind.True;
    }

    private string TraitDefaultInterfaceMethodBody(string traitName, JsonElement method)
    {
        var methodName = method.GetProperty("name").GetString() ?? "";
        return (traitName, methodName) switch
        {
            ("Show", "output") => "arg0.Impl.write_string(arg0.Self, TImpl.to_string(self))",
            ("Show", "to_string") =>
                "{ var logger = new MoonBitStringBuilder(); TImpl.output(self, new LoggerObject(logger, LoggerImplObject<MoonBitStringBuilder, StringBuilderLoggerImpl>.Instance)); return logger.ToString(); }",
            _ =>
                "throw new System.NotImplementedException(\"default trait method body is not emitted\")",
        };
    }

    private static string TraitMethodArgumentList(JsonElement method)
