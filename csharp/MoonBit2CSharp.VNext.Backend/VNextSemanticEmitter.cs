    private string SymbolContainerName(string symbolId, string moduleName)
    {
        if (symbolId.StartsWith("default-trait:", StringComparison.Ordinal))
        {
            var rest = symbolId["default-trait:".Length..];
            var methodSeparator = rest.LastIndexOf(':');
            if (methodSeparator > 0)
                return SymbolContainerName(rest[..methodSeparator], moduleName);
        }

        var packageName = PackageNameFromSymbolId(symbolId);
        if (packageName.Length == 0)
            return ModuleClassName(moduleName);

        var symbolModuleName = ModuleNameFromSymbolId(symbolId);
        if (symbolModuleName.Length == 0)
            return ToPublicIdentifier(LastPathSegment(packageName));

        var localModuleName =
            symbolModuleName == packageName ? LastPathSegment(packageName)
            : symbolModuleName.StartsWith(packageName + "/", StringComparison.Ordinal)
                ? symbolModuleName[(packageName.Length + 1)..]
            : symbolModuleName;
        var packagePrefix = PackageNamespaceSegment(packageName) + "_";
        if (localModuleName.StartsWith(packagePrefix, StringComparison.Ordinal))
            localModuleName = localModuleName[packagePrefix.Length..];

        var publicName = ToPublicIdentifier(localModuleName);
        return publicName.StartsWith(packagePrefix, StringComparison.Ordinal)
            ? publicName[packagePrefix.Length..]
            : publicName;
    }

