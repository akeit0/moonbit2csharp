    }

    private ClassDeclarationSyntax AddStaticTraitImplAdapterBase(
        ClassDeclarationSyntax declaration,
        IReadOnlyList<JsonElement> functions
    )
    {
        if (!TryGetStaticTraitImplAdapter(functions, out var adapter))
            return declaration;

        var selfTypeName = EmitType(adapter.SelfType).NormalizeWhitespace().ToFullString();
        var interfaceName = QualifyPackageTypeName(
            adapter.TraitSymbolId,
            "I" + ToPublicIdentifier(adapter.TraitName) + "Impl"
        );
        var className = declaration.Identifier.Text;
        return declaration.WithBaseList(
            BaseList(
                SingletonSeparatedList<BaseTypeSyntax>(
                    SimpleBaseType(ParseTypeName($"{interfaceName}<{selfTypeName}, {className}>"))
                )
            )
        );
    }

    private IEnumerable<MemberDeclarationSyntax> EmitStaticTraitImplDefaultMembers(
        IReadOnlyList<JsonElement> functions
    )
    {
        if (!TryGetStaticTraitImplAdapter(functions, out var adapter))
            yield break;

        var selfTypeName = EmitType(adapter.SelfType).NormalizeWhitespace().ToFullString();
        if (string.Equals(adapter.TraitName, "Eq", StringComparison.Ordinal))
        {
            var hasEqual = StaticTraitImplAdapterHasMethod(adapter, "equal");
            var hasNotEqual = StaticTraitImplAdapterHasMethod(adapter, "not_equal");
            if (hasNotEqual && !hasEqual)
                yield return ParseMemberDeclaration(
                    $"public static bool equal({selfTypeName} self, {selfTypeName} that) => !not_equal(self, that);"
                )!;
            else if (hasEqual && !hasNotEqual)
                yield return ParseMemberDeclaration(
                    $"public static bool not_equal({selfTypeName} self, {selfTypeName} that) => !equal(self, that);"
                )!;
        }

        if (
            string.Equals(adapter.TraitName, "Show", StringComparison.Ordinal)
            && !StaticTraitImplAdapterHasMethod(adapter, "output")
        ) { }
    }

    private IEnumerable<MemberDeclarationSyntax> EmitGenericStaticTraitImplAdapterMembers(
        string packageName
    )
    {
        foreach (
            var adapter in genericStaticTraitImplAdapters
                .Values.Where(adapter => PackageNameFromSymbolId(adapter.SymbolId) == packageName)
                .OrderBy(adapter => adapter.AdapterTypeName, StringComparer.Ordinal)
        )
        {
            var functions = adapter
                .FunctionSymbolIds.Distinct(StringComparer.Ordinal)
                .Select(functionId => functionsBySymbolId[functionId])
                .ToArray();
            var staticAdapter = new StaticTraitImplAdapter(
                adapter.TraitSymbolId,
                adapter.TraitName,
                adapter.SelfType,
                functions
            );
            if (!StaticTraitImplAdapterSatisfiesStaticInterface(staticAdapter))
                continue;

            yield return ParseMemberDeclaration(
                EmitGenericStaticTraitImplAdapterSource(adapter, functions)
            )!;
        }
    }

    private string EmitGenericStaticTraitImplAdapterSource(
        GenericStaticTraitImplAdapter adapter,
        IReadOnlyList<JsonElement> functions
    )
    {
        var typeParameterList = GenericStaticTraitImplAdapterTypeParameterList(adapter.TypeParams);
        var adapterTypeName = adapter.AdapterTypeName + typeParameterList;
        var selfTypeName = EmitType(adapter.SelfType).NormalizeWhitespace().ToFullString();
        var interfaceName = QualifyPackageTypeName(
            adapter.TraitSymbolId,
            "I" + ToPublicIdentifier(adapter.TraitName) + "Impl"
        );
        var constraints = GenericStaticTraitImplAdapterConstraintClauses(adapter.TypeParams);
        var methods = string.Join(
            Environment.NewLine,
            functions.Select(function => EmitGenericStaticTraitImplAdapterMethodSource(function))
        );
        return $$"""
            public sealed class {{adapter.AdapterTypeName}}{{typeParameterList}} : {{interfaceName}}<{{selfTypeName}}, {{adapterTypeName}}>
                {{constraints}}
            {
            {{methods}}
            }
            """;
    }

    private string EmitGenericStaticTraitImplAdapterMethodSource(JsonElement function)
    {
        var functionId = function.GetProperty("symbolId").GetString() ?? "";
        var returnType = EmitFunctionReturnType(function).NormalizeWhitespace().ToFullString();
        var methodName = ToTraitMethodIdentifier(
            UnqualifiedMoonBitFunctionName(function.GetProperty("name").GetString() ?? "")
        );
        var parameters = function.GetProperty("params").EnumerateArray().ToArray();
        var parameterNames = parameters
            .Select((param, index) => GenericStaticTraitImplAdapterParameterName(param, index))
            .ToArray();
        var parameterList = string.Join(
            ", ",
            parameters.Select(
                (param, index) =>
                    EmitType(param.GetProperty("type")).NormalizeWhitespace().ToFullString()
                    + " "
                    + parameterNames[index]
            )
        );
        var callTarget = GenericStaticTraitImplAdapterCallTarget(function);
        return $"    public static {returnType} {methodName}({parameterList}) => {callTarget}({string.Join(", ", parameterNames)});";
    }

    private string GenericStaticTraitImplAdapterCallTarget(JsonElement function)
    {
        var functionId = function.GetProperty("symbolId").GetString() ?? "";
        var methodName = FunctionMethodName(functionId);
        var typeParamInfos = function.TryGetProperty("typeParams", out var typeParams)
            ? ReadTypeParamInfos(typeParams)
            : [];
        var typeArguments = GenericStaticTraitImplAdapterTypeArgumentNames(typeParamInfos);
        var memberName =
            typeArguments.Length == 0
                ? methodName
                : methodName + "<" + string.Join(", ", typeArguments) + ">";
        if (!functionContainers.TryGetValue(functionId, out var containerName))
            throw new InvalidOperationException(
                "VNXB001: unresolved function target in executable IR: " + functionId
            );

        var packageName = PackageNameFromSymbolId(functionId);
        var container =
            packageName.Length > 0 && packageName != currentPackageName
                ? "global::" + PackageNamespace(packageName) + "." + containerName
                : containerName;
        return container + "." + memberName;
    }

    private static string GenericStaticTraitImplAdapterParameterName(JsonElement param, int index)
    {
        var name = param.TryGetProperty("name", out var nameNode) ? nameNode.GetString() ?? "" : "";
        return name.Length == 0
            ? "arg" + index.ToString(CultureInfo.InvariantCulture)
            : SafeIdentifier(name);
    }

    private string[] GenericStaticTraitImplAdapterTypeArgumentNames(TypeParamInfo[] typeParams)
    {
        return typeParams
            .Select(param => SafeIdentifier(param.Name))
            .Concat(
                typeParams.SelectMany(param =>
                    param.Constraints.Select(trait =>
                        StaticTraitImplTypeParameterName(param.Name, trait)
                    )
                )
            )
            .ToArray();
    }

    private static string GenericStaticTraitImplAdapterTypeParameterList(TypeParamInfo[] typeParams)
    {
        var names = typeParams
            .Select(param => SafeIdentifier(param.Name))
            .Concat(
                typeParams.SelectMany(param =>
                    param.Constraints.Select(trait =>
                        StaticTraitImplTypeParameterName(param.Name, trait)
                    )
                )
            )
            .ToArray();
        return names.Length == 0 ? "" : "<" + string.Join(", ", names) + ">";
    }

    private string GenericStaticTraitImplAdapterConstraintClauses(TypeParamInfo[] typeParams)
    {
        return string.Join(
            Environment.NewLine,
            typeParams.SelectMany(param =>
                param.Constraints.Select(trait =>
                    "where "
                    + StaticTraitImplTypeParameterName(param.Name, trait)
                    + " : "
                    + StaticTraitConstraintType(param.Name, trait)
                )
            )
        );
    }

    private static bool StaticTraitImplAdapterHasMethod(
        StaticTraitImplAdapter adapter,
        string traitMethodName
    )
    {
        return adapter.Functions.Any(function =>
            string.Equals(
                ToTraitMethodIdentifier(
                    UnqualifiedMoonBitFunctionName(function.GetProperty("name").GetString() ?? "")
                ),
                traitMethodName,
                StringComparison.Ordinal
            )
        );
    }

    private bool TryGetStaticTraitImplAdapter(
        IReadOnlyList<JsonElement> functions,
        out StaticTraitImplAdapter adapter
    )
    {
        var implFunctions = functions
            .Select(function => (Function: function, Impl: TryReadTraitImplSymbol(function)))
            .Where(item => item.Impl is not null)
            .ToArray();
        if (implFunctions.Length == 0)
        {
            adapter = default;
            return false;
        }

        var first = implFunctions[0];
        var selfType = first.Function.GetProperty("params")[0].GetProperty("type");
        if (ContainsTypeParameter(selfType))
        {
            adapter = default;
            return false;
        }

        adapter = new(
            first.Impl!.Value.TraitSymbolId,
            first.Impl.Value.TraitName,
            selfType,
            implFunctions.Select(item => item.Function).ToArray()
        );
        return StaticTraitImplAdapterSatisfiesStaticInterface(adapter);
    }

    private bool StaticTraitImplAdapterSatisfiesStaticInterface(StaticTraitImplAdapter adapter)
    {
        if (!traitsBySymbolId.TryGetValue(adapter.TraitSymbolId, out var trait))
            return false;

        var implementedMethods = adapter
            .Functions.Select(function =>
                ToTraitMethodIdentifier(
                    UnqualifiedMoonBitFunctionName(function.GetProperty("name").GetString() ?? "")
                )
            )
            .ToHashSet(StringComparer.Ordinal);
        foreach (var method in trait.GetProperty("methods").EnumerateArray())
        {
            if (TraitMethodHasDefault(method))
                continue;

            var methodName = ToTraitMethodIdentifier(method.GetProperty("name").GetString() ?? "");
            if (
                !implementedMethods.Contains(methodName)
                && !CanSynthesizeStaticTraitImplMethod(adapter, implementedMethods, methodName)
            )
                return false;
        }

        return true;
    }

    private static bool CanSynthesizeStaticTraitImplMethod(
        StaticTraitImplAdapter adapter,
        HashSet<string> implementedMethods,
        string methodName
    )
    {
        return string.Equals(adapter.TraitName, "Eq", StringComparison.Ordinal)
            && string.Equals(methodName, "equal", StringComparison.Ordinal)
            && implementedMethods.Contains("not_equal");
    }

    private TraitImplSymbol? TryReadTraitImplSymbol(JsonElement function)
    {
        var symbolId = function.GetProperty("symbolId").GetString() ?? "";
        var parts = symbolId.Split(':');
        for (var i = 0; i < parts.Length; i++)
        {
            if (
                string.Equals(parts[i], "impl", StringComparison.Ordinal)
                && i + 2 < parts.Length
                && parts[i + 1].Contains('/', StringComparison.Ordinal)
                && function.GetProperty("params").GetArrayLength() > 0
            )
            {
                var traitPackage = parts[i + 1];
                var traitName = parts[i + 2];
                if (TryFindTraitSymbolId(traitName, traitPackage, out var packageTraitSymbolId))
                    return new TraitImplSymbol(packageTraitSymbolId, traitName);
            }

            if (
                string.Equals(parts[i], "impl", StringComparison.Ordinal)
                && i + 2 < parts.Length
                && !parts[i + 1].Contains('/', StringComparison.Ordinal)
                && function.GetProperty("params").GetArrayLength() > 0
            )
            {
                var traitName = parts[i + 1];
                if (TryFindTraitSymbolId(traitName, null, out var traitSymbolId))
                    return new TraitImplSymbol(traitSymbolId, traitName);
            }
        }

        return null;
    }

    private bool TryFindTraitSymbolId(
        string traitName,
        string? packageName,
        out string traitSymbolId
    )
    {
        if (traitSymbolIdsByName.TryGetValue(ToPublicIdentifier(traitName), out var ids))
            foreach (var id in ids)
                if (
                    packageName is null
                    || string.Equals(
                        PackageNameFromSymbolId(id),
                        packageName,
                        StringComparison.Ordinal
                    )
                )
                {
                    traitSymbolId = id;
                    return true;
                }

        traitSymbolId = "";
        return false;
    }

    private TypeSyntax EmitFunctionReturnType(JsonElement function)
    {
        var returnType = function.GetProperty("returnType");
        if (TryGetRaisingEffect(function, out var errorTypeName))
            return ParseTypeName(
                $"MoonBitResult<{EmitType(returnType).NormalizeWhitespace().ToFullString()}, {errorTypeName}>"
            );

        return EmitType(returnType);
    }

    private bool TryGetRaisingEffect(JsonElement function, out string errorTypeName)
    {
        errorTypeName = "object";
        if (
            function.TryGetProperty("effect", out var effect)
            && effect.TryGetProperty("kind", out var kind)
            && kind.GetString() == "Raises"
            && effect.TryGetProperty("error", out var errorType)
        )
        {
            errorTypeName = EmitType(errorType).NormalizeWhitespace().ToFullString();
            return true;
        }

        return false;
    }

    private static bool TryEmitExternalFunctionBody(JsonElement function, out BlockSyntax body)
    {
        body = Block();
        if (
            !function.TryGetProperty("external", out var external)
            || external.ValueKind == JsonValueKind.Null
        )
            return false;

        var target = external.GetProperty("target").GetString() ?? "";
        if (target == "csharp")
        {
            body = EmitExternalCSharpFunctionBody(external.GetProperty("body").GetString() ?? "");
            return true;
        }

        if (target == "interface")
        {
            var symbolId = function.GetProperty("symbolId").GetString() ?? "";
            body = Block(
                ThrowStatement(
                    ObjectCreationExpression(IdentifierName("NotImplementedException"))
                        .WithArgumentList(
                            ArgumentList(
                                SingletonSeparatedList(
                                    Argument(
                                        LiteralExpression(
                                            SyntaxKind.StringLiteralExpression,
                                            Literal(
                                                "imported MoonBit interface function is not linked: "
                                                    + symbolId
                                            )
                                        )
                                    )
                                )
                            )
                        )
                )
            );
            return true;
        }

        body = EmitUnavailableExternalFunctionBody(function, target);
        return true;
    }

    private static BlockSyntax EmitUnavailableExternalFunctionBody(
        JsonElement function,
        string target
    )
    {
        var symbolId = function.GetProperty("symbolId").GetString() ?? "";
        return Block(
            ThrowStatement(
                ObjectCreationExpression(IdentifierName("NotImplementedException"))
                    .WithArgumentList(
                        ArgumentList(
                            SingletonSeparatedList(
                                Argument(
                                    LiteralExpression(
                                        SyntaxKind.StringLiteralExpression,
                                        Literal(
                                            "MoonBit extern target is not linked for C#: "
                                                + target
                                                + " ("
                                                + symbolId
                                                + ")"
                                        )
                                    )
                                )
                            )
                        )
                    )
            )
        );
    }

    private static BlockSyntax EmitExternalCSharpFunctionBody(string body)
    {
        var block = (BlockSyntax)ParseStatement(
            "{" + Environment.NewLine + body + Environment.NewLine + "}"
        );
        var errors = block
            .GetDiagnostics()
            .Where(diagnostic => diagnostic.Severity == DiagnosticSeverity.Error)
            .ToArray();
        if (errors.Length > 0)
            throw new InvalidOperationException(
                "invalid vnext extern csharp body: "
                    + string.Join(Environment.NewLine, errors.Select(error => error.ToString()))
            );

        return block;
    }

    private ExpressionSyntax EmitExpr(JsonElement expr)
    {
        var kind = expr.GetProperty("kind").GetString() ?? "";
        return kind switch
        {
            "Name" => EmitName(expr),
            "FunctionRef" => FunctionMemberAccess(expr.GetProperty("functionId").GetString() ?? ""),
            "IntLiteral" => EmitIntegerLiteral(expr),
            "FloatLiteral" => EmitFloatLiteral(expr),
            "CharLiteral" => LiteralExpression(
                SyntaxKind.NumericLiteralExpression,
                Literal(CharLiteralCodePoint(expr.GetProperty("value").GetString() ?? ""))
            ),
            "StringLiteral" => LiteralExpression(
                SyntaxKind.StringLiteralExpression,
                Literal(expr.GetProperty("value").GetString() ?? "")
            ),
            "BytesLiteral" => EmitBytesLiteral(expr.GetProperty("value").GetString() ?? ""),
            "BoolLiteral" => LiteralExpression(
                expr.GetProperty("value").GetBoolean()
                    ? SyntaxKind.TrueLiteralExpression
                    : SyntaxKind.FalseLiteralExpression
            ),
            "UnitLiteral" => ParseExpression("MoonBitUnit.Value"),
            "TupleLiteral" => TupleExpression(
                SeparatedList(
                    expr.GetProperty("items")
                        .EnumerateArray()
                        .Select(item => Argument(EmitExpr(item)))
                )
            ),
            "TupleGet" => MemberAccessExpression(
                SyntaxKind.SimpleMemberAccessExpression,
                EmitExpr(expr.GetProperty("target")),
                IdentifierName(
                    "Item"
                        + (expr.GetProperty("index").GetInt32() + 1).ToString(
                            CultureInfo.InvariantCulture
                        )
                )
            ),
            "OptionSome" => EmitOptionSome(expr),
            "OptionNone" => EmitOptionNone(expr),
            "Panic" => ThrowExpression(
                ObjectCreationExpression(IdentifierName("MoonBitPanic"))
                    .WithArgumentList(ArgumentList())
            ),
            "Raise" => EmitRaise(expr),
            "TryCatch" => EmitTryCatch(expr),
            "EnumCase" => EmitEnumCase(expr),
            "LocalLet" => throw new NotSupportedException(
                "vnext LocalLet is only supported as a function-body expression"
            ),
            "Sequence" => throw new NotSupportedException(
                "vnext Sequence is only supported as a function-body expression"
            ),
            "Call" => EmitCall(expr),
            "FunctionValueCall" => InvocationExpression(
                EmitExpr(expr.GetProperty("callee")),
                ArgumentList(
                    SeparatedList(
                        expr.GetProperty("args")
                            .EnumerateArray()
                            .Select(arg => Argument(EmitExpr(arg)))
                    )
                )
            ),
            "Lambda" => EmitLambda(expr),
            "IndexGet" => ElementAccessExpression(EmitExpr(expr.GetProperty("target")))
                .WithArgumentList(
                    BracketedArgumentList(
                        SingletonSeparatedList(Argument(EmitExpr(expr.GetProperty("index"))))
                    )
                ),
            "FieldAccess" => MemberAccessExpression(
                SyntaxKind.SimpleMemberAccessExpression,
                EmitExpr(expr.GetProperty("target")),
                IdentifierName(ToPublicIdentifier(FieldRefName(expr.GetProperty("field"))))
            ),
            "FieldAssign" => AssignmentExpression(
                SyntaxKind.SimpleAssignmentExpression,
                MemberAccessExpression(
                    SyntaxKind.SimpleMemberAccessExpression,
                    EmitExpr(expr.GetProperty("target")),
                    IdentifierName(ToPublicIdentifier(FieldRefName(expr.GetProperty("field"))))
                ),
                EmitExpr(expr.GetProperty("value"))
            ),
            "Assign" => AssignmentExpression(
                SyntaxKind.SimpleAssignmentExpression,
                IdentifierName(LocalIdentifier(expr)),
                EmitExpr(expr.GetProperty("value"))
            ),
            "IndexAssign" => AssignmentExpression(
                SyntaxKind.SimpleAssignmentExpression,
                ElementAccessExpression(EmitExpr(expr.GetProperty("target")))
                    .WithArgumentList(
                        BracketedArgumentList(
                            SingletonSeparatedList(Argument(EmitExpr(expr.GetProperty("index"))))
                        )
                    ),
                EmitExpr(expr.GetProperty("value"))
            ),
            "TraitMethodCall" => EmitTraitMethodCall(expr),
            "ArrayLiteral" => EmitArrayLiteral(expr),
            "MapLiteral" => EmitMapLiteral(expr),
            "StructLiteral" => EmitStructLiteral(expr),
            "StructUpdate" => EmitStructUpdate(expr),
            "Conversion" => EmitConversion(expr),
            "Unary" => EmitUnary(expr),
            "Binary" => EmitBinary(expr),
            "If" => EmitIfExpression(expr),
            "IsPattern" => EmitIsPatternExpression(expr),
            "Match" => EmitMatchExpression(expr),
            "While" or "ForRange" or "ForLoop" or "ForIn" or "Break" or "Continue" or "Return" =>
                throw new NotSupportedException(
                    "vnext " + kind + " is only supported as a statement expression"
                ),

            _ => throw new NotSupportedException($"vnext expression kind is not supported: {kind}"),
        };
    }

    private ExpressionSyntax EmitName(JsonElement expr)
    {
        var symbolId = expr.GetProperty("symbolId").GetString() ?? "";
        var name = expr.GetProperty("name").GetString() ?? "";
        if (symbolId.StartsWith("global:", StringComparison.Ordinal))
        {
            var containerName = SymbolContainerName(symbolId, rootModuleName);
            var packageName = PackageNameFromSymbolId(symbolId);
            var container =
                packageName.Length > 0 && packageName != currentPackageName
                    ? "global::" + PackageNamespace(packageName) + "." + containerName
                    : containerName;
            return ParseExpression(container + "." + ToPublicIdentifier(name));
        }

        return IdentifierName(LocalIdentifier(name, symbolId));
    }

    private static string IntegerLiteralDigits(string value)
    {
        var end = value.Length;
        while (end > 0 && value[end - 1] is 'u' or 'U' or 'l' or 'L')
            end--;

        return value[..end].Replace("_", "", StringComparison.Ordinal);
    }

    private static ExpressionSyntax EmitIntegerLiteral(JsonElement expr)
    {
        var value = expr.GetProperty("value").GetString() ?? "0";
        var typeName = expr.TryGetProperty("type", out var type) ? BuiltinTypeName(type) : "";
        return typeName switch
        {
            "UInt64" => LiteralExpression(
                SyntaxKind.NumericLiteralExpression,
                Literal(UInt64IntegerLiteralValue(value))
            ),
            "Int64" => LiteralExpression(
                SyntaxKind.NumericLiteralExpression,
                Literal(Int64IntegerLiteralValue(value))
            ),
            "UInt" => LiteralExpression(
                SyntaxKind.NumericLiteralExpression,
                Literal(UInt32IntegerLiteralValue(value))
            ),
            _ => LiteralExpression(
                SyntaxKind.NumericLiteralExpression,
                Literal(Int32IntegerLiteralValue(value))
            ),
        };
    }

    private static int Int32IntegerLiteralValue(string value)
    {
        var digits = IntegerLiteralDigits(value);
        if (digits.StartsWith("0x", StringComparison.OrdinalIgnoreCase))
            return Convert.ToInt32(digits[2..], 16);

        if (digits.StartsWith("0b", StringComparison.OrdinalIgnoreCase))
            return Convert.ToInt32(digits[2..], 2);

        if (digits.StartsWith("0o", StringComparison.OrdinalIgnoreCase))
            return Convert.ToInt32(digits[2..], 8);

        return int.Parse(digits, CultureInfo.InvariantCulture);
    }

