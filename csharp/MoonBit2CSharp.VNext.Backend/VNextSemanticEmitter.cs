    public string Emit(string json)
    {
        var files = EmitFiles(json);
        if (files.Count == 1)
            return files[0].Code;

        var builder = new StringBuilder();
        builder.Append("// <auto-generated/>").Append(options.NewLine);
        builder.Append("#nullable enable").Append(options.NewLine).Append(options.NewLine);
        builder.Append("using System;").Append(options.NewLine);
        builder
            .Append("using ")
            .Append(options.GeneratedNamespace)
            .Append(".Runtime;")
            .Append(options.NewLine);
        foreach (var file in files)
        {
            var marker = options.NewLine + "namespace ";
            var namespaceStart = file.Code.IndexOf(marker, StringComparison.Ordinal);
            if (namespaceStart < 0)
                continue;

            namespaceStart += options.NewLine.Length;
            var namespaceEnd = file.Code.IndexOf(';', namespaceStart);
            if (namespaceEnd < 0)
                continue;

            var namespaceLine = file.Code[namespaceStart..namespaceEnd];
            var bodyStart = namespaceEnd + 1;
            var body = file.Code[bodyStart..].Trim();
            builder
                .Append(options.NewLine)
                .Append(namespaceLine)
                .Append(options.NewLine)
                .Append("{")
                .Append(options.NewLine)
                .Append(body)
                .Append(options.NewLine)
                .Append("}")
                .Append(options.NewLine);
        }

        var code = builder.ToString().TrimEnd('\r', '\n');
        return options.FinalNewLine ? code + options.NewLine : code;
    }

    public IReadOnlyList<VNextGeneratedFile> EmitFiles(string json)
    {
        typeDefinitions.Clear();
        typeNames.Clear();
        traitSymbolIdsByName.Clear();
        traitsBySymbolId.Clear();
        functionNames.Clear();
        functionContainers.Clear();
        bytesLiteralCaches.Clear();
        staticTraitImplAdapterTypes.Clear();
        genericStaticTraitImplAdapters.Clear();
        functionEffects.Clear();
        functionsBySymbolId.Clear();
        requiredCoreBuiltinEvidence.Clear();
        using var document = JsonDocument.Parse(json);
        var root = document.RootElement;
        var diagnostics = root.GetProperty("diagnostics").EnumerateArray().ToArray();
        var errors = diagnostics
            .Where(d => d.GetProperty("severity").GetString() == "error")
            .Select(FormatDiagnostic)
            .ToArray();
        if (errors.Length > 0)
            throw new InvalidOperationException(string.Join(Environment.NewLine, errors));

        var moduleName = root.GetProperty("module").GetProperty("name").GetString() ?? "Main";
        rootModuleName = moduleName;
        foreach (var typeDefinition in EnumerateOptionalArray(root, "types"))
        {
            var id = typeDefinition.GetProperty("symbol").GetProperty("id").GetString();
            if (!string.IsNullOrEmpty(id))
                typeDefinitions[id] = typeDefinition;
        }

        BuildTypeNameMap(root);
        foreach (var trait in EnumerateOptionalArray(root, "traits"))
        {
            var id = trait.GetProperty("symbol").GetProperty("id").GetString();
            if (!string.IsNullOrEmpty(id))
                traitsBySymbolId[id] = trait;
        }

        BuildTraitNameMap(root);
        BuildFunctionNameMap(root, moduleName);

        var emittedFunctions = root.GetProperty("functions").EnumerateArray().ToArray();
        var emittedGlobals = EnumerateOptionalArray(root, "globals").ToArray();
        var usedTypeIds = UsedTypeIds(emittedFunctions, emittedGlobals);
        var usedTraitIds = UsedTraitIds(emittedFunctions, emittedGlobals);
        var usedTraitImpls = EnumerateOptionalArray(root, "usedTraitImpls").ToArray();
        foreach (var usedTraitImpl in usedTraitImpls)
        {
            CollectUsedTraitIds(usedTraitImpl, usedTraitIds);
            CollectUsedTypeIds(usedTraitImpl, usedTypeIds);
        }

        BuildUsedDerivedTraitImplKeys(usedTraitImpls);
        CollectExpressionDerivedTraitImplKeys(root);
        if (RequiresCoreDebugPackage(usedTraitIds))
            AddCoreDebugSourceDependencies(usedTypeIds, usedTraitIds);
        CloseDerivedTraitImpls("Eq");
        CloseDerivedTraitImpls("Hash");
        CloseDerivedTraitImpls("Debug");
        foreach (var typeId in UsedDerivedTraitImplTypeIds())
            usedTypeIds.Add(typeId);
        var emitAllDeclarations = emittedFunctions.Length == 0 && emittedGlobals.Length == 0;
        var usedTraits = EnumerateOptionalArray(root, "traits")
            .Where(trait => UsedTrait(trait, usedTraitIds, emitAllDeclarations))
            .ToArray();
        usedTraits = usedTraits
            .Concat(
                EnumerateOptionalArray(root, "traits")
                    .Where(trait => TraitReferencedByTraitMethods(trait, usedTraits))
            )
            .GroupBy(
                trait => trait.GetProperty("symbol").GetProperty("id").GetString() ?? "",
                StringComparer.Ordinal
            )
            .Select(group => group.First())
            .ToArray();
        foreach (var trait in usedTraits)
            CollectUsedTypeIds(trait, usedTypeIds);
        var usedTypes = EnumerateOptionalArray(root, "types")
            .Where(type => UsedTypeDefinition(type, usedTypeIds, emitAllDeclarations))
            .ToArray();
        emitCoreBuiltinHasherFallback = !usedTypes.Any(IsConcreteCoreBuiltinHasherType);
        CollectRequiredCoreBuiltinEvidence(usedTraitImpls, usedTraits, usedTypes);
        var classNames = emittedFunctions
            .Where(function => !IsDefaultTraitFunction(function))
            .Select(function =>
                functionContainers[function.GetProperty("symbolId").GetString() ?? ""]
            )
            .Concat(emittedGlobals.Select(global => GlobalContainerName(global, moduleName)))
            .Distinct(StringComparer.Ordinal)
            .ToArray();
        var packages = usedTypes
            .Select(TypeDefinitionPackageName)
            .Concat(usedTraits.Select(TraitPackageName))
            .Concat(
                RequiresCoreDebugPackage(usedTraitIds)
                    ? new[] { "moonbitlang/core/debug" }
                    : Array.Empty<string>()
            )
            .Concat(
                emittedFunctions.Select(function =>
                    PackageNameFromSymbolId(function.GetProperty("symbolId").GetString() ?? "")
                )
            )
            .Concat(
                emittedGlobals.Select(global =>
                    PackageNameFromSymbolId(global.GetProperty("symbolId").GetString() ?? "")
                )
            )
            .Distinct(StringComparer.Ordinal)
            .Order(StringComparer.Ordinal)
            .ToArray();
        var files = new List<VNextGeneratedFile>();
        foreach (var packageName in packages)
        {
            currentPackageName = packageName;
            var packageClassNames = classNames
                .Where(className =>
                    emittedFunctions.Any(function =>
                        !IsDefaultTraitFunction(function)
                        && functionContainers[function.GetProperty("symbolId").GetString() ?? ""]
                            == className
                        && PackageNameFromSymbolId(
                            function.GetProperty("symbolId").GetString() ?? ""
                        ) == packageName
                    )
                    || emittedGlobals.Any(global =>
                        GlobalContainerName(global, moduleName) == className
                        && PackageNameFromSymbolId(global.GetProperty("symbolId").GetString() ?? "")
                            == packageName
                    )
                )
                .ToArray();
            var moduleClasses = packageClassNames
                .Select(className =>
                {
                    var classFunctions = emittedFunctions
                        .Where(function =>
                            !IsDefaultTraitFunction(function)
                            && functionContainers[
                                function.GetProperty("symbolId").GetString() ?? ""
                            ] == className
                            && PackageNameFromSymbolId(
                                function.GetProperty("symbolId").GetString() ?? ""
                            ) == packageName
                        )
                        .ToArray();
                    var hasStaticTraitImplAdapter = ClassHasStaticTraitImplAdapter(classFunctions);
                    var classDeclaration = hasStaticTraitImplAdapter
                        ? ClassDeclaration(className)
                            .AddModifiers(
                                Token(SyntaxKind.PublicKeyword),
                                Token(SyntaxKind.PartialKeyword)
                            )
                        : ClassDeclaration(className)
                            .AddModifiers(
                                Token(SyntaxKind.PublicKeyword),
                                Token(SyntaxKind.StaticKeyword),
                                Token(SyntaxKind.PartialKeyword)
                            );
                    classDeclaration = AddStaticTraitImplAdapterBase(
                        classDeclaration,
                        classFunctions
                    );
                    var classMembers = new List<MemberDeclarationSyntax>();
                    var previousMemberContainerName = currentMemberContainerName;
                    currentMemberContainerName = className;
                    foreach (
                        var global in emittedGlobals.Where(global =>
                            GlobalContainerName(global, moduleName) == className
                            && PackageNameFromSymbolId(
                                global.GetProperty("symbolId").GetString() ?? ""
                            ) == packageName
                        )
                    )
                        classMembers.Add(EmitGlobal(global));
                    foreach (var function in classFunctions)
                        classMembers.Add(EmitFunction(function));
                    classMembers.AddRange(EmitStaticTraitImplDefaultMembers(classFunctions));
                    classMembers.AddRange(EmitBytesLiteralCacheMembers(packageName, className));
                    currentMemberContainerName = previousMemberContainerName;
                    return classDeclaration.AddMembers(classMembers.ToArray());
                })
                .ToArray();
            var members = usedTraits
                .Where(trait =>
                    TraitPackageName(trait) == packageName
                    && !CoreBuiltinTraitEmittedManually(trait)
                )
                .SelectMany(EmitTrait)
                .Concat(
                    usedTypes
                        .Where(type => TypeDefinitionPackageName(type) == packageName)
                        .SelectMany(EmitTypeDefinitionMembers)
                )
                .Concat(EmitCoreBuiltinEvidenceMembers(packageName))
                .Concat(EmitCoreDebugEvidenceMembers(packageName))
                .Concat(EmitGenericStaticTraitImplAdapterMembers(packageName))
                .Concat(moduleClasses)
                .ToArray();
            if (members.Length == 0)
                continue;
            files.Add(
                new(
                    PackageFileName(packageName),
                    EmitCompilationUnit(PackageNamespace(packageName), members)
                )
            );
        }

        currentPackageName = "";
        var entryPointMembers = EmitEntryPointMembers(root).ToArray();
        if (entryPointMembers.Length > 0)
            files.Add(
                new(
                    "Program.g.cs",
                    EmitCompilationUnit(options.GeneratedNamespace, entryPointMembers)
                )
            );

        return files;
    }

    private string EmitCompilationUnit(
        string namespaceName,
        IReadOnlyList<MemberDeclarationSyntax> members
    )
    {
        var unit = CompilationUnit()
            .WithUsings(SingletonList(UsingDirective(ParseName("System"))))
            .AddUsings(UsingDirective(ParseName(options.GeneratedNamespace + ".Runtime")))
            .WithMembers(
                SingletonList<MemberDeclarationSyntax>(
                    FileScopedNamespaceDeclaration(ParseName(namespaceName))
                        .AddMembers(members.ToArray())
                )
            );
        unit = (CompilationUnitSyntax)new RuntimeIdentifierQualifier(options).Visit(unit)!;
        unit = unit.NormalizeWhitespace(new(' ', Math.Max(0, options.IndentSize)), options.NewLine);

        var code =
            "// <auto-generated/>"
            + options.NewLine
            + "#nullable enable"
            + options.NewLine
            + options.NewLine
            + unit.ToFullString().TrimEnd('\r', '\n');
        return options.FinalNewLine ? code + options.NewLine : code;
    }

    private static string FormatDiagnostic(JsonElement diagnostic)
    {
        var code = diagnostic.GetProperty("code").GetString() ?? "";
        var message = diagnostic.GetProperty("message").GetString() ?? "";
        if (
            !diagnostic.TryGetProperty("span", out var span)
            || span.ValueKind != JsonValueKind.Object
        )
            return $"{code}: {message}";

        var file = span.TryGetProperty("file", out var fileNode) ? fileNode.GetString() ?? "" : "";
        var line = span.TryGetProperty("line", out var lineNode) ? lineNode.GetInt32() : 0;
        var column = span.TryGetProperty("column", out var columnNode) ? columnNode.GetInt32() : 0;
        if (file.Length == 0 && line <= 0 && column <= 0)
            return $"{code}: {message}";

        var location =
            file.Length == 0
                ? $"{line.ToString(CultureInfo.InvariantCulture)}:{column.ToString(CultureInfo.InvariantCulture)}"
                : $"{file}:{line.ToString(CultureInfo.InvariantCulture)}:{column.ToString(CultureInfo.InvariantCulture)}";
        return $"{location}: {code}: {message}";
    }

    private IEnumerable<MemberDeclarationSyntax> EmitEntryPointMembers(JsonElement root)
    {
        if (!options.EmitEntryPoint)
            yield break;

        var mainFunction = root.GetProperty("functions")
            .EnumerateArray()
            .FirstOrDefault(function =>
                (function.GetProperty("name").GetString() ?? "") is "main" or "Main"
                && function.GetProperty("params").GetArrayLength() == 0
            );
        if (mainFunction.ValueKind == JsonValueKind.Undefined)
            yield break;

        var symbolId = mainFunction.GetProperty("symbolId").GetString() ?? "";
        var mainAccess = FunctionMemberAccess(symbolId).NormalizeWhitespace().ToFullString();
        yield return ParseMemberDeclaration(
            $$"""
            public static class Program
            {
                public static void Main(string[] args)
                {
                    {{mainAccess}}();
                }
            }
            """
        )!;
    }

    private MemberDeclarationSyntax EmitTypeDefinition(JsonElement typeDefinition)
    {
        var kind = typeDefinition.TryGetProperty("kind", out var kindProperty)
            ? kindProperty.GetString()
            : "Struct";
        if (kind == "Enum")
            return EmitEnumDefinition(typeDefinition);
        if (kind == "Opaque")
        {
            var opaqueSymbol = typeDefinition.GetProperty("symbol");
            var opaqueName = TypeDefinitionName(opaqueSymbol);
            var opaqueTypeParams = ReadTypeParams(typeDefinition.GetProperty("typeParams"));
            var typeParameters =
                opaqueTypeParams.Length == 0
                    ? ""
                    : "<"
                        + string.Join(", ", opaqueTypeParams.Select(param => param.Identifier.Text))
                        + ">";
            return ParseMemberDeclaration(
                $"public readonly record struct {opaqueName}{typeParameters}(object? Value);"
            )!;
        }

        var symbol = typeDefinition.GetProperty("symbol");
        var name = TypeDefinitionName(symbol);
        var typeParams = ReadTypeParams(typeDefinition.GetProperty("typeParams"));
        var fields = typeDefinition.GetProperty("fields").EnumerateArray().ToArray();
        var isValType =
            typeDefinition.TryGetProperty("valtype", out var valtype)
            && valtype.ValueKind == JsonValueKind.True;
        var hasMutableField = fields.Any(field => field.GetProperty("mutable").GetBoolean());

        if (isValType)
            return EmitStructDefinition(name, typeParams, fields, hasMutableField);

        var properties = fields.Select(EmitStructProperty).Cast<MemberDeclarationSyntax>();
        var declaration = ClassDeclaration(name)
            .AddModifiers(Token(SyntaxKind.PublicKeyword), Token(SyntaxKind.SealedKeyword))
            .AddMembers(properties.Append(EmitConstructor(name, fields)).ToArray());
        return typeParams.Length == 0
            ? declaration
            : declaration.WithTypeParameterList(TypeParameterList(SeparatedList(typeParams)));
    }

    private IEnumerable<MemberDeclarationSyntax> EmitTypeDefinitionMembers(
        JsonElement typeDefinition
    )
    {
        yield return EmitTypeDefinition(typeDefinition);
        foreach (var member in EmitDerivedEqMembers(typeDefinition))
            yield return member;
        foreach (var member in EmitDerivedHashMembers(typeDefinition))
            yield return member;
        foreach (var member in EmitDerivedDebugMembers(typeDefinition))
            yield return member;
    }

    private IEnumerable<MemberDeclarationSyntax> EmitDerivedHashMembers(JsonElement typeDefinition)
    {
        if (
            !TypeDefinitionDerives(typeDefinition, "Hash")
            || !UsedDerivedTraitImpl(typeDefinition, "Hash")
        )
            yield break;

        var symbol = typeDefinition.GetProperty("symbol");
        var name = TypeDefinitionName(symbol);
        var typeParams = ReadTypeParams(typeDefinition.GetProperty("typeParams"));
        var selfTypeName = SelfTypeName(name, typeParams);
        var implName = DerivedHashImplTypeName(name);
        var hashImplInterfaceName = CoreBuiltinTypeName("IHashImpl");
        var hasherName = CoreBuiltinTypeName("Hasher");
        var typeParameterList =
            typeParams.Length == 0
                ? ""
                : "<" + string.Join(", ", typeParams.Select(param => param.Identifier.Text)) + ">";
        var statements = string.Join(
            Environment.NewLine,
            EmitDerivedHashStatements(
                typeDefinition,
                ParseExpression("self"),
                ParseExpression("arg0")
            )
        );
        yield return ParseMemberDeclaration(
            $$"""
            public sealed class {{implName}}{{typeParameterList}} : {{hashImplInterfaceName}}<{{selfTypeName}}, {{implName}}{{typeParameterList}}>
            {
                public static MoonBitUnit hash_combine({{selfTypeName}} self, {{hasherName}} arg0)
                {
                    {{statements}}
                    return MoonBitUnit.Value;
                }
            }
            """
        )!;
    }

    private IEnumerable<MemberDeclarationSyntax> EmitDerivedEqMembers(JsonElement typeDefinition)
    {
        if (
            !TypeDefinitionDerives(typeDefinition, "Eq")
            || !UsedDerivedTraitImpl(typeDefinition, "Eq")
        )
            yield break;

        var symbol = typeDefinition.GetProperty("symbol");
        var name = TypeDefinitionName(symbol);
        var typeParams = ReadTypeParams(typeDefinition.GetProperty("typeParams"));
        var selfTypeName = SelfTypeName(name, typeParams);
        var implName = DerivedEqImplTypeName(name);
        var eqImplInterfaceName = CoreBuiltinTypeName("IEqImpl");
        var typeParameterList =
            typeParams.Length == 0
                ? ""
                : "<" + string.Join(", ", typeParams.Select(param => param.Identifier.Text)) + ">";
        var equality = EmitDerivedEquality(
                TypeRefFromDefinition(typeDefinition),
                ParseExpression("self"),
                ParseExpression("arg0"),
                new System.Collections.Generic.HashSet<string>()
            )
            .NormalizeWhitespace()
            .ToFullString();
        yield return ParseMemberDeclaration(
            $$"""
            public sealed class {{implName}}{{typeParameterList}} : {{eqImplInterfaceName}}<{{selfTypeName}}, {{implName}}{{typeParameterList}}>
            {
                public static bool equal({{selfTypeName}} self, {{selfTypeName}} arg0) => {{equality}};
                public static bool not_equal({{selfTypeName}} self, {{selfTypeName}} arg0) => !({{equality}});
            }
            """
        )!;
    }

    private static JsonElement TypeRefFromDefinition(JsonElement typeDefinition)
    {
        using var document = JsonDocument.Parse(
            $$"""
              {
                "kind": "Declared",
                "symbol": {{typeDefinition.GetProperty("symbol").GetRawText()}},
                "args": [{{string.Join(
                    ",",
                    typeDefinition
                        .GetProperty("typeParams")
                        .EnumerateArray()
                        .Select(param =>
                            $$"""{"kind":"TypeParameter","name":{{JsonSerializer.Serialize(param.GetString() ?? "")}},"symbolId":"type-param:{{param.GetString() ?? ""}}"}"""
                        )
                )}}]
              }
              """
        );
        return document.RootElement.Clone();
    }

    private IEnumerable<string> EmitDerivedHashStatements(
        JsonElement typeOrDefinition,
        ExpressionSyntax value,
        ExpressionSyntax hasher
    )
    {
        var kind = typeOrDefinition.TryGetProperty("kind", out var kindProperty)
            ? kindProperty.GetString()
            : "";
        if (kind == "Struct")
        {
            foreach (var field in typeOrDefinition.GetProperty("fields").EnumerateArray())
            {
                var member = ToPublicIdentifier(field.GetProperty("name").GetString() ?? "");
                foreach (
                    var statement in EmitDerivedHashStatements(
                        field.GetProperty("type"),
                        ParseExpression($"({value.NormalizeWhitespace()}).{member}"),
                        hasher
                    )
                )
                    yield return statement;
            }

            yield break;
        }

        if (kind == "Enum")
        {
            foreach (
                var statement in EmitDerivedEnumHashStatements(typeOrDefinition, value, hasher)
            )
                yield return statement;
            yield break;
        }

        if (
            kind == "Declared"
            && typeDefinitions.TryGetValue(
                typeOrDefinition.GetProperty("symbol").GetProperty("id").GetString() ?? "",
                out var definition
            )
            && TypeDefinitionDerives(definition, "Hash")
        )
        {
            var typeName = TypeDefinitionName(definition.GetProperty("symbol"));
            var implName = DerivedHashImplTypeName(typeName);
            yield return $"{implName}.hash_combine({value.NormalizeWhitespace()}, {hasher.NormalizeWhitespace()});";
            yield break;
        }

        var typeText = EmitType(typeOrDefinition).NormalizeWhitespace().ToFullString();
        yield return $"{hasher.NormalizeWhitespace()}.acc = unchecked({hasher.NormalizeWhitespace()}.acc * 16777619u + (uint)System.Collections.Generic.EqualityComparer<{typeText}>.Default.GetHashCode({value.NormalizeWhitespace()}));";
    }

    private IEnumerable<string> EmitDerivedEnumHashStatements(
        JsonElement definition,
        ExpressionSyntax value,
        ExpressionSyntax hasher
    )
    {
        var typeName = QualifiedTypeDefinitionName(definition.GetProperty("symbol"));
        var variants = definition.GetProperty("variants").EnumerateArray().ToArray();
        var valueText = value.NormalizeWhitespace().ToFullString();
        if (variants.All(variant => variant.GetProperty("payloads").GetArrayLength() == 0))
        {
            yield return $"{hasher.NormalizeWhitespace()}.acc = unchecked({hasher.NormalizeWhitespace()}.acc * 16777619u + (uint)(int){valueText});";
            yield break;
        }

        yield return $"{hasher.NormalizeWhitespace()}.acc = unchecked({hasher.NormalizeWhitespace()}.acc * 16777619u + (uint)(int){valueText}.Kind);";
        yield return "switch (" + valueText + ".Kind)";
        yield return "{";
        foreach (var variant in variants)
        {
            var variantName = EnumVariantMemberName(
                typeName,
                variant.GetProperty("name").GetString() ?? ""
            );
            var payloads = variant.GetProperty("payloads").EnumerateArray().ToArray();
            yield return $"case {typeName}.Tag.{variantName}:";
            if (payloads.Length > 0)
            {
                var variantType = PayloadVariantTypeName(typeName, variantName);
                for (var index = 0; index < payloads.Length; index++)
                    foreach (
                        var statement in EmitDerivedHashStatements(
                            EnumPayloadType(payloads[index]),
                            ParseExpression(
                                $"(({variantType}){valueText}).Item{index.ToString(CultureInfo.InvariantCulture)}"
                            ),
                            hasher
                        )
                    )
                        yield return statement;
            }

            yield return "break;";
        }

        yield return "}";
    }

    private IEnumerable<MemberDeclarationSyntax> EmitTrait(JsonElement trait)
    {
        var name = ToPublicIdentifier(
            trait.GetProperty("symbol").GetProperty("name").GetString() ?? ""
        );
        var objectName = TraitObjectTypeName(name);
        var implName = TraitImplInterfaceName(name);
        var genericImplName = implName;
        var methods = trait.GetProperty("methods").EnumerateArray().ToArray();
        yield return ParseMemberDeclaration(
            $"public readonly record struct {objectName}(object Self, {implName} Impl);"
        )!;
        yield return ParseMemberDeclaration(
            $$"""
              public interface {{implName}}
              {
                  {{string.Join(
                      Environment.NewLine,
                      methods.Select(method =>
                          $"{TraitMethodType(method.GetProperty("returnType"), "object")} {ToTraitMethodIdentifier(method.GetProperty("name").GetString() ?? "")}({TraitObjectMethodParameters(method)});"
                      )
                  )}}
              }
              """
        )!;
        yield return ParseMemberDeclaration(
            $$"""
              public interface {{genericImplName}}<T, TImpl>
                  where TImpl : {{genericImplName}}<T, TImpl>
              {
                  {{string.Join(
                      Environment.NewLine,
                      methods.Select(method =>
                          TraitGenericInterfaceMethod(name, method)
                      )
                  )}}
              }
              """
        )!;
        yield return ParseMemberDeclaration(
            $$"""
              public static class {{TraitDispatcherTypeName(name)}}
              {
                  {{string.Join(
                      Environment.NewLine,
                      methods.Select(method => TraitDispatcherMethod(name, method))
                  )}}
              }
              """
        )!;
        yield return ParseMemberDeclaration(
            $$"""
            public sealed class {{name}}ImplObject<T, TImpl> : {{implName}}
                where TImpl : {{genericImplName}}<T, TImpl>
            {
                public static readonly {{name}}ImplObject<T, TImpl> Instance = new();
                private {{name}}ImplObject() { }
                {{string.Join(Environment.NewLine, methods.Select(TraitObjectAdapterMethod))}}
            }
            """
        )!;
    }

    private IEnumerable<MemberDeclarationSyntax> EmitDerivedDebugMembers(JsonElement typeDefinition)
    {
        if (
            !TypeDefinitionDerives(typeDefinition, "Debug")
            || !UsedDerivedTraitImpl(typeDefinition, "Debug")
        )
            yield break;

        var symbol = typeDefinition.GetProperty("symbol");
        var name = TypeDefinitionName(symbol);
        var typeParams = ReadTypeParams(typeDefinition.GetProperty("typeParams"));
        var selfTypeName = SelfTypeName(name, typeParams);
        var implName = DerivedDebugImplTypeName(name);
        var debugImplInterfaceName = CoreDebugTypeName("IDebugImpl");
        var reprType = CoreDebugTypeName("Repr");
        var typeParameterList =
            typeParams.Length == 0
                ? ""
                : "<" + string.Join(", ", typeParams.Select(param => param.Identifier.Text)) + ">";
        var repr = EmitDerivedDebugRepr(ParseExpression("self"), typeDefinition)
            .NormalizeWhitespace()
            .ToFullString();
        yield return ParseMemberDeclaration(
            $$"""
            public sealed class {{implName}}{{typeParameterList}} : {{debugImplInterfaceName}}<{{selfTypeName}}, {{implName}}{{typeParameterList}}>
            {
                public static {{reprType}} to_repr({{selfTypeName}} self) => {{repr}};
            }
            """
        )!;
    }

    private static bool CoreBuiltinTraitEmittedManually(JsonElement trait)
    {
        var symbol = trait.GetProperty("symbol");
        return (symbol.GetProperty("packageId").GetString() ?? "") == "pkg:moonbitlang/core/builtin"
            && (symbol.GetProperty("name").GetString() ?? "") == "Hash";
    }

    private static bool TraitReferencedByTraitMethods(
        JsonElement candidate,
        JsonElement[] usedTraits
    )
    {
        var candidateId = candidate.GetProperty("symbol").GetProperty("id").GetString() ?? "";
        return usedTraits.Any(trait => TraitReferencesType(trait, candidateId));
    }

    private static bool TraitReferencesType(JsonElement element, string typeId)
    {
        if (element.ValueKind == JsonValueKind.Object)
        {
            if (
                element.TryGetProperty("kind", out var kind)
                && kind.GetString() == "TraitObject"
                && element.GetProperty("trait").GetProperty("symbol").GetProperty("id").GetString()
                    == typeId
            )
                return true;
            foreach (var property in element.EnumerateObject())
                if (TraitReferencesType(property.Value, typeId))
                    return true;
        }
        else if (element.ValueKind == JsonValueKind.Array)
        {
            foreach (var item in element.EnumerateArray())
                if (TraitReferencesType(item, typeId))
                    return true;
        }

        return false;
    }

    private MemberDeclarationSyntax EmitEnumDefinition(JsonElement typeDefinition)
    {
        var symbol = typeDefinition.GetProperty("symbol");
        var name = TypeDefinitionName(symbol);
        var typeParams = ReadTypeParams(typeDefinition.GetProperty("typeParams"));
        var variants = typeDefinition.GetProperty("variants").EnumerateArray().ToArray();
        if (variants.All(variant => variant.GetProperty("payloads").GetArrayLength() == 0))
            return EnumDeclaration(name)
                .AddModifiers(Token(SyntaxKind.PublicKeyword))
                .WithMembers(
                    SeparatedList(
                        variants.Select(variant =>
                            EnumMemberDeclaration(
                                EnumVariantMemberName(
                                    name,
                                    variant.GetProperty("name").GetString() ?? ""
                                )
                            )
                        )
                    )
                );

        var tagMembers = variants.Select(variant =>
            EnumMemberDeclaration(
                EnumVariantMemberName(name, variant.GetProperty("name").GetString() ?? "")
            )
        );
        var members = new List<MemberDeclarationSyntax>
        {
            EnumDeclaration("Tag")
                .AddModifiers(Token(SyntaxKind.PublicKeyword))
                .WithMembers(SeparatedList(tagMembers)),
            FieldDeclaration(
                    VariableDeclaration(IdentifierName("Tag"))
                        .WithVariables(SingletonSeparatedList(VariableDeclarator("Kind")))
                )
                .AddModifiers(Token(SyntaxKind.PublicKeyword), Token(SyntaxKind.ReadOnlyKeyword)),
            ConstructorDeclaration(name)
                .AddModifiers(Token(SyntaxKind.ProtectedKeyword))
                .WithParameterList(
                    ParameterList(
                        SingletonSeparatedList(
                            Parameter(Identifier("kind")).WithType(IdentifierName("Tag"))
                        )
                    )
                )
                .WithBody(
                    Block(
                        ExpressionStatement(
                            AssignmentExpression(
                                SyntaxKind.SimpleAssignmentExpression,
                                IdentifierName("Kind"),
                                IdentifierName("kind")
                            )
                        )
                    )
                ),
        };
        var selfTypeName = SelfTypeName(name, typeParams);
        foreach (var variant in variants)
        {
            var variantName = EnumVariantMemberName(
                name,
                variant.GetProperty("name").GetString() ?? ""
            );
            var payloads = variant.GetProperty("payloads").EnumerateArray().ToArray();
            var variantTypeName = variantName + "Variant";
            var parameters = payloads
                .Select(
                    (payload, index) =>
                        Parameter(Identifier("item" + index.ToString(CultureInfo.InvariantCulture)))
                            .WithType(EmitType(EnumPayloadType(payload)))
                )
                .ToArray();
            var properties = payloads
                .Select(
                    (payload, index) =>
                        PropertyDeclaration(
                                EmitType(EnumPayloadType(payload)),
                                "Item" + index.ToString(CultureInfo.InvariantCulture)
                            )
                            .AddModifiers(Token(SyntaxKind.PublicKeyword))
                            .WithAccessorList(
                                AccessorList(
                                    List([
                                        AccessorDeclaration(SyntaxKind.GetAccessorDeclaration)
                                            .WithSemicolonToken(Token(SyntaxKind.SemicolonToken)),
                                        AccessorDeclaration(SyntaxKind.InitAccessorDeclaration)
                                            .WithSemicolonToken(Token(SyntaxKind.SemicolonToken)),
                                    ])
                                )
                            )
                )
                .Cast<MemberDeclarationSyntax>()
                .ToArray();
            var assignments = payloads.Select(
                (_, index) =>
                    ExpressionStatement(
                        AssignmentExpression(
                            SyntaxKind.SimpleAssignmentExpression,
                            MemberAccessExpression(
                                SyntaxKind.SimpleMemberAccessExpression,
                                ThisExpression(),
                                IdentifierName(
                                    "Item" + index.ToString(CultureInfo.InvariantCulture)
                                )
                            ),
                            IdentifierName("item" + index.ToString(CultureInfo.InvariantCulture))
                        )
                    )
            );
            var variantClass = ClassDeclaration(variantTypeName)
                .AddModifiers(Token(SyntaxKind.PublicKeyword), Token(SyntaxKind.SealedKeyword))
                .WithBaseList(
                    BaseList(
                        SingletonSeparatedList<BaseTypeSyntax>(
                            SimpleBaseType(ParseTypeName(selfTypeName))
                        )
                    )
                )
                .AddMembers(
                    properties
                        .Append(
                            ConstructorDeclaration(variantTypeName)
                                .AddModifiers(Token(SyntaxKind.PublicKeyword))
                                .WithParameterList(ParameterList(SeparatedList(parameters)))
                                .WithInitializer(
                                    ConstructorInitializer(
                                        SyntaxKind.BaseConstructorInitializer,
                                        ArgumentList(
                                            SingletonSeparatedList(
                                                Argument(
                                                    MemberAccessExpression(
                                                        SyntaxKind.SimpleMemberAccessExpression,
                                                        IdentifierName("Tag"),
                                                        IdentifierName(variantName)
                                                    )
                                                )
                                            )
                                        )
                                    )
                                )
                                .WithBody(Block(assignments))
                        )
                        .ToArray()
                );
            members.Add(variantClass);

            if (payloads.Length == 0)
                members.Add(
                    FieldDeclaration(
                            VariableDeclaration(ParseTypeName(selfTypeName))
                                .WithVariables(
                                    SingletonSeparatedList(
                                        VariableDeclarator(Identifier(variantName))
                                            .WithInitializer(
                                                EqualsValueClause(
                                                    ObjectCreationExpression(
                                                            IdentifierName(variantTypeName)
                                                        )
                                                        .WithArgumentList(ArgumentList())
                                                )
                                            )
                                    )
                                )
                        )
                        .AddModifiers(
                            Token(SyntaxKind.PublicKeyword),
                            Token(SyntaxKind.StaticKeyword),
                            Token(SyntaxKind.ReadOnlyKeyword)
                        )
                );
            else
                members.Add(
                    MethodDeclaration(ParseTypeName(selfTypeName), variantName)
                        .AddModifiers(
                            Token(SyntaxKind.PublicKeyword),
                            Token(SyntaxKind.StaticKeyword)
                        )
                        .WithParameterList(ParameterList(SeparatedList(parameters)))
                        .WithBody(
                            Block(
                                ReturnStatement(
                                    ObjectCreationExpression(IdentifierName(variantTypeName))
                                        .WithArgumentList(
                                            ArgumentList(
                                                SeparatedList(
                                                    parameters.Select(parameter =>
                                                        Argument(
                                                            IdentifierName(
                                                                parameter.Identifier.Text
                                                            )
                                                        )
                                                    )
                                                )
                                            )
                                        )
                                )
                            )
                        )
                );
        }

        var declaration = ClassDeclaration(name)
            .AddModifiers(Token(SyntaxKind.PublicKeyword), Token(SyntaxKind.AbstractKeyword))
            .AddMembers(members.ToArray());
        return typeParams.Length == 0
            ? declaration
            : declaration.WithTypeParameterList(TypeParameterList(SeparatedList(typeParams)));
    }

    private static JsonElement EnumPayloadType(JsonElement payload)
    {
        return
            payload.ValueKind == JsonValueKind.Object
            && payload.TryGetProperty("type", out var type)
            ? type
            : payload;
    }

    private static string? EnumPayloadLabel(JsonElement payload)
    {
        return
            payload.ValueKind == JsonValueKind.Object
            && payload.TryGetProperty("label", out var label)
            && label.ValueKind == JsonValueKind.String
            ? label.GetString()
            : null;
    }

    private MemberDeclarationSyntax EmitStructDefinition(
        string name,
        TypeParameterSyntax[] typeParams,
        JsonElement[] fields,
        bool hasMutableField
    )
    {
        var modifiers = hasMutableField
            ? new[] { Token(SyntaxKind.PublicKeyword) }
            : [Token(SyntaxKind.PublicKeyword), Token(SyntaxKind.ReadOnlyKeyword)];
        var declaration = StructDeclaration(name)
            .AddModifiers(modifiers)
            .AddMembers(
                fields
                    .Select(EmitStructProperty)
                    .Cast<MemberDeclarationSyntax>()
                    .Append(EmitConstructor(name, fields))
                    .ToArray()
            );
        return typeParams.Length == 0
            ? declaration
            : declaration.WithTypeParameterList(TypeParameterList(SeparatedList(typeParams)));
    }

    private PropertyDeclarationSyntax EmitStructProperty(JsonElement field)
    {
        var mutable = field.GetProperty("mutable").GetBoolean();
        var secondAccessor = mutable
            ? AccessorDeclaration(SyntaxKind.SetAccessorDeclaration)
            : AccessorDeclaration(SyntaxKind.InitAccessorDeclaration);
        return PropertyDeclaration(
                EmitType(field.GetProperty("type")),
                ToPublicIdentifier(field.GetProperty("name").GetString() ?? "")
            )
            .AddModifiers(Token(SyntaxKind.PublicKeyword))
            .WithAccessorList(
                AccessorList(
                    List([
                        AccessorDeclaration(SyntaxKind.GetAccessorDeclaration)
                            .WithSemicolonToken(Token(SyntaxKind.SemicolonToken)),
                        secondAccessor.WithSemicolonToken(Token(SyntaxKind.SemicolonToken)),
                    ])
                )
            );
    }

    private ConstructorDeclarationSyntax EmitConstructor(
        string containingTypeName,
        JsonElement[] fields
    )
    {
        var parameters = fields.Select(field =>
            Parameter(Identifier(ToLocalIdentifier(field.GetProperty("name").GetString() ?? "")))
                .WithType(EmitType(field.GetProperty("type")))
        );
        var assignments = fields.Select(field =>
            ExpressionStatement(
                AssignmentExpression(
                    SyntaxKind.SimpleAssignmentExpression,
                    MemberAccessExpression(
                        SyntaxKind.SimpleMemberAccessExpression,
                        ThisExpression(),
                        IdentifierName(
                            ToPublicIdentifier(field.GetProperty("name").GetString() ?? "")
                        )
                    ),
                    IdentifierName(ToLocalIdentifier(field.GetProperty("name").GetString() ?? ""))
                )
            )
        );
        return ConstructorDeclaration(containingTypeName)
            .AddModifiers(Token(SyntaxKind.PublicKeyword))
            .WithParameterList(ParameterList(SeparatedList(parameters)))
            .WithBody(Block(assignments));
    }

    private MemberDeclarationSyntax EmitGlobal(JsonElement global)
    {
        return PropertyDeclaration(
                EmitType(global.GetProperty("type")),
                ToPublicIdentifier(global.GetProperty("name").GetString() ?? "")
            )
            .AddModifiers(VisibilityModifier(global), Token(SyntaxKind.StaticKeyword))
            .WithAccessorList(
                AccessorList(
                    SingletonList(
                        AccessorDeclaration(SyntaxKind.GetAccessorDeclaration)
                            .WithSemicolonToken(Token(SyntaxKind.SemicolonToken))
                    )
                )
            )
            .WithInitializer(EqualsValueClause(EmitExpr(global.GetProperty("value"))))
            .WithSemicolonToken(Token(SyntaxKind.SemicolonToken));
    }

    private MethodDeclarationSyntax EmitFunction(JsonElement function)
    {
        BuildLocalNameCollisionMap(function);
        var returnType = EmitFunctionReturnType(function);
        var symbolId = function.GetProperty("symbolId").GetString() ?? "";
        var name = FunctionMethodName(
            symbolId,
            function.GetProperty("name").GetString() ?? symbolId
        );
        var typeParamInfos = function.TryGetProperty("typeParams", out var typeParamsNode)
            ? ReadTypeParamInfos(typeParamsNode)
            : [];
        var typeParams = typeParamInfos
            .Select(param => TypeParameter(ToLocalIdentifier(param.Name)))
            .Concat(
                typeParamInfos.SelectMany(param =>
                    param.Constraints.Select(trait =>
                        TypeParameter(StaticTraitImplTypeParameterName(param.Name, trait))
                    )
                )
            )
            .ToArray();
        var parameters = function
            .GetProperty("params")
            .EnumerateArray()
            .Select(param =>
                Parameter(Identifier(LocalIdentifier(param)))
                    .WithType(EmitType(param.GetProperty("type")))
            );
        var previousFunctionRaises = currentFunctionRaises;
        var previousFunctionErrorType = currentFunctionErrorType;
        var previousFunctionReturnType = currentFunctionReturnType;
        currentFunctionRaises = TryGetRaisingEffect(function, out var functionErrorType);
        currentFunctionErrorType = functionErrorType;
        currentFunctionReturnType = function.GetProperty("returnType");
        var body = TryEmitExternalFunctionBody(function, out var externalBody)
            ? externalBody
            : EmitFunctionBody(function.GetProperty("body"));
        currentFunctionRaises = previousFunctionRaises;
        currentFunctionErrorType = previousFunctionErrorType;
        currentFunctionReturnType = previousFunctionReturnType;
        var declaration = MethodDeclaration(returnType, name)
            .AddModifiers(VisibilityModifier(function), Token(SyntaxKind.StaticKeyword))
            .WithParameterList(ParameterList(SeparatedList(parameters)))
            .WithBody(body);
        var constraints = typeParamInfos
            .SelectMany(param =>
                param.Constraints.Select(trait =>
                    TypeParameterConstraintClause(
                        IdentifierName(StaticTraitImplTypeParameterName(param.Name, trait)),
                        SingletonSeparatedList<TypeParameterConstraintSyntax>(
                            TypeConstraint(
                                ParseTypeName(StaticTraitConstraintType(param.Name, trait))
                            )
                        )
                    )
                )
            )
            .ToArray();
        declaration = declaration.AddConstraintClauses(constraints);
        return typeParams.Length == 0
            ? declaration
            : declaration.WithTypeParameterList(TypeParameterList(SeparatedList(typeParams)));
    }

    private static SyntaxToken VisibilityModifier(JsonElement member)
    {
        return
            member.TryGetProperty("isPublic", out var isPublic)
            && isPublic.ValueKind == JsonValueKind.True
            ? Token(SyntaxKind.PublicKeyword)
            : Token(SyntaxKind.InternalKeyword);
    }

    private bool ClassHasStaticTraitImplAdapter(IReadOnlyList<JsonElement> functions)
