    private sealed class RuntimeIdentifierQualifier(VNextEmitterOptions options)
        : CSharpSyntaxRewriter
    {
        private static readonly IReadOnlyDictionary<string, string> RuntimeIdentifierTargets =
            new Dictionary<string, string>(StringComparer.Ordinal)
            {
                ["ArrayUtility"] = "ArrayUtility",
                ["ArrayView"] = "ArrayView",
                ["BytesView"] = "BytesView",
                ["ConsoleUtility"] = "ConsoleUtility",
                ["FixedArray"] = "FixedArray",
                ["Intrinsics"] = "Intrinsics",
                ["MutArrayView"] = "MutArrayView",
                ["Option"] = "Option",
                ["OptionEq"] = "OptionEq",
                ["OptionEqImpl"] = "OptionEqImpl",
                ["NullableOptionEqImpl"] = "NullableOptionEqImpl",
                ["Panic"] = "Panic",
                ["Result"] = "Result",
                ["StringBuilder"] = "StringBuilder",
                ["StringView"] = "StringView",
                ["Unit"] = "Unit",
                ["BuiltinEq"] = "BuiltinEq",
                ["MoonBitArray"] = "Array",
                ["MoonBitArrayView"] = "ArrayView",
                ["MoonBitBytesView"] = "BytesView",
                ["MoonBitConsole"] = "ConsoleUtility",
                ["MoonBitFixedArray"] = "FixedArray",
                ["MoonBitIntrinsics"] = "Intrinsics",
                ["MoonBitMutArrayView"] = "MutArrayView",
                ["MoonBitPanic"] = "Panic",
                ["MoonBitResult"] = "Result",
                ["MoonBitStringBuilder"] = "StringBuilder",
                ["MoonBitStringView"] = "StringView",
                ["MoonBitUnit"] = "Unit",
                ["MoonBitEq"] = "BuiltinEq",
                ["MoonBitError"] = "Error",
            };
        private static readonly IReadOnlyDictionary<
            string,
            string
        > QualifiedRuntimeIdentifierTargets = RuntimeIdentifierTargets
            .Concat(
                new[]
                {
                    new KeyValuePair<string, string>("IShowImpl", "IShowImpl"),
                    new KeyValuePair<string, string>("Logger", "Logger"),
                }
            )
            .ToDictionary(pair => pair.Key, pair => pair.Value, StringComparer.Ordinal);

        public override SyntaxNode? VisitMemberAccessExpression(MemberAccessExpressionSyntax node)
        {
            if (
                node.Expression is IdentifierNameSyntax { Identifier.ValueText: "Array" }
                && node.Name.Identifier.ValueText == "Empty"
            )
                return node.WithExpression(ParseName("global::System.Array"))
                    .WithName((SimpleNameSyntax)Visit(node.Name)!);

            if (
                RuntimeIdentifierTargets.TryGetValue(
                    LastMemberAccessIdentifier(node.Expression),
                    out var target
                ) && IsRuntimeMemberAccessNamespace(node.Expression)
            )
                return node.WithExpression(RuntimeQualifiedName(target));

            return base.VisitMemberAccessExpression(node);
        }

        public override SyntaxNode? VisitQualifiedName(QualifiedNameSyntax node)
        {
            if (
                IsRuntimeNamespace(node.Left)
                && QualifiedRuntimeIdentifierTargets.TryGetValue(
                    node.Right.Identifier.ValueText,
                    out var target
                )
            )
                return QualifiedName(RuntimeNamespaceName(), RenameSimpleName(node.Right, target));

            return base.VisitQualifiedName(node);
        }

        public override SyntaxNode? VisitIdentifierName(IdentifierNameSyntax node)
        {
            if (IsMemberOrQualifiedNamePart(node))
                return base.VisitIdentifierName(node);

            return RuntimeIdentifierTargets.TryGetValue(node.Identifier.ValueText, out var target)
                ? RuntimeQualifiedName(target)
                : base.VisitIdentifierName(node);
        }

        public override SyntaxNode? VisitGenericName(GenericNameSyntax node)
        {
            if (
                IsSimpleNamePart(node)
                || !RuntimeIdentifierTargets.TryGetValue(node.Identifier.ValueText, out var target)
            )
                return base.VisitGenericName(node);

            var visitedTypeArguments = TypeArgumentList(
                SeparatedList(
                    node.TypeArgumentList.Arguments.Select(argument => (TypeSyntax)Visit(argument)!)
                )
            );
            return QualifiedName(
                RuntimeNamespaceName(),
                GenericName(Identifier(target)).WithTypeArgumentList(visitedTypeArguments)
            );
        }

        private static bool IsMemberOrQualifiedNamePart(IdentifierNameSyntax node)
        {
            return IsSimpleNamePart(node);
        }

        private static bool IsSimpleNamePart(SimpleNameSyntax node)
        {
            return node.Parent switch
            {
                MemberAccessExpressionSyntax memberAccess
                    when ReferenceEquals(memberAccess.Name, node) => true,
                MemberBindingExpressionSyntax memberBinding
                    when ReferenceEquals(memberBinding.Name, node) => true,
                QualifiedNameSyntax qualifiedName when ReferenceEquals(qualifiedName.Right, node) =>
                    true,
                AliasQualifiedNameSyntax aliasQualifiedName
                    when ReferenceEquals(aliasQualifiedName.Name, node) => true,
                _ => false,
            };
        }

        private bool IsRuntimeNamespace(NameSyntax name)
        {
            return string.Equals(
                name.ToString(),
                "global::" + options.RuntimeNamespace,
                StringComparison.Ordinal
            );
        }

        private bool IsRuntimeMemberAccessNamespace(ExpressionSyntax expression)
        {
            var text = expression.ToString();
            var lastDot = text.LastIndexOf('.');
            if (lastDot < 0)
                return false;

            return string.Equals(
                text[..lastDot],
                "global::" + options.RuntimeNamespace,
                StringComparison.Ordinal
            );
        }

        private static string LastMemberAccessIdentifier(ExpressionSyntax expression)
        {
            return expression switch
            {
                IdentifierNameSyntax identifier => identifier.Identifier.ValueText,
                MemberAccessExpressionSyntax memberAccess => memberAccess.Name.Identifier.ValueText,
                _ => "",
            };
        }

        private NameSyntax RuntimeNamespaceName()
        {
            return ParseName("global::" + options.GeneratedNamespace + ".Runtime");
        }

        private NameSyntax RuntimeQualifiedName(string name)
        {
            return ParseName("global::" + options.GeneratedNamespace + ".Runtime." + name);
        }

        private static SimpleNameSyntax RenameSimpleName(SimpleNameSyntax name, string target)
        {
            return name switch
            {
                GenericNameSyntax generic => generic.WithIdentifier(Identifier(target)),
                _ => IdentifierName(target),
            };
        }
    }
