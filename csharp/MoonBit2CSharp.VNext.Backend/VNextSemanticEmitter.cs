    {
        var indexSymbol = expr.GetProperty("indexSymbol");
        if (indexSymbol.ValueKind == JsonValueKind.Null)
            return;

        statements.Add(
            ExpressionStatement(
                PostfixUnaryExpression(
                    SyntaxKind.PostIncrementExpression,
                    IdentifierName(LocalIdentifier(indexSymbol))
                )
            )
        );
    }

    private ExpressionSyntax EmitForInNext(JsonElement expr, string iteratorName)
    {
        var iteratorType = expr.GetProperty("iterator").GetProperty("type");
        if (
            iteratorType.GetProperty("kind").GetString() == "Declared"
            && IsDeclaredTypeNamed(iteratorType, "Iter")
        )
            return InvocationExpression(
                MemberAccessExpression(
                    SyntaxKind.SimpleMemberAccessExpression,
                    IdentifierName(iteratorName),
                    IdentifierName("f")
                )
            );

        if (
            iteratorType.GetProperty("kind").GetString() == "Declared"
            && IsDeclaredTypeNamed(iteratorType, "Iter2")
        )
            return InvocationExpression(
                MemberAccessExpression(
                    SyntaxKind.SimpleMemberAccessExpression,
                    MemberAccessExpression(
                        SyntaxKind.SimpleMemberAccessExpression,
                        IdentifierName(iteratorName),
                        IdentifierName("iter")
                    ),
                    IdentifierName("f")
                )
            );

        return InvocationExpression(
            MemberAccessExpression(
                SyntaxKind.SimpleMemberAccessExpression,
                IdentifierName(iteratorName),
                IdentifierName("f")
            )
        );
    }

    private ExpressionSyntax IterNextMemberAccess(JsonElement iteratorType)
    {
        var symbolId =
            iteratorType.TryGetProperty("symbol", out var symbol)
            && symbol.TryGetProperty("id", out var id)
                ? id.GetString() ?? ""
                : "";
        var packageName = PackageNameFromSymbolId(symbolId);
        foreach (var (functionId, methodName) in functionNames)
            if (
                functionId.EndsWith(
                    ":" + IteratorTypeDeclarationName(iteratorType) + "::next",
                    StringComparison.Ordinal
                )
                && PackageNameFromSymbolId(functionId) == packageName
            )
                return FunctionMemberAccess(functionId);

        var containerName = SymbolContainerName(symbolId, rootModuleName);
        var container =
            packageName.Length > 0 && packageName != currentPackageName
                ? "global::" + PackageNamespace(packageName) + "." + containerName
                : containerName;
        return ParseExpression(container + ".next");
    }

    private static string IteratorTypeDeclarationName(JsonElement type)
    {
        if (
            type.TryGetProperty("symbol", out var symbol)
            && symbol.TryGetProperty("name", out var name)
        )
            return name.GetString() ?? "";
        if (
            type.TryGetProperty("constructor", out var constructor)
            && constructor.TryGetProperty("name", out var constructorName)
        )
            return constructorName.GetString() ?? "";
        return "";
    }

    private bool TryGetSpecializedForInSource(JsonElement iterator, out ForInSource source)
    {
        source = default;
        if (
            iterator.GetProperty("kind").GetString() != "Call"
            || !iterator.TryGetProperty("args", out var argsElement)
        )
            return false;

        var args = argsElement.EnumerateArray().ToArray();
        if (args.Length != 1)
            return false;

        var functionId = iterator.GetProperty("functionId").GetString() ?? "";
        var receiver = args[0];
        var receiverType = receiver.GetProperty("type");
        if (
            (
                functionId.EndsWith(":Array::iter", StringComparison.Ordinal)
                || functionId.EndsWith(":Array::iter2", StringComparison.Ordinal)
            ) && IsBuiltinApply(receiverType, "Array")
        )
        {
            source = new(ForInSourceKind.ArrayLike, receiver);
            return true;
        }

        if (
            (
                functionId.EndsWith(":FixedArray::iter", StringComparison.Ordinal)
                || functionId.EndsWith(":FixedArray::iter2", StringComparison.Ordinal)
            ) && IsBuiltinApply(receiverType, "FixedArray")
        )
        {
            source = new(ForInSourceKind.ArrayLike, receiver);
            return true;
        }

        if (
            (
                (
                    functionId.EndsWith(":ArrayView::iter", StringComparison.Ordinal)
                    || functionId.EndsWith(":ArrayView::iter2", StringComparison.Ordinal)
                ) && IsBuiltinApply(receiverType, "ArrayView")
            )
            || (
                (
                    functionId.EndsWith(":MutArrayView::iter", StringComparison.Ordinal)
                    || functionId.EndsWith(":MutArrayView::iter2", StringComparison.Ordinal)
                ) && IsBuiltinApply(receiverType, "MutArrayView")
            )
        )
        {
            source = new(ForInSourceKind.ArrayLike, receiver);
            return true;
        }

        if (
            (
                functionId.EndsWith(":String::iter", StringComparison.Ordinal)
                || functionId.EndsWith(":String::iter2", StringComparison.Ordinal)
            ) && IsBuiltinType(receiverType, "String")
        )
        {
            source = new(ForInSourceKind.StringLike, receiver);
            return true;
        }

        if (
            (
                functionId.EndsWith(":StringView::iter", StringComparison.Ordinal)
                || functionId.EndsWith(":StringView::iter2", StringComparison.Ordinal)
            ) && IsBuiltinType(receiverType, "StringView")
        )
        {
            source = new(ForInSourceKind.StringLike, receiver);
            return true;
        }

        if (
            (
                functionId.EndsWith(":Bytes::iter", StringComparison.Ordinal)
                || functionId.EndsWith(":Bytes::iter2", StringComparison.Ordinal)
            ) && IsBuiltinType(receiverType, "Bytes")
        )
        {
            source = new(ForInSourceKind.BytesLike, receiver);
            return true;
        }

        if (
            (
                functionId.EndsWith(":BytesView::iter", StringComparison.Ordinal)
                || functionId.EndsWith(":BytesView::iter2", StringComparison.Ordinal)
            ) && IsBuiltinType(receiverType, "BytesView")
        )
        {
            source = new(ForInSourceKind.BytesLike, receiver);
            return true;
        }

        return false;
    }

    private void EmitForLoopBodyStatement(
        JsonElement expr,
        JsonElement loop,
        List<StatementSyntax> statements,
        string? loopResultDestination
    )
    {
        var kind = expr.GetProperty("kind").GetString();
        switch (kind)
        {
            case "Sequence":
                EmitForLoopBodyStatement(
                    expr.GetProperty("first"),
                    loop,
                    statements,
                    loopResultDestination
                );
                if (IsTerminalLoopControl(expr.GetProperty("first")))
                    return;
                EmitForLoopBodyStatement(
                    expr.GetProperty("body"),
                    loop,
                    statements,
                    loopResultDestination
                );
                return;

            case "LocalLet":
                EmitExprAsStatement(expr, statements);
                return;

            case "Break":
                EmitBreakStatement(expr, statements);
                return;

            case "Continue":
                EmitContinueStatement(expr, statements);
                return;

            case "If":
            {
                var thenStatements = new List<StatementSyntax>();
                EmitForLoopBodyStatement(
                    expr.GetProperty("then"),
                    loop,
                    thenStatements,
                    loopResultDestination
                );
                var elseStatements = new List<StatementSyntax>();
                EmitForLoopBodyStatement(
                    expr.GetProperty("else"),
                    loop,
                    elseStatements,
                    loopResultDestination
                );
                statements.Add(
                    IfStatement(
                        EmitExpr(expr.GetProperty("condition")),
                        Block(thenStatements),
                        ElseClauseIfNotEmpty(elseStatements)
                    )
                );
                return;
            }

            case "Match":
                EmitMatchAsStatement(expr, statements);
                return;

            case "Guard":
                EmitGuardAsStatement(expr, statements);
                return;

            case "ForRange":
                statements.Add(EmitForRange(expr));
                return;

            case "ForLoop":
                statements.Add(EmitForLoop(expr));
                return;

            case "UnitLiteral":
                return;

            default:
                statements.Add(ExpressionStatement(EmitExpr(expr)));
                return;
        }
    }

    private void EmitForLoopUpdates(JsonElement loop, List<StatementSyntax> statements)
    {
        foreach (var update in loop.GetProperty("updates").EnumerateArray())
            statements.Add(ExpressionStatement(EmitExpr(update)));
    }

    private void EmitForLoopContinueAssignments(
        JsonElement continueExpr,
        JsonElement loop,
        List<StatementSyntax> statements
    )
    {
        if (!continueExpr.TryGetProperty("args", out var argsElement))
        {
            EmitLoopDefaultContinue(loop, statements);
            return;
        }

        var args = argsElement.EnumerateArray().ToArray();
        if (args.Length == 0)
        {
            EmitLoopDefaultContinue(loop, statements);
            return;
        }

        var bindings = loop.GetProperty("bindings").EnumerateArray().ToArray();
        if (args.Length != bindings.Length)
            throw new InvalidOperationException(
                $"continue value count ({args.Length}) must match loop binding count ({bindings.Length})"
            );

        var tempNames = args.Select(_ => FreshEmitterTempName("__mbt_continue")).ToArray();
        for (var i = 0; i < args.Length && i < bindings.Length; i++)
            statements.Add(
                LocalDeclarationStatement(
                    VariableDeclaration(EmitType(bindings[i].GetProperty("type")))
                        .WithVariables(
                            SingletonSeparatedList(
                                VariableDeclarator(tempNames[i])
                                    .WithInitializer(EqualsValueClause(EmitExpr(args[i])))
                            )
                        )
                )
            );

        for (var i = 0; i < args.Length; i++)
            statements.Add(
                ExpressionStatement(
                    AssignmentExpression(
                        SyntaxKind.SimpleAssignmentExpression,
                        IdentifierName(LocalIdentifier(bindings[i])),
                        IdentifierName(tempNames[i])
                    )
                )
            );
    }

    private void EmitLoopDefaultContinue(JsonElement loop, List<StatementSyntax> statements)
    {
        if ((loop.GetProperty("kind").GetString() ?? "") == "ForLoop")
            EmitForLoopUpdates(loop, statements);
    }

    private string FreshEmitterTempName(string prefix)
    {
        return prefix + tempNameIndex++.ToString(CultureInfo.InvariantCulture);
    }

    private static bool IsTerminalLoopControl(JsonElement expr)
    {
        var kind = expr.GetProperty("kind").GetString();
        if (kind == "Break" || kind == "Continue")
            return true;

        if (kind == "If")
            return IsTerminalLoopControl(expr.GetProperty("then"))
                && IsTerminalLoopControl(expr.GetProperty("else"));

        return false;
    }

    private StatementSyntax EmitForRange(JsonElement expr)
    {
        var loopName = LocalIdentifier(
            expr.GetProperty("name").GetString() ?? "",
            expr.TryGetProperty("symbolId", out var symbolId) ? symbolId.GetString() ?? "" : ""
        );
        var variables = new List<VariableDeclaratorSyntax>();
        var startExpression = BoundExpression(expr.GetProperty("start"), variables, "rangeStart");
        var endExpression = BoundExpression(expr.GetProperty("end"), variables, "rangeEnd");
        var reverse = expr.GetProperty("reverse").GetBoolean();
        var inclusive = expr.GetProperty("inclusive").GetBoolean();
        var excludeStart = expr.GetProperty("excludeStart").GetBoolean();
        variables.Add(
            VariableDeclarator(loopName)
                .WithInitializer(
                    EqualsValueClause(
                        reverse && excludeStart
                            ? BinaryExpression(
                                SyntaxKind.SubtractExpression,
                                startExpression,
                                LiteralExpression(SyntaxKind.NumericLiteralExpression, Literal(1))
                            )
                            : startExpression
                    )
                )
        );

        var bodyStatements = new List<StatementSyntax>();
        EmitExprAsStatement(expr.GetProperty("body"), bodyStatements);
        var loop = ForStatement(Block(bodyStatements))
            .WithDeclaration(
                VariableDeclaration(PredefinedType(Token(SyntaxKind.IntKeyword)))
                    .WithVariables(SeparatedList(variables))
            )
            .WithCondition(
                BinaryExpression(
                    reverse
                        ? inclusive
                            ? SyntaxKind.GreaterThanOrEqualExpression
                            : SyntaxKind.GreaterThanExpression
                        : inclusive
                            ? SyntaxKind.LessThanOrEqualExpression
                            : SyntaxKind.LessThanExpression,
                    IdentifierName(loopName),
                    endExpression
                )
            )
            .WithIncrementors(
                SingletonSeparatedList<ExpressionSyntax>(
                    PostfixUnaryExpression(
                        reverse
                            ? SyntaxKind.PostDecrementExpression
                            : SyntaxKind.PostIncrementExpression,
                        IdentifierName(loopName)
                    )
                )
            );
        return loop;
    }

    private ExpressionSyntax BoundExpression(
        JsonElement expr,
        List<VariableDeclaratorSyntax> variables,
        string namePrefix
    )
    {
        if (expr.GetProperty("kind").GetString() == "IntLiteral")
            return EmitExpr(expr);

        var name =
            "__moonbit" + namePrefix + tempNameIndex++.ToString(CultureInfo.InvariantCulture);
        variables.Add(VariableDeclarator(name).WithInitializer(EqualsValueClause(EmitExpr(expr))));
        return IdentifierName(name);
    }

