    private ExpressionSyntax EmitBytesLiteral(string value)
    {
        var bytes = MoonBitBytesLiteralBytes(value);
        var cacheKey = currentPackageName + "|" + currentMemberContainerName + "|" + value;
        if (!bytesLiteralCaches.TryGetValue(cacheKey, out var cache))
        {
            var fieldName =
                "__bytes_literal_"
                + bytesLiteralCaches.Count.ToString(CultureInfo.InvariantCulture);
            cache = (fieldName, bytes);
            bytesLiteralCaches[cacheKey] = cache;
        }

        return CastExpression(
            ArrayType(PredefinedType(Token(SyntaxKind.ByteKeyword)))
                .WithRankSpecifiers(
                    SingletonList(
                        ArrayRankSpecifier(
                            SingletonSeparatedList<ExpressionSyntax>(OmittedArraySizeExpression())
                        )
                    )
                ),
            InvocationExpression(
                MemberAccessExpression(
                    SyntaxKind.SimpleMemberAccessExpression,
                    IdentifierName(cache.FieldName),
                    IdentifierName("Clone")
                )
            )
        );
    }

    private IEnumerable<MemberDeclarationSyntax> EmitBytesLiteralCacheMembers(
        string packageName,
        string containerName
    )
    {
        var prefix = packageName + "|" + containerName + "|";
        foreach (
            var cache in bytesLiteralCaches.Where(entry =>
                entry.Key.StartsWith(prefix, StringComparison.Ordinal)
            )
        )
        {
            yield return FieldDeclaration(
                    VariableDeclaration(
                            ArrayType(PredefinedType(Token(SyntaxKind.ByteKeyword)))
                                .WithRankSpecifiers(
                                    SingletonList(
                                        ArrayRankSpecifier(
                                            SingletonSeparatedList<ExpressionSyntax>(
                                                OmittedArraySizeExpression()
                                            )
                                        )
                                    )
                                )
                        )
                        .WithVariables(
                            SingletonSeparatedList(
                                VariableDeclarator(cache.Value.FieldName)
                                    .WithInitializer(
                                        EqualsValueClause(EmitByteArrayCreation(cache.Value.Bytes))
                                    )
                            )
                        )
                )
                .AddModifiers(
                    Token(SyntaxKind.PrivateKeyword),
                    Token(SyntaxKind.StaticKeyword),
                    Token(SyntaxKind.ReadOnlyKeyword)
                )
                .WithSemicolonToken(Token(SyntaxKind.SemicolonToken));
        }
    }

    private static ExpressionSyntax EmitByteArrayCreation(byte[] bytes)
    {
        var elements = new System.Collections.Generic.List<ExpressionSyntax>();
        foreach (var b in bytes)
        {
            elements.Add(LiteralExpression(SyntaxKind.NumericLiteralExpression, Literal((int)b)));
        }

        return ArrayCreationExpression(
                ArrayType(PredefinedType(Token(SyntaxKind.ByteKeyword)))
                    .WithRankSpecifiers(
                        SingletonList(
                            ArrayRankSpecifier(
                                SingletonSeparatedList<ExpressionSyntax>(
                                    OmittedArraySizeExpression()
                                )
                            )
                        )
                    )
            )
            .WithInitializer(
                InitializerExpression(
                    SyntaxKind.ArrayInitializerExpression,
                    SeparatedList(elements)
                )
            );
    }

    private static byte[] MoonBitBytesLiteralBytes(string value)
    {
        var bytes = new System.Collections.Generic.List<byte>();
        for (var i = 0; i < value.Length; i++)
        {
            var ch = value[i];
            if (ch == '\\' && i + 1 < value.Length)
            {
                var escaped = value[++i];
                switch (escaped)
                {
                    case 'n':
                        bytes.Add((byte)'\n');
                        continue;
                    case 'r':
                        bytes.Add((byte)'\r');
                        continue;
                    case 't':
                        bytes.Add((byte)'\t');
                        continue;
                    case '0':
                        bytes.Add(0);
                        continue;
                    case '\\':
                        bytes.Add((byte)'\\');
                        continue;
                    case '"':
                        bytes.Add((byte)'"');
                        continue;
                    case '\'':
                        bytes.Add((byte)'\'');
                        continue;
                    case 'x' when i + 2 < value.Length:
                        var hi = HexNibble(value[i + 1]);
                        var lo = HexNibble(value[i + 2]);
                        if (hi >= 0 && lo >= 0)
                        {
                            bytes.Add((byte)((hi << 4) | lo));
                            i += 2;
                            continue;
                        }

                        break;
                }

                bytes.AddRange(Encoding.UTF8.GetBytes(escaped.ToString()));
                continue;
            }

            bytes.AddRange(Encoding.UTF8.GetBytes(ch.ToString()));
        }

        return bytes.ToArray();
    }

    private static int HexNibble(char ch) =>
        ch switch
        {
            >= '0' and <= '9' => ch - '0',
            >= 'a' and <= 'f' => ch - 'a' + 10,
            >= 'A' and <= 'F' => ch - 'A' + 10,
            _ => -1,
        };

    private static int CharLiteralCodePoint(string value)
    {
        if (value.Length == 0)
            return 0;

        if (value[0] != '\\')
            return char.ConvertToUtf32(value, 0);

        if (value.Length == 1)
            return '\\';

        return value[1] switch
        {
            'n' => '\n',
            'r' => '\r',
            't' => '\t',
            '\\' => '\\',
            '\'' => '\'',
            '"' => '"',
            _ => char.ConvertToUtf32(value, 1),
        };
    }

    private static bool UsesMapLiteral(JsonElement element)
    {
        if (
            element.ValueKind == JsonValueKind.Object
            && element.TryGetProperty("kind", out var kind)
            && kind.GetString() == "MapLiteral"
        )
            return true;

        if (element.ValueKind == JsonValueKind.Object)
        {
            foreach (var property in element.EnumerateObject())
                if (UsesMapLiteral(property.Value))
                    return true;
        }
        else if (element.ValueKind == JsonValueKind.Array)
        {
            foreach (var item in element.EnumerateArray())
                if (UsesMapLiteral(item))
                    return true;
        }

        return false;
    }

    private TypeSyntax EmitType(JsonElement type)
    {
        return type.GetProperty("kind").GetString() switch
        {
            "Builtin" when type.GetProperty("name").GetString() == "Int" => PredefinedType(
                Token(SyntaxKind.IntKeyword)
            ),
            "Builtin" when type.GetProperty("name").GetString() == "Float" => PredefinedType(
                Token(SyntaxKind.FloatKeyword)
            ),
            "Builtin" when type.GetProperty("name").GetString() == "Double" => PredefinedType(
                Token(SyntaxKind.DoubleKeyword)
            ),
            "Builtin" when type.GetProperty("name").GetString() == "Bool" => PredefinedType(
                Token(SyntaxKind.BoolKeyword)
            ),
            "Builtin" when type.GetProperty("name").GetString() == "Byte" => PredefinedType(
                Token(SyntaxKind.ByteKeyword)
            ),
            "Builtin" when type.GetProperty("name").GetString() == "Int16" => PredefinedType(
                Token(SyntaxKind.ShortKeyword)
            ),
            "Builtin" when type.GetProperty("name").GetString() == "Int64" => PredefinedType(
                Token(SyntaxKind.LongKeyword)
            ),
            "Builtin" when type.GetProperty("name").GetString() == "UInt" => PredefinedType(
                Token(SyntaxKind.UIntKeyword)
            ),
            "Builtin" when type.GetProperty("name").GetString() == "UInt16" => PredefinedType(
                Token(SyntaxKind.UShortKeyword)
            ),
            "Builtin" when type.GetProperty("name").GetString() == "UInt64" => PredefinedType(
                Token(SyntaxKind.ULongKeyword)
            ),
            "Builtin" when type.GetProperty("name").GetString() == "Char" => PredefinedType(
                Token(SyntaxKind.IntKeyword)
            ),
            "Builtin" when type.GetProperty("name").GetString() == "Bytes" => ArrayType(
                PredefinedType(Token(SyntaxKind.ByteKeyword)),
                SingletonList(
                    ArrayRankSpecifier(
                        SingletonSeparatedList<ExpressionSyntax>(OmittedArraySizeExpression())
                    )
                )
            ),
            "Builtin" when type.GetProperty("name").GetString() == "BytesView" => IdentifierName(
                "MoonBitBytesView"
            ),
            "Builtin" when type.GetProperty("name").GetString() == "Error" => IdentifierName(
                "MoonBitError"
            ),
            "Builtin" when type.GetProperty("name").GetString() == "SourceLoc" => IdentifierName(
                "MoonBitSourceLoc"
            ),
            "Builtin" when type.GetProperty("name").GetString() == "StringBuilder" =>
                IdentifierName("MoonBitStringBuilder"),
            "Builtin" when type.GetProperty("name").GetString() == "String" => PredefinedType(
                Token(SyntaxKind.StringKeyword)
            ),
            "Builtin" when type.GetProperty("name").GetString() == "StringView" => IdentifierName(
                "MoonBitStringView"
            ),
            "Builtin" when type.GetProperty("name").GetString() == "Unit" => IdentifierName(
                "MoonBitUnit"
            ),
            _ when IsBuiltinApply(type, "Array") => ParseTypeName(
                $"MoonBitArray<{EmitType(type.GetProperty("args")[0]).NormalizeWhitespace().ToFullString()}>"
            ),
            _ when IsBuiltinApply(type, "ArrayView") => ParseTypeName(
                $"MoonBitArrayView<{EmitType(type.GetProperty("args")[0]).NormalizeWhitespace().ToFullString()}>"
            ),
            _ when IsBuiltinApply(type, "MutArrayView") => ParseTypeName(
                $"MoonBitMutArrayView<{EmitType(type.GetProperty("args")[0]).NormalizeWhitespace().ToFullString()}>"
            ),
            _ when IsBuiltinApply(type, "Option") => EmitOptionType(type),
            _ when IsBuiltinApply(type, "Result") => ParseTypeName(
                $"MoonBitResult<{EmitType(type.GetProperty("args")[0]).NormalizeWhitespace().ToFullString()}, {EmitType(type.GetProperty("args")[1]).NormalizeWhitespace().ToFullString()}>"
            ),
            _ when IsBuiltinApply(type, "Map") => ParseTypeName(
                $"{CoreBuiltinTypeName("Map")}<{EmitType(type.GetProperty("args")[0]).NormalizeWhitespace().ToFullString()}, {EmitType(type.GetProperty("args")[1]).NormalizeWhitespace().ToFullString()}>"
            ),
            _ when IsBuiltinApply(type, "UninitializedArray") => ArrayType(
                    EmitType(type.GetProperty("args")[0])
                )
                .WithRankSpecifiers(
                    SingletonList(
                        ArrayRankSpecifier(
                            SingletonSeparatedList<ExpressionSyntax>(OmittedArraySizeExpression())
                        )
                    )
                ),
            _ when IsBuiltinApply(type, "FixedArray") => ArrayType(
                    EmitType(type.GetProperty("args")[0])
                )
                .WithRankSpecifiers(
                    SingletonList(
                        ArrayRankSpecifier(
                            SingletonSeparatedList<ExpressionSyntax>(OmittedArraySizeExpression())
                        )
                    )
                ),
            "TraitObject" => IdentifierName(
                QualifiedTraitObjectTypeName(type.GetProperty("trait").GetProperty("symbol"))
            ),
            "Tuple" => ParseTypeName(
                "("
                    + string.Join(
                        ", ",
                        type.GetProperty("items")
                            .EnumerateArray()
                            .Select(item => EmitType(item).NormalizeWhitespace().ToFullString())
                    )
                    + ")"
            ),
            "Function" => EmitFunctionType(type),
            "Declared" => ParseTypeName(DeclaredTypeName(type)),
            "TypeParameter" => IdentifierName(
                SafeIdentifier(type.GetProperty("name").GetString() ?? "")
            ),
            var kind => throw new NotSupportedException($"vnext type is not supported: {kind}"),
        };
    }

    private TypeSyntax EmitFunctionType(JsonElement type)
    {
        var parts = type.GetProperty("params")
            .EnumerateArray()
            .Select(param =>
                EmitType(param.GetProperty("type")).NormalizeWhitespace().ToFullString()
            )
            .Append(EmitType(type.GetProperty("return")).NormalizeWhitespace().ToFullString());
        return ParseTypeName($"System.Func<{string.Join(", ", parts)}>");
    }

