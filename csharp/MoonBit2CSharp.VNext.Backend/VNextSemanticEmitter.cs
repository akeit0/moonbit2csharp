    private string TraitEvidenceTypeArgument(JsonElement type, string traitName)
    {
        if (type.GetProperty("kind").GetString() == "TypeParameter")
            return StaticTraitImplTypeParameterName(
                type.GetProperty("name").GetString() ?? "",
                traitName
            );

        if (
            staticTraitImplAdapterTypes.TryGetValue(
                StaticTraitImplAdapterKey(traitName, type),
                out var adapterType
            )
        )
            return adapterType;

        if (
            TryGenericStaticTraitImplAdapterTypeArgument(
                type,
                traitName,
                out var genericAdapterType
            )
        )
            return genericAdapterType;

        if (traitName == "Show" && IsBuiltinApply(type, "Option"))
        {
            var elementType = OptionElementType(type);
            var elementTypeName = EmitType(elementType).NormalizeWhitespace().ToFullString();
            var elementShowType = TraitEvidenceTypeArgument(elementType, "Show");
            var implName = UseNullableReferenceOption(type)
                ? "NullableOptionShowImpl"
                : "OptionShowImpl";
            requiredCoreBuiltinEvidence.Add(implName);
            return $"{CoreBuiltinTypeName(implName)}<{elementTypeName}, {elementShowType}>";
        }

        if (
            traitName == "Eq"
            && type.GetProperty("kind").GetString() == "Declared"
            && DeclaredTypeDerives(type, "Eq")
        )
        {
            var symbol = type.GetProperty("symbol");
            var typeName = TypeDefinitionName(symbol);
            var implName = DerivedEqImplTypeName(typeName);
            var args = type.TryGetProperty("args", out var typeArgs)
                ? typeArgs.EnumerateArray().ToArray()
                : [];
            var qualifiedImplName = QualifyPackageTypeName(
                symbol.GetProperty("id").GetString() ?? "",
                implName
            );
            if (args.Length == 0)
                return qualifiedImplName;

            return qualifiedImplName
                + "<"
                + string.Join(
                    ", ",
                    args.Select(arg => EmitType(arg).NormalizeWhitespace().ToFullString())
                )
                + ">";
        }

        if (
            traitName == "Hash"
            && type.GetProperty("kind").GetString() == "Declared"
            && DeclaredTypeDerives(type, "Hash")
        )
        {
            var symbol = type.GetProperty("symbol");
            var typeName = TypeDefinitionName(symbol);
            var implName = DerivedHashImplTypeName(typeName);
            var args = type.TryGetProperty("args", out var typeArgs)
                ? typeArgs.EnumerateArray().ToArray()
                : [];
            var qualifiedImplName = QualifyPackageTypeName(
                symbol.GetProperty("id").GetString() ?? "",
                implName
            );
            if (args.Length == 0)
                return qualifiedImplName;

            return qualifiedImplName
                + "<"
                + string.Join(
                    ", ",
                    args.Select(arg => EmitType(arg).NormalizeWhitespace().ToFullString())
                )
                + ">";
        }

        var builtinTypeName = BuiltinTypeName(type);
        if (CoreBuiltinEvidenceName(builtinTypeName, traitName) is { } coreBuiltinEvidenceName)
            requiredCoreBuiltinEvidence.Add(coreBuiltinEvidenceName);

        return (builtinTypeName, traitName) switch
        {
            ("Int", "Eq") => CoreBuiltinTypeName("IntEqImpl"),
            ("Int", "Hash") => CoreBuiltinTypeName("IntHashImpl"),
            ("String", "Eq") => CoreBuiltinTypeName("StringEqImpl"),
            ("Char", "Eq") => CoreBuiltinTypeName("CharEqImpl"),
            ("String", "Hash") => CoreBuiltinTypeName("StringHashImpl"),
            ("StringBuilder", "Logger") => CoreBuiltinTypeName("StringBuilderLoggerImpl"),
            ("String", "Show") => CoreBuiltinTypeName("StringShowImpl"),
            ("StringView", "Show") => CoreBuiltinTypeName("StringViewShowImpl"),
            ("Char", "Show") => CoreBuiltinTypeName("CharShowImpl"),
            ("Int", "Show") => CoreBuiltinTypeName("IntShowImpl"),
            ("Bytes", "Show") => CoreBuiltinTypeName("BytesShowImpl"),
            ("BytesView", "Show") => CoreBuiltinTypeName("BytesViewShowImpl"),
            ("Int", "Debug") => CoreDebugTypeName("IntDebugImpl"),
            ("String", "Debug") => CoreDebugTypeName("StringDebugImpl"),
            ("StringView", "Debug") => CoreDebugTypeName("StringViewDebugImpl"),
            _ => StaticTraitImplTypeParameterName(
                EmitType(type).NormalizeWhitespace().ToFullString(),
                traitName
            ),
        };
    }

    private static string StaticTraitImplAdapterKey(string traitName, JsonElement type)
    {
        return traitName + "|" + TypeEvidenceKey(type);
    }

    private static string TypeEvidenceKey(JsonElement type)
    {
        var kind = type.GetProperty("kind").GetString() ?? "";
        return kind switch
        {
            "Declared" when type.TryGetProperty("symbol", out var symbol) => "Declared:"
                + (symbol.GetProperty("id").GetString() ?? ""),
            "Builtin" => "Builtin:" + (type.GetProperty("name").GetString() ?? ""),
            "TypeParameter" => "TypeParameter:" + (type.GetProperty("name").GetString() ?? ""),
            _ => kind + ":" + type.GetRawText(),
        };
    }

    private bool TryGenericStaticTraitImplAdapterTypeArgument(
        JsonElement type,
        string traitName,
        out string evidenceName
    )
    {
        evidenceName = "";
        if (
            !genericStaticTraitImplAdapters.TryGetValue(
                StaticTraitImplAdapterKey(traitName, type),
                out var adapter
            )
        )
            return false;

        var substitutions = new Dictionary<string, JsonElement>(StringComparer.Ordinal);
        if (!TryBuildTypeParameterSubstitutions(adapter.SelfType, type, substitutions))
            return false;

        var typeArguments = new List<string>();
        foreach (var typeParam in adapter.TypeParams)
        {
            if (!substitutions.TryGetValue(typeParam.Name, out var actualType))
                return false;

            typeArguments.Add(EmitType(actualType).NormalizeWhitespace().ToFullString());
            foreach (var constraint in typeParam.Constraints)
                typeArguments.Add(TraitEvidenceTypeArgument(actualType, constraint));
        }

        var adapterTypeName = QualifyPackageTypeName(adapter.SymbolId, adapter.AdapterTypeName);
        evidenceName =
            typeArguments.Count == 0
                ? adapterTypeName
                : adapterTypeName + "<" + string.Join(", ", typeArguments) + ">";
        return true;
    }

    private static bool TryBuildTypeParameterSubstitutions(
        JsonElement pattern,
        JsonElement actual,
        Dictionary<string, JsonElement> substitutions
    )
    {
        var patternKind = pattern.GetProperty("kind").GetString() ?? "";
        var actualKind = actual.GetProperty("kind").GetString() ?? "";
        if (patternKind == "TypeParameter")
        {
            var name = pattern.GetProperty("name").GetString() ?? "";
            if (substitutions.TryGetValue(name, out var previous))
                return TypeStructuralKey(previous) == TypeStructuralKey(actual);

            substitutions[name] = actual;
            return true;
        }

        if (patternKind != actualKind)
            return false;

        if (patternKind == "Declared")
        {
            if (
                pattern.GetProperty("symbol").GetProperty("id").GetString()
                != actual.GetProperty("symbol").GetProperty("id").GetString()
            )
                return false;

            var patternArgs = pattern.TryGetProperty("args", out var patternArgsNode)
                ? patternArgsNode.EnumerateArray().ToArray()
                : [];
            var actualArgs = actual.TryGetProperty("args", out var actualArgsNode)
                ? actualArgsNode.EnumerateArray().ToArray()
                : [];
            if (patternArgs.Length != actualArgs.Length)
                return false;

            for (var i = 0; i < patternArgs.Length; i++)
                if (
                    !TryBuildTypeParameterSubstitutions(
                        patternArgs[i],
                        actualArgs[i],
                        substitutions
                    )
                )
                    return false;

            return true;
        }

        if (patternKind == "Builtin")
            return pattern.GetProperty("name").GetString()
                == actual.GetProperty("name").GetString();

        return TypeEvidenceKey(pattern) == TypeEvidenceKey(actual);
    }

    private static string TypeStructuralKey(JsonElement type)
    {
        var kind = type.GetProperty("kind").GetString() ?? "";
        return kind switch
        {
            "Declared" when type.TryGetProperty("symbol", out var symbol) => "Declared:"
                + (symbol.GetProperty("id").GetString() ?? "")
                + "<"
                + string.Join(
                    ",",
                    type.TryGetProperty("args", out var args)
                        ? args.EnumerateArray().Select(TypeStructuralKey)
                        : Enumerable.Empty<string>()
                )
                + ">",
            "Builtin" => "Builtin:" + (type.GetProperty("name").GetString() ?? ""),
            "TypeParameter" => "TypeParameter:" + (type.GetProperty("name").GetString() ?? ""),
            _ => kind + ":" + type.GetRawText(),
        };
    }

    private static bool ContainsTypeParameter(JsonElement type)
    {
        var kind = type.GetProperty("kind").GetString() ?? "";
        if (kind == "TypeParameter")
            return true;

        if (type.TryGetProperty("args", out var args))
            foreach (var arg in args.EnumerateArray())
                if (ContainsTypeParameter(arg))
                    return true;

        return false;
    }

    private ExpressionSyntax EmitBinary(JsonElement expr)
    {
        return EmitBinary(
            expr,
            EmitExpr(expr.GetProperty("left")),
            EmitExpr(expr.GetProperty("right"))
        );
    }

    private ExpressionSyntax EmitBinary(
        JsonElement expr,
        ExpressionSyntax left,
        ExpressionSyntax right
    )
    {
        if (
            expr.TryGetProperty("selectedIntrinsic", out var optionIntrinsic)
            && optionIntrinsic.ValueKind == JsonValueKind.String
            && IsOptionEqualityIntrinsic(optionIntrinsic.GetString() ?? "")
        )
            return EmitOptionEquality(expr, left, right);

        if (IsDerivedEqualityCall(expr))
        {
            var equality = EmitDerivedEquality(
                expr.GetProperty("left").GetProperty("type"),
                left,
                right,
                new System.Collections.Generic.HashSet<string>()
            );
            return (expr.GetProperty("op").GetString() ?? "") == "!="
                ? ParenthesizedExpression(
                    PrefixUnaryExpression(
                        SyntaxKind.LogicalNotExpression,
                        ParenthesizedExpression(equality)
                    )
                )
                : ParenthesizedExpression(equality);
        }

        if (IsDerivedCompareCall(expr))
        {
            var compare = EmitDerivedCompare(
                expr.GetProperty("left").GetProperty("type"),
                left,
                right
            );
            return ParenthesizedExpression(
                BinaryExpression(
                    expr.GetProperty("op").GetString() switch
                    {
                        "<" => SyntaxKind.LessThanExpression,
                        "<=" => SyntaxKind.LessThanOrEqualExpression,
                        ">" => SyntaxKind.GreaterThanExpression,
                        ">=" => SyntaxKind.GreaterThanOrEqualExpression,
                        _ => throw new NotSupportedException(
                            "vnext derived compare operator is not supported"
                        ),
                    },
                    compare,
                    LiteralExpression(SyntaxKind.NumericLiteralExpression, Literal(0))
                )
            );
        }

        if (
            expr.TryGetProperty("selectedIntrinsic", out var intrinsic)
            && intrinsic.ValueKind == JsonValueKind.String
            && IntrinsicBindings.TryEmit(
                intrinsic.GetString() ?? "",
                [Argument(left), Argument(right)],
                EmitType(expr.GetProperty("type")),
                out var intrinsicExpr
            )
        )
            return ParenthesizedExpression(QualifySupportExpression(intrinsicExpr));

        if (TryEmitPrimitiveResolvedBinary(expr, left, right, out var primitiveBinary))
            return ParenthesizedExpression(primitiveBinary);

        if (TryEmitSelectedBinaryFunction(expr, left, right, out var selectedCall))
            return selectedCall;

        return ParenthesizedExpression(
            BinaryExpression(
                expr.GetProperty("op").GetString() switch
                {
                    "+" => SyntaxKind.AddExpression,
                    "&&" => SyntaxKind.LogicalAndExpression,
                    "||" => SyntaxKind.LogicalOrExpression,
                    _ => throw new NotSupportedException(UnsupportedBinaryOperatorMessage(expr)),
                },
                ParenthesizeBinaryOperand(left),
                ParenthesizeBinaryOperand(right)
            )
        );
    }

    private static ExpressionSyntax ParenthesizeBinaryOperand(ExpressionSyntax expression)
    {
        return expression is BinaryExpressionSyntax or ConditionalExpressionSyntax
            ? ParenthesizedExpression(expression)
            : expression;
    }

    private bool TryEmitSelectedBinaryFunction(
        JsonElement expr,
        ExpressionSyntax left,
        ExpressionSyntax right,
        out ExpressionSyntax result
    )
    {
        result = LiteralExpression(SyntaxKind.NullLiteralExpression);
        if (
            !expr.TryGetProperty("selectedFunctionId", out var selected)
            || selected.ValueKind != JsonValueKind.String
        )
            return false;

        var functionId = selected.GetString() ?? "";
        if (functionId.Length == 0)
            return false;

        result = InvocationExpression(
            FunctionMemberAccess(
                functionId,
                expr.TryGetProperty("typeArgs", out var typeArgs)
                    ? typeArgs.EnumerateArray().ToArray()
                    : []
            ),
            ArgumentList(SeparatedList([Argument(left), Argument(right)]))
        );
        return true;
    }

    private static string UnsupportedBinaryOperatorMessage(JsonElement expr)
    {
        var op = expr.GetProperty("op").GetString() ?? "";
        var selectedFunctionId =
            expr.TryGetProperty("selectedFunctionId", out var selected)
            && selected.ValueKind == JsonValueKind.String
                ? selected.GetString() ?? ""
                : "";
        var selectedIntrinsic =
            expr.TryGetProperty("selectedIntrinsic", out var intrinsic)
            && intrinsic.ValueKind == JsonValueKind.String
                ? intrinsic.GetString() ?? ""
                : "";
        return "vnext binary operator requires a supported intrinsic or logical operator"
            + $": op='{op}', selectedFunctionId='{selectedFunctionId}', selectedIntrinsic='{selectedIntrinsic}'";
    }

    private static bool TryEmitPrimitiveResolvedBinary(
        JsonElement expr,
        ExpressionSyntax left,
        ExpressionSyntax right,
        out ExpressionSyntax result
    )
    {
        result = LiteralExpression(SyntaxKind.NullLiteralExpression);
        if (
            !expr.TryGetProperty("selectedFunctionId", out var selected)
            || selected.ValueKind != JsonValueKind.String
            || string.IsNullOrWhiteSpace(selected.GetString())
        )
            return false;

        var leftType = expr.GetProperty("left").GetProperty("type");
        var rightType = expr.GetProperty("right").GetProperty("type");
        if (!SameBuiltinType(leftType, rightType) || !IsPrimitiveBinaryOperatorType(leftType))
            return false;

        var kind = (expr.GetProperty("op").GetString() ?? "") switch
        {
            "==" => SyntaxKind.EqualsExpression,
            "!=" => SyntaxKind.NotEqualsExpression,
            "<" => SyntaxKind.LessThanExpression,
            "<=" => SyntaxKind.LessThanOrEqualExpression,
            ">" => SyntaxKind.GreaterThanExpression,
            ">=" => SyntaxKind.GreaterThanOrEqualExpression,
            _ => SyntaxKind.None,
        };
        if (kind == SyntaxKind.None)
            return false;
        if (
            BuiltinTypeName(leftType) is "Bool" or "String"
            && kind is not SyntaxKind.EqualsExpression and not SyntaxKind.NotEqualsExpression
        )
            return false;

        result = BinaryExpression(
            kind,
            ParenthesizeBinaryOperand(left),
            ParenthesizeBinaryOperand(right)
        );
        return true;
    }

    private static bool SameBuiltinType(JsonElement left, JsonElement right)
    {
        return left.GetProperty("kind").GetString() == "Builtin"
            && right.GetProperty("kind").GetString() == "Builtin"
            && left.GetProperty("name").GetString() == right.GetProperty("name").GetString();
    }

    private static bool IsPrimitiveBinaryOperatorType(JsonElement type)
    {
        return BuiltinTypeName(type)
            is "Byte"
                or "Int"
                or "Int16"
                or "Int64"
                or "UInt"
                or "UInt16"
                or "UInt64"
                or "Float"
                or "Double"
                or "Char"
                or "Bool"
                or "String"
                or "StringView";
    }

    private ExpressionSyntax EmitOptionEquality(
        JsonElement expr,
        ExpressionSyntax left,
        ExpressionSyntax right
    )
    {
        var optionType = expr.GetProperty("left").GetProperty("type");
        var elementType = OptionElementType(optionType);
        var elementTypeName = EmitType(elementType).NormalizeWhitespace().ToFullString();
        var elementEqEvidenceName = EqEvidenceName(elementType);
        var helperName = UseNullableReferenceOption(optionType)
            ? "equal_nullable_reference"
            : "equal";
        var equalityTarget = UseNullableReferenceOption(optionType)
            ? SupportTypeName("OptionEq")
            : CoreBuiltinTypeName("impl_Eq_Option_X_");
        var equality = ParseExpression(
            $"{equalityTarget}.{helperName}<{elementTypeName}, {elementEqEvidenceName}>({left.NormalizeWhitespace()}, {right.NormalizeWhitespace()})"
        );
        return (expr.GetProperty("op").GetString() ?? "") == "!="
            ? ParenthesizedExpression(
                PrefixUnaryExpression(SyntaxKind.LogicalNotExpression, equality)
            )
            : ParenthesizedExpression(equality);
    }

    private static bool IsOptionEqualityIntrinsic(string intrinsic)
    {
        return intrinsic is "%option_eq" or "%option_ne";
    }

    private static bool IsDerivedEqualityCall(JsonElement expr)
    {
        return expr.TryGetProperty("selectedFunctionId", out var selected)
            && selected.ValueKind == JsonValueKind.String
            && (selected.GetString() ?? "").StartsWith("derived:trait:", StringComparison.Ordinal)
            && (selected.GetString() ?? "").Contains(":Eq:", StringComparison.Ordinal)
            && (expr.GetProperty("op").GetString() ?? "") is "==" or "!=";
    }

    private static bool IsDerivedCompareCall(JsonElement expr)
    {
        return expr.TryGetProperty("selectedFunctionId", out var selected)
            && selected.ValueKind == JsonValueKind.String
            && (selected.GetString() ?? "").StartsWith("derived:trait:", StringComparison.Ordinal)
            && (selected.GetString() ?? "").Contains(":Compare:", StringComparison.Ordinal)
            && (expr.GetProperty("op").GetString() ?? "") is "<" or "<=" or ">" or ">=";
    }

    private ExpressionSyntax EmitDerivedCompare(
        JsonElement type,
        ExpressionSyntax left,
        ExpressionSyntax right
    )
    {
        if (type.GetProperty("kind").GetString() == "Builtin")
            return ParseExpression(
                $"{SupportTypeName("Compare")}.Compare({left.NormalizeWhitespace()}, {right.NormalizeWhitespace()})"
            );

        if (
            type.GetProperty("kind").GetString() == "Declared"
            && typeDefinitions.TryGetValue(
                type.GetProperty("symbol").GetProperty("id").GetString() ?? "",
                out var definition
            )
        )
        {
            var kind = definition.TryGetProperty("kind", out var kindProperty)
                ? kindProperty.GetString()
                : "Struct";
            if (kind == "Struct")
                return EmitDerivedStructCompare(definition, left, right);
            if (kind == "Enum")
                return EmitDerivedEnumCompare(definition, left, right);
        }

        return ParseExpression(
            $"{SupportTypeName("Compare")}.Compare({left.NormalizeWhitespace()}, {right.NormalizeWhitespace()})"
        );
    }

    private ExpressionSyntax EmitDerivedEquality(
        JsonElement type,
        ExpressionSyntax left,
        ExpressionSyntax right,
        System.Collections.Generic.HashSet<string> activeTypes
    )
    {
        if (type.GetProperty("kind").GetString() == "Builtin")
            return ParseExpression(
                $"System.Collections.Generic.EqualityComparer<{EmitType(type).NormalizeWhitespace()}>.Default.Equals({left.NormalizeWhitespace()}, {right.NormalizeWhitespace()})"
            );

        if (
            type.GetProperty("kind").GetString() == "Declared"
            && typeDefinitions.TryGetValue(
                type.GetProperty("symbol").GetProperty("id").GetString() ?? "",
                out var definition
            )
        )
        {
            var symbolId = type.GetProperty("symbol").GetProperty("id").GetString() ?? "";
            if (!activeTypes.Add(symbolId))
            {
                var implName = TraitEvidenceTypeArgument(type, "Eq");
                return ParseExpression(
                    $"{implName}.equal({left.NormalizeWhitespace()}, {right.NormalizeWhitespace()})"
                );
            }
            var kind = definition.TryGetProperty("kind", out var kindProperty)
                ? kindProperty.GetString()
                : "Struct";
            ExpressionSyntax equality;
            if (kind == "Struct")
                equality = EmitDerivedStructEquality(definition, left, right, activeTypes);
            else if (kind == "Enum")
                equality = EmitDerivedEnumEquality(definition, left, right, activeTypes);
            else
                equality = ParseExpression(
                    $"System.Collections.Generic.EqualityComparer<{EmitType(type).NormalizeWhitespace()}>.Default.Equals({left.NormalizeWhitespace()}, {right.NormalizeWhitespace()})"
                );
            activeTypes.Remove(symbolId);
            return equality;
        }

        return ParseExpression(
            $"System.Collections.Generic.EqualityComparer<{EmitType(type).NormalizeWhitespace()}>.Default.Equals({left.NormalizeWhitespace()}, {right.NormalizeWhitespace()})"
        );
    }

    private ExpressionSyntax EmitDerivedStructEquality(
        JsonElement definition,
        ExpressionSyntax left,
        ExpressionSyntax right,
        System.Collections.Generic.HashSet<string> activeTypes
    )
    {
        var fields = definition.GetProperty("fields").EnumerateArray().ToArray();
        if (fields.Length == 0)
            return LiteralExpression(SyntaxKind.TrueLiteralExpression);

        var checks = fields.Select(field =>
        {
            var member = ToPublicIdentifier(field.GetProperty("name").GetString() ?? "");
            return EmitDerivedEquality(
                    field.GetProperty("type"),
                    ParseExpression($"({left.NormalizeWhitespace()}).{member}"),
                    ParseExpression($"({right.NormalizeWhitespace()}).{member}"),
                    activeTypes
                )
                .NormalizeWhitespace()
                .ToFullString();
        });
        return ParseExpression(string.Join(" && ", checks.Select(check => "(" + check + ")")));
    }

    private ExpressionSyntax EmitDerivedEnumEquality(
        JsonElement definition,
        ExpressionSyntax left,
        ExpressionSyntax right,
        System.Collections.Generic.HashSet<string> activeTypes
    )
    {
        var typeName = QualifiedTypeDefinitionName(definition.GetProperty("symbol"));
        var variants = definition.GetProperty("variants").EnumerateArray().ToArray();
        if (variants.All(variant => variant.GetProperty("payloads").GetArrayLength() == 0))
            return ParenthesizedExpression(
                BinaryExpression(SyntaxKind.EqualsExpression, left, right)
            );

        var leftText = left.NormalizeWhitespace().ToFullString();
        var rightText = right.NormalizeWhitespace().ToFullString();
        var cases = variants.Select(variant =>
        {
            var variantName = EnumVariantMemberName(
                typeName,
                variant.GetProperty("name").GetString() ?? ""
            );
            var variantType = PayloadVariantTypeName(typeName, variantName);
            var payloads = variant.GetProperty("payloads").EnumerateArray().ToArray();
            var payloadChecks = payloads.Select(
                (payload, index) =>
                    EmitDerivedEquality(
                            EnumPayloadType(payload),
                            ParseExpression(
                                $"(({variantType}){leftText}).Item{index.ToString(CultureInfo.InvariantCulture)}"
                            ),
                            ParseExpression(
                                $"(({variantType}){rightText}).Item{index.ToString(CultureInfo.InvariantCulture)}"
                            ),
                            activeTypes
                        )
                        .NormalizeWhitespace()
                        .ToFullString()
            );
            var sameVariant =
                payloads.Length == 0
                    ? "true"
                    : string.Join(" && ", payloadChecks.Select(check => "(" + check + ")"));
            return $"{typeName}.Tag.{variantName} => {sameVariant}";
        });
        return ParseExpression(
            $"({leftText}.Kind == {rightText}.Kind && ({leftText}.Kind switch {{ {string.Join(", ", cases)}, _ => false }}))"
        );
    }

    private ExpressionSyntax EmitDerivedStructCompare(
        JsonElement definition,
        ExpressionSyntax left,
        ExpressionSyntax right
    )
    {
        var fields = definition.GetProperty("fields").EnumerateArray().ToArray();
        if (fields.Length == 0)
            return LiteralExpression(SyntaxKind.NumericLiteralExpression, Literal(0));

        var comparisons = fields
            .Select(field =>
            {
                var member = ToPublicIdentifier(field.GetProperty("name").GetString() ?? "");
                return $"{SupportTypeName("Compare")}.Compare(({left.NormalizeWhitespace()}).{member}, ({right.NormalizeWhitespace()}).{member})";
            })
            .ToArray();
        return ParseExpression(LexicographicCompareExpression(comparisons, 0));
    }

    private ExpressionSyntax EmitDerivedEnumCompare(
        JsonElement definition,
        ExpressionSyntax left,
        ExpressionSyntax right
    )
    {
        var typeName = QualifiedTypeDefinitionName(definition.GetProperty("symbol"));
        var variants = definition.GetProperty("variants").EnumerateArray().ToArray();
        if (variants.All(variant => variant.GetProperty("payloads").GetArrayLength() == 0))
            return ParseExpression(
                $"{SupportTypeName("Compare")}.Compare((int){left.NormalizeWhitespace()}, (int){right.NormalizeWhitespace()})"
            );

        var leftText = left.NormalizeWhitespace().ToFullString();
        var rightText = right.NormalizeWhitespace().ToFullString();
        var cases = variants.Select(
            (variant, ordinal) =>
            {
                var variantName = EnumVariantMemberName(
                    typeName,
                    variant.GetProperty("name").GetString() ?? ""
                );
                var variantType = PayloadVariantTypeName(typeName, variantName);
                var payloads = variant.GetProperty("payloads").EnumerateArray().ToArray();
                var sameVariantCompare =
                    payloads.Length == 0
                        ? "0"
                        : LexicographicCompareExpression(
                            payloads
                                .Select(
                                    (payload, index) =>
                                        EmitDerivedCompare(
                                                EnumPayloadType(payload),
                                                ParseExpression(
                                                    $"(({variantType}){leftText}).Item{index.ToString(CultureInfo.InvariantCulture)}"
                                                ),
                                                ParseExpression(
                                                    $"(({variantType}){rightText}).Item{index.ToString(CultureInfo.InvariantCulture)}"
                                                )
                                            )
                                            .NormalizeWhitespace()
                                            .ToFullString()
                                )
                                .ToArray(),
                            0
                        );
                return $"{typeName}.Tag.{variantName} => {sameVariantCompare}";
            }
        );
        return ParseExpression(
            $"({leftText}.Kind != {rightText}.Kind ? {SupportTypeName("Compare")}.Compare((int){leftText}.Kind, (int){rightText}.Kind) : ({leftText}.Kind switch {{ {string.Join(", ", cases)}, _ => 0 }}))"
        );
    }

    private static string LexicographicCompareExpression(string[] comparisons, int index)
    {
        if (index >= comparisons.Length)
            return "0";
        var temp = comparisons[index];
        return $"(({temp}) != 0 ? ({temp}) : {LexicographicCompareExpression(comparisons, index + 1)})";
    }

    private ExpressionSyntax EmitUnary(JsonElement expr)
    {
        var value = EmitExpr(expr.GetProperty("value"));
        if (
            expr.TryGetProperty("selectedIntrinsic", out var intrinsic)
            && intrinsic.ValueKind == JsonValueKind.String
            && IntrinsicBindings.TryEmit(
                intrinsic.GetString() ?? "",
                [Argument(value)],
                EmitType(expr.GetProperty("type")),
                out var intrinsicExpr
            )
        )
            return ParenthesizedExpression(QualifySupportExpression(intrinsicExpr));
        if (
            expr.TryGetProperty("selectedFunctionId", out var selected)
            && selected.ValueKind == JsonValueKind.String
            && !string.IsNullOrWhiteSpace(selected.GetString())
            && functionContainers.ContainsKey(selected.GetString() ?? "")
        )
            return InvocationExpression(
                FunctionMemberAccess(selected.GetString() ?? ""),
                ArgumentList(SingletonSeparatedList(Argument(value)))
            );

        return ParenthesizedExpression(
            PrefixUnaryExpression(
                expr.GetProperty("op").GetString() switch
                {
                    "-" => SyntaxKind.UnaryMinusExpression,
                    "!" => SyntaxKind.LogicalNotExpression,
                    _ => throw new NotSupportedException("vnext unary operator is not supported"),
                },
                value
            )
        );
    }

    private ExpressionSyntax EmitCall(JsonElement expr)
    {
        var args = expr.GetProperty("args").EnumerateArray().Select(EmitExpr).ToArray();
        return EmitCallWithArguments(expr, args);
    }

    private ExpressionSyntax EmitCallWithArguments(
        JsonElement expr,
        IReadOnlyList<ExpressionSyntax> emittedArgs
    )
    {
        var args = emittedArgs.Select(Argument).ToArray();
        if (
            expr.TryGetProperty("selectedIntrinsic", out var intrinsic)
            && intrinsic.ValueKind == JsonValueKind.String
            && IntrinsicBindings.TryEmit(
                intrinsic.GetString() ?? "",
                args,
                EmitType(expr.GetProperty("type")),
                out var intrinsicExpr
            )
        )
            return QualifySupportExpression(intrinsicExpr);

        var functionId = expr.GetProperty("functionId").GetString() ?? "";
        if (IsDerivedDefaultFunctionId(functionId))
            return EmitDerivedDefaultValue(expr.GetProperty("type"));

        if (TryEmitBuiltinPrintln(expr, functionId, emittedArgs, out var printlnExpr))
            return printlnExpr;

        if (TryEmitCoreOptionUnwrapOr(expr, functionId, emittedArgs, out var optionExpr))
            return optionExpr;

        return InvocationExpression(
            FunctionMemberAccess(
                functionId,
                expr.TryGetProperty("typeArgs", out var typeArgs)
                    ? typeArgs.EnumerateArray().ToArray()
                    : []
            ),
            ArgumentList(SeparatedList(args))
        );
    }

    private bool TryEmitCoreOptionUnwrapOr(
        JsonElement expr,
        string functionId,
        IReadOnlyList<ExpressionSyntax> emittedArgs,
        out ExpressionSyntax result
    )
    {
        result = default!;
        if (
            functionId
                != "fn:pkg:moonbitlang/core/builtin:moonbitlang/core/builtin:Option::unwrap_or"
            || emittedArgs.Count != 2
        )
            return false;

        var args = expr.GetProperty("args").EnumerateArray().ToArray();
        if (args.Length != 2 || !args[0].TryGetProperty("type", out var selfType))
            return false;

        if (!UseNullableReferenceOption(selfType))
            return false;

        result = ParseExpression(
            $"({emittedArgs[0].NormalizeWhitespace().ToFullString()} ?? {emittedArgs[1].NormalizeWhitespace().ToFullString()})"
        );
        return true;
    }

    private bool TryEmitBuiltinPrintln(
        JsonElement expr,
        string functionId,
        IReadOnlyList<ExpressionSyntax> emittedArgs,
        out ExpressionSyntax result
    )
    {
        result = default!;
        if (
            functionId != "fn:pkg:moonbitlang/core/builtin:moonbitlang/core/builtin:println"
            || emittedArgs.Count != 1
            || !expr.TryGetProperty("typeArgs", out var typeArgsElement)
        )
            return false;

        var typeArgs = typeArgsElement.EnumerateArray().ToArray();
        if (typeArgs.Length != 1)
            return false;

        var valueType = EmitType(typeArgs[0]).NormalizeWhitespace().ToFullString();
        var showType = TraitEvidenceTypeArgument(typeArgs[0], "Show");
        var value = emittedArgs[0].NormalizeWhitespace().ToFullString();
        result = ParseExpression(
            $"MoonBitIntrinsics.PrintlnString({CoreBuiltinTypeName("ShowTrait")}.to_string<{valueType}, {showType}>({value}))"
        );
        return true;
    }

    private static bool IsDerivedDefaultFunctionId(string functionId)
    {
        return functionId.StartsWith("derived:trait:", StringComparison.Ordinal)
            && functionId.Contains(":Default:", StringComparison.Ordinal)
            && functionId.EndsWith(":default", StringComparison.Ordinal);
    }

    private ExpressionSyntax EmitDerivedDefaultValue(JsonElement type)
    {
        var kind = type.GetProperty("kind").GetString();
        if (kind == "Builtin")
            return BuiltinTypeName(type) switch
            {
                "Int" or "Int16" or "Int64" or "UInt" or "UInt16" or "UInt64" or "Byte" =>
                    LiteralExpression(SyntaxKind.NumericLiteralExpression, Literal(0)),
                "Float" => ParseExpression("0.0f"),
                "Double" => ParseExpression("0.0"),
                "Bool" => LiteralExpression(SyntaxKind.FalseLiteralExpression),
                "String" => LiteralExpression(SyntaxKind.StringLiteralExpression, Literal("")),
                "Unit" => ParseExpression("MoonBitUnit.Value"),
                var name => ParseExpression("default!"),
            };
        if (kind == "Apply" && IsBuiltinApply(type, "Option"))
        {
            var typeName = EmitType(type).NormalizeWhitespace().ToFullString();
            return UseNullableReferenceOption(type)
                ? LiteralExpression(SyntaxKind.NullLiteralExpression)
                : ParseExpression($"{typeName}.None()");
        }

        if (
            kind == "Declared"
            && typeDefinitions.TryGetValue(
                type.GetProperty("symbol").GetProperty("id").GetString() ?? "",
                out var definition
            )
        )
        {
            var defKind = definition.TryGetProperty("kind", out var kindProperty)
                ? kindProperty.GetString()
                : "Struct";
            if (defKind == "Struct")
            {
                var typeName = EmitType(type).NormalizeWhitespace().ToFullString();
                var args = definition
                    .GetProperty("fields")
                    .EnumerateArray()
                    .Select(field =>
                        EmitDerivedDefaultValue(field.GetProperty("type"))
                            .NormalizeWhitespace()
                            .ToFullString()
                    );
                return ParseExpression($"new {typeName}({string.Join(", ", args)})");
            }

            if (defKind == "Enum")
            {
                var typeName = EmitType(type).NormalizeWhitespace().ToFullString();
                foreach (var variant in definition.GetProperty("variants").EnumerateArray())
                    if (variant.GetProperty("payloads").GetArrayLength() == 0)
                    {
                        var variantName = EnumVariantMemberName(
                            TypeDefinitionName(definition.GetProperty("symbol")),
                            variant.GetProperty("name").GetString() ?? ""
                        );
                        return ParseExpression($"{typeName}.{variantName}");
                    }
            }
        }

        return ParseExpression("default!");
    }

    private static HashSet<string> UsedTypeIds(
        IReadOnlyList<JsonElement> functions,
        IReadOnlyList<JsonElement> globals
    )
    {
        var result = new HashSet<string>(StringComparer.Ordinal);
        foreach (var function in functions)
            CollectUsedTypeIds(function, result);
        foreach (var global in globals)
            CollectUsedTypeIds(global, result);
        return result;
    }

    private static HashSet<string> UsedTraitIds(
        IReadOnlyList<JsonElement> functions,
        IReadOnlyList<JsonElement> globals
    )
    {
        var result = new HashSet<string>(StringComparer.Ordinal);
        foreach (var function in functions)
            CollectUsedTraitIds(function, result);
        foreach (var global in globals)
            CollectUsedTraitIds(global, result);
        return result;
    }

    private bool UsedTypeDefinition(
        JsonElement type,
        HashSet<string> usedTypeIds,
        bool emitAllDeclarations
    )
    {
        if (emitAllDeclarations)
            return !IsRuntimeBackedBuiltinTypeDefinition(type);
        if (IsRuntimeBackedBuiltinTypeDefinition(type))
            return false;
        var symbolId = type.GetProperty("symbol").GetProperty("id").GetString() ?? "";
        return usedTypeIds.Contains(symbolId)
            || PackageNameFromSymbolId(symbolId) == rootModuleName;
    }

    private static bool IsRuntimeBackedBuiltinTypeDefinition(JsonElement type)
    {
        var symbol = type.GetProperty("symbol");
        return (symbol.GetProperty("packageId").GetString() ?? "") == "pkg:moonbitlang/core/builtin"
            && (symbol.GetProperty("name").GetString() ?? "") is "Array";
    }

    private bool UsedTrait(
        JsonElement trait,
        HashSet<string> usedTraitIds,
        bool emitAllDeclarations
    )
    {
        if (emitAllDeclarations)
            return true;
        var symbolId = trait.GetProperty("symbol").GetProperty("id").GetString() ?? "";
        return usedTraitIds.Contains(symbolId)
            || PackageNameFromSymbolId(symbolId) == rootModuleName;
    }

    private static void CollectUsedTypeIds(JsonElement value, HashSet<string> result)
    {
        if (value.ValueKind == JsonValueKind.Object)
        {
            if (
                value.TryGetProperty("kind", out var kind)
                && kind.ValueKind == JsonValueKind.String
            )
                switch (kind.GetString())
                {
                    case "Declared" when value.TryGetProperty("symbol", out var symbol):
                        AddSymbolId(symbol, result);
                        break;
                    case "Apply" when value.TryGetProperty("constructor", out var constructor):
                        if (
                            constructor.ValueKind == JsonValueKind.Object
                            && constructor.TryGetProperty("kind", out var constructorKind)
                            && constructorKind.GetString() == "Declared"
                            && constructor.TryGetProperty("symbol", out var constructorSymbol)
                        )
                            AddSymbolId(constructorSymbol, result);
                        break;
                    case "StructLiteral" when value.TryGetProperty("typeId", out var typeId):
                    case "StructUpdate" when value.TryGetProperty("typeId", out typeId):
                        AddString(typeId, result);
                        break;
                }

            foreach (var property in value.EnumerateObject())
                CollectUsedTypeIds(property.Value, result);
            return;
        }

        if (value.ValueKind == JsonValueKind.Array)
            foreach (var item in value.EnumerateArray())
                CollectUsedTypeIds(item, result);
    }

    private static void CollectUsedTraitIds(JsonElement value, HashSet<string> result)
    {
        if (value.ValueKind == JsonValueKind.Object)
        {
            if (
                value.TryGetProperty("constraints", out var constraints)
                && constraints.ValueKind == JsonValueKind.Array
            )
                foreach (var constraint in constraints.EnumerateArray())
                    AddString(constraint, result);

            if (value.TryGetProperty("trait", out var trait))
                if (trait.ValueKind == JsonValueKind.Object)
                {
                    if (trait.TryGetProperty("trait", out var nestedTrait))
                        AddSymbolId(nestedTrait, result);
                    else
                        AddSymbolId(trait, result);
                }

            foreach (var property in value.EnumerateObject())
                CollectUsedTraitIds(property.Value, result);
            return;
        }

        if (value.ValueKind == JsonValueKind.Array)
            foreach (var item in value.EnumerateArray())
                CollectUsedTraitIds(item, result);
    }

    private void BuildUsedDerivedTraitImplKeys(IReadOnlyList<JsonElement> usedTraitImpls)
    {
        usedDerivedTraitImplKeys.Clear();
        foreach (var impl in usedTraitImpls)
            if (
                impl.TryGetProperty("trait", out var traitRef)
                && traitRef.TryGetProperty("symbol", out var traitSymbol)
                && impl.TryGetProperty("selfType", out var selfType)
                && selfType.ValueKind == JsonValueKind.Object
                && selfType.TryGetProperty("kind", out var kind)
                && kind.GetString() == "Declared"
                && selfType.TryGetProperty("symbol", out var selfSymbol)
                && selfSymbol.TryGetProperty("id", out var selfId)
                && selfId.ValueKind == JsonValueKind.String
            )
            {
                var traitName = traitSymbol.GetProperty("name").GetString() ?? "";
                var typeId = selfId.GetString() ?? "";
                if (
                    typeDefinitions.TryGetValue(typeId, out var definition)
                    && TypeDefinitionDerives(definition, traitName)
                )
                    usedDerivedTraitImplKeys.Add(UsedDerivedTraitImplKey(typeId, traitName));
            }
    }

    private void CollectExpressionDerivedTraitImplKeys(JsonElement value)
    {
        if (value.ValueKind == JsonValueKind.Object)
        {
            if (
                value.TryGetProperty("selectedFunctionId", out var selectedFunctionId)
                && selectedFunctionId.ValueKind == JsonValueKind.String
                && TryDerivedTraitName(selectedFunctionId.GetString() ?? "", out var traitName)
                && value.TryGetProperty("left", out var left)
                && left.ValueKind == JsonValueKind.Object
                && left.TryGetProperty("type", out var selfType)
            )
                AddUsedDerivedTraitImplKey(selfType, traitName);

            if (
                value.TryGetProperty("selectedIntrinsic", out var selectedIntrinsic)
                && selectedIntrinsic.ValueKind == JsonValueKind.String
                && IsOptionEqualityIntrinsic(selectedIntrinsic.GetString() ?? "")
                && value.TryGetProperty("left", out var optionLeft)
                && optionLeft.ValueKind == JsonValueKind.Object
                && optionLeft.TryGetProperty("type", out var optionType)
            )
                AddUsedDerivedTraitImplKey(optionType, "Eq");

            foreach (var property in value.EnumerateObject())
                CollectExpressionDerivedTraitImplKeys(property.Value);
            return;
        }

        if (value.ValueKind == JsonValueKind.Array)
            foreach (var item in value.EnumerateArray())
                CollectExpressionDerivedTraitImplKeys(item);
    }

    private void AddUsedDerivedTraitImplKey(JsonElement selfType, string traitName)
    {
        if (
            selfType.ValueKind != JsonValueKind.Object
            || !selfType.TryGetProperty("kind", out var kind)
        )
            return;

        if (kind.GetString() == "Declared")
        {
            if (
                !selfType.TryGetProperty("symbol", out var selfSymbol)
                || !selfSymbol.TryGetProperty("id", out var selfId)
                || selfId.ValueKind != JsonValueKind.String
            )
                return;

            var typeId = selfId.GetString() ?? "";
            if (
                typeDefinitions.TryGetValue(typeId, out var definition)
                && TypeDefinitionDerives(definition, traitName)
            )
                usedDerivedTraitImplKeys.Add(UsedDerivedTraitImplKey(typeId, traitName));

            return;
        }

        if (kind.GetString() != "Apply" || !selfType.TryGetProperty("args", out var args))
            return;

        foreach (var arg in args.EnumerateArray())
            AddUsedDerivedTraitImplKey(arg, traitName);
    }

    private static bool TryDerivedTraitName(string functionId, out string traitName)
    {
        traitName = "";
        if (!functionId.StartsWith("derived:trait:", StringComparison.Ordinal))
            return false;

        foreach (var candidate in new[] { "Eq", "Hash", "Debug" })
            if (functionId.Contains(":" + candidate + ":", StringComparison.Ordinal))
            {
                traitName = candidate;
                return true;
            }

        return false;
    }

    private bool UsedDerivedTraitImpl(JsonElement typeDefinition, string traitName)
    {
        var typeId = typeDefinition.GetProperty("symbol").GetProperty("id").GetString() ?? "";
        return usedDerivedTraitImplKeys.Contains(UsedDerivedTraitImplKey(typeId, traitName));
    }

    private bool RequiresCoreDebugPackage(IReadOnlySet<string> usedTraitIds)
    {
        return usedDerivedTraitImplKeys.Any(key =>
                key.StartsWith("Debug|", StringComparison.Ordinal)
            )
            || usedTraitIds.Any(traitId =>
                PackageNameFromSymbolId(traitId) == "moonbitlang/core/debug"
            );
    }

    private static void AddCoreDebugSourceDependencies(
        HashSet<string> usedTypeIds,
        HashSet<string> usedTraitIds
    )
    {
        usedTypeIds.Add("type:pkg:moonbitlang/core/debug:moonbitlang/core/debug:Repr");
        usedTraitIds.Add("type:pkg:moonbitlang/core/debug:moonbitlang/core/debug:Debug");
    }

    private IEnumerable<string> UsedDerivedTraitImplTypeIds()
    {
        foreach (var key in usedDerivedTraitImplKeys)
        {
            var separator = key.IndexOf('|', StringComparison.Ordinal);
            if (separator >= 0)
                yield return key[(separator + 1)..];
        }
    }

    private IEnumerable<string> UsedDerivedTraitImplTypeIds(string traitName)
    {
        var prefix = traitName + "|";
        foreach (var key in usedDerivedTraitImplKeys)
            if (key.StartsWith(prefix, StringComparison.Ordinal))
                yield return key[prefix.Length..];
    }

    private static string UsedDerivedTraitImplKey(string typeId, string traitName)
    {
        return traitName + "|" + typeId;
    }

    private void CloseDerivedTraitImpls(string traitName)
    {
        var changed = true;
        while (changed)
        {
            changed = false;
            foreach (var typeId in UsedDerivedTraitImplTypeIds(traitName).ToArray())
            {
                if (!typeDefinitions.TryGetValue(typeId, out var definition))
                    continue;
                foreach (var nestedId in DerivedNestedTypeIds(definition, traitName))
                    if (usedDerivedTraitImplKeys.Add(UsedDerivedTraitImplKey(nestedId, traitName)))
                        changed = true;
            }
        }
    }

    private IEnumerable<string> DerivedNestedTypeIds(JsonElement definition, string traitName)
    {
        var kind = definition.TryGetProperty("kind", out var kindProperty)
            ? kindProperty.GetString()
            : "";
        if (kind == "Struct" && definition.TryGetProperty("fields", out var fields))
            foreach (var field in fields.EnumerateArray())
            foreach (var id in DerivedTraitTypeIdsFromType(field.GetProperty("type"), traitName))
                yield return id;
        else if (kind == "Enum" && definition.TryGetProperty("variants", out var variants))
            foreach (var variant in variants.EnumerateArray())
            foreach (var payload in variant.GetProperty("payloads").EnumerateArray())
            foreach (var id in DerivedTraitTypeIdsFromType(EnumPayloadType(payload), traitName))
                yield return id;
    }

    private IEnumerable<string> DerivedTraitTypeIdsFromType(JsonElement type, string traitName)
    {
        if (type.ValueKind != JsonValueKind.Object || !type.TryGetProperty("kind", out var kind))
            yield break;

        if (kind.GetString() == "Declared")
        {
            if (
                type.TryGetProperty("symbol", out var symbol)
                && symbol.TryGetProperty("id", out var id)
                && id.ValueKind == JsonValueKind.String
                && typeDefinitions.TryGetValue(id.GetString() ?? "", out var definition)
                && TypeDefinitionDerives(definition, traitName)
            )
                yield return id.GetString() ?? "";

            yield break;
        }

        if (kind.GetString() != "Apply" || !type.TryGetProperty("args", out var args))
            yield break;

        foreach (var arg in args.EnumerateArray())
        foreach (var nestedTypeId in DerivedTraitTypeIdsFromType(arg, traitName))
            yield return nestedTypeId;
    }

    private static void AddSymbolId(JsonElement symbol, HashSet<string> result)
    {
        if (symbol.ValueKind != JsonValueKind.Object)
            return;

        if (symbol.TryGetProperty("id", out var id))
            AddString(id, result);
        else if (symbol.TryGetProperty("symbol", out var nestedSymbol))
            AddSymbolId(nestedSymbol, result);
    }

    private static void AddString(JsonElement value, HashSet<string> result)
    {
        if (value.ValueKind == JsonValueKind.String)
        {
            var text = value.GetString();
            if (!string.IsNullOrEmpty(text))
                result.Add(text);
        }
    }

    private ExpressionSyntax EmitLambda(JsonElement expr)
    {
        var parameters = expr.GetProperty("params")
            .EnumerateArray()
            .Select(param => Parameter(Identifier(LocalIdentifier(param))))
            .ToArray();
        var body = expr.GetProperty("body");
        if (ExprNeedsReturnStatementLowering(body))
        {
            var statements = new List<StatementSyntax>();
            EmitExprAsReturn(body, statements);
            return ParenthesizedLambdaExpression(
                ParameterList(SeparatedList(parameters)),
                Block(statements)
            );
        }

        return ParenthesizedLambdaExpression(
            ParameterList(SeparatedList(parameters)),
            EmitExpr(body)
        );
    }

    private ExpressionSyntax EmitIfExpression(JsonElement expr)
    {
        var condition = expr.GetProperty("condition");
        if (condition.GetProperty("kind").GetString() == "IsPattern")
        {
            var restSymbols = BoundArrayRestSymbolIds(condition.GetProperty("pattern"));
            if (ExprReferencesAnySymbol(expr.GetProperty("then"), restSymbols))
                throw new NotSupportedException(
                    "vnext array rest pattern binding requires ArrayView materialization"
                );
        }

        return ConditionalExpression(
            EmitExpr(expr.GetProperty("condition")),
            EmitExpr(expr.GetProperty("then")),
            EmitExpr(expr.GetProperty("else"))
        );
    }

    private static bool ExprReferencesAnySymbol(JsonElement expr, HashSet<string> symbolIds)
    {
        if (symbolIds.Count == 0 || expr.ValueKind != JsonValueKind.Object)
            return false;

        if (
            expr.TryGetProperty("symbolId", out var symbolId)
            && symbolId.ValueKind == JsonValueKind.String
            && symbolIds.Contains(symbolId.GetString() ?? "")
        )
            return true;

        foreach (var property in expr.EnumerateObject())
            if (JsonValueReferencesAnySymbol(property.Value, symbolIds))
                return true;

        return false;
    }

    private static bool JsonValueReferencesAnySymbol(JsonElement value, HashSet<string> symbolIds)
    {
        if (value.ValueKind == JsonValueKind.Object)
            return ExprReferencesAnySymbol(value, symbolIds);

        if (value.ValueKind == JsonValueKind.Array)
            foreach (var item in value.EnumerateArray())
                if (JsonValueReferencesAnySymbol(item, symbolIds))
                    return true;

        return false;
    }

    private static ExpressionSyntax EmitFloatLiteral(JsonElement expr)
    {
        var value = expr.GetProperty("value").GetString() ?? "0.0";
        var suffix =
            expr.GetProperty("type").GetProperty("kind").GetString() == "Builtin"
            && expr.GetProperty("type").GetProperty("name").GetString() == "Float"
            && !value.EndsWith("f", StringComparison.OrdinalIgnoreCase)
                ? "f"
                : "";
        return ParseExpression(value + suffix);
    }

    private ExpressionSyntax EmitConversion(JsonElement expr)
    {
        var value = EmitExpr(expr.GetProperty("value"));
        return expr.GetProperty("conversion").GetString() switch
        {
            "StringToStringView" => value,
            "ArrayToArrayView" => value,
            "FixedArrayToArrayView" => value,
            "IterToIter2" => ObjectCreationExpression(EmitType(expr.GetProperty("type")))
                .WithArgumentList(ArgumentList(SingletonSeparatedList(Argument(value)))),
            "ConcreteToTraitObject" => EmitConcreteToTraitObject(expr, value),
            var kind => throw new NotSupportedException(
                $"vnext conversion is not supported: {kind}"
            ),
        };
    }

    private ExpressionSyntax EmitConcreteToTraitObject(JsonElement expr, ExpressionSyntax value)
    {
        var targetType = expr.GetProperty("type");
        var traitSymbol = targetType.GetProperty("trait").GetProperty("symbol");
        var traitName = ToPublicIdentifier(traitSymbol.GetProperty("name").GetString() ?? "");
        var receiverType = expr.GetProperty("value").GetProperty("type");
        var receiverTypeName = EmitType(receiverType).NormalizeWhitespace().ToFullString();
        var implType = TraitEvidenceTypeArgument(receiverType, traitName);
        var objectType = QualifiedTraitObjectTypeName(traitSymbol);
        var implObjectType = QualifyPackageTypeName(
            traitSymbol.GetProperty("id").GetString() ?? "",
            traitName + "ImplObject"
        );
        var adapterType = implObjectType + "<" + receiverTypeName + ", " + implType + ">";
        return ParseExpression(
            $"new {objectType}({value.NormalizeWhitespace()}, {adapterType}.Instance)"
        );
    }

    private ExpressionSyntax EmitStructLiteral(JsonElement expr)
    {
        var typeId = expr.GetProperty("typeId").GetString() ?? "";
        if (!typeDefinitions.TryGetValue(typeId, out var typeDefinition))
            throw new NotSupportedException($"vnext struct literal type is not declared: {typeId}");

        var type = EmitType(expr.GetProperty("type")).NormalizeWhitespace().ToFullString();
        var literalFields = expr.GetProperty("fields")
            .EnumerateArray()
            .ToDictionary(
                field => field.GetProperty("name").GetString() ?? "",
                field => field,
                StringComparer.Ordinal
            );
        var fields = typeDefinition.GetProperty("fields").EnumerateArray();
        var args = string.Join(
            ", ",
            fields.Select(fieldDefinition =>
                EmitExpr(
                        literalFields[
                            fieldDefinition.GetProperty("name").GetString()
                                ?? throw new InvalidOperationException(
                                    "vnext struct field definition missing name"
                                )
                        ]
                            .GetProperty("value")
                    )
                    .NormalizeWhitespace()
                    .ToFullString()
            )
        );
        return ParseExpression($"new {type}({args})");
    }

    private ExpressionSyntax EmitStructUpdate(JsonElement expr)
    {
        var typeId = expr.GetProperty("typeId").GetString() ?? "";
        if (!typeDefinitions.TryGetValue(typeId, out var typeDefinition))
            throw new NotSupportedException($"vnext struct update type is not declared: {typeId}");

        var type = EmitType(expr.GetProperty("type")).NormalizeWhitespace().ToFullString();
        var baseExpr = expr.GetProperty("base");
        var updateFields = expr.GetProperty("fields")
            .EnumerateArray()
            .ToDictionary(
                field => field.GetProperty("name").GetString() ?? "",
                field => field,
                StringComparer.Ordinal
            );
        var fields = typeDefinition.GetProperty("fields").EnumerateArray();
        var args = string.Join(
            ", ",
            fields.Select(fieldDefinition =>
            {
                var name =
                    fieldDefinition.GetProperty("name").GetString()
                    ?? throw new InvalidOperationException(
                        "vnext struct field definition missing name"
                    );
                return updateFields.TryGetValue(name, out var update)
                    ? EmitExpr(update.GetProperty("value")).NormalizeWhitespace().ToFullString()
                    : MemberAccessExpression(
                            SyntaxKind.SimpleMemberAccessExpression,
                            EmitExpr(baseExpr),
                            IdentifierName(ToPublicIdentifier(name))
                        )
                        .NormalizeWhitespace()
                        .ToFullString();
            })
        );
        return ParseExpression($"new {type}({args})");
    }

    private ExpressionSyntax EmitArrayLiteral(JsonElement expr)
    {
        var type = expr.GetProperty("type");
        var elementType = type.GetProperty("args")[0];
        var elementTypeName = EmitType(elementType).NormalizeWhitespace().ToFullString();
        var itemElements = expr.GetProperty("items").EnumerateArray().ToArray();
        if (itemElements.Any(IsArraySpreadElement))
            return EmitSpreadArrayLiteral(type, elementTypeName, itemElements);

        var items = string.Join(
            ", ",
            itemElements.Select(item =>
                EmitExpr(item.GetProperty("value")).NormalizeWhitespace().ToFullString()
            )
        );
        var isEmpty = itemElements.Length == 0;
        return type.GetProperty("kind").GetString() switch
        {
            _ when IsBuiltinApply(type, "FixedArray") => ParseExpression(
                isEmpty
                    ? $"Array.Empty<{elementTypeName}>()"
                    : $"new {elementTypeName}[] {{ {items} }}"
            ),
            _ when IsBuiltinApply(type, "Array") => ParseExpression(
                isEmpty
                    ? $"new MoonBitArray<{elementTypeName}>(Array.Empty<{elementTypeName}>())"
                    : $"new MoonBitArray<{elementTypeName}>(new {elementTypeName}[] {{ {items} }})"
            ),
            var kind => throw new NotSupportedException(
                $"array literal target type is not supported: {kind}"
            ),
        };
    }

    private ExpressionSyntax EmitSpreadArrayLiteral(
        JsonElement type,
        string elementTypeName,
        JsonElement[] items
    )
    {
        var result = ParseExpression(
            $"new MoonBitArray<{elementTypeName}>(Array.Empty<{elementTypeName}>())"
        );
        var values = new List<string>();
        foreach (var item in items)
            if (IsArraySpreadElement(item))
            {
                result = ConcatArraySegment(result, elementTypeName, values);
                values.Clear();
                var spread = EmitArraySpreadValue(item.GetProperty("value"), elementTypeName);
                result = ParseExpression(
                    $"ArrayUtility.Concat({result.NormalizeWhitespace().ToFullString()}, {spread})"
                );
            }
            else
            {
                values.Add(
                    EmitExpr(item.GetProperty("value")).NormalizeWhitespace().ToFullString()
                );
            }

        result = ConcatArraySegment(result, elementTypeName, values);
        if (IsBuiltinApply(type, "Array"))
            return result;

        if (IsBuiltinApply(type, "FixedArray"))
            return ParseExpression(
                $"{result.NormalizeWhitespace().ToFullString()}.AsSpan().ToArray()"
            );

        throw new NotSupportedException(
            $"array literal target type is not supported: {type.GetProperty("kind").GetString()}"
        );
    }

    private string EmitArraySpreadValue(JsonElement spreadValue, string elementTypeName)
    {
        var spread = EmitExpr(spreadValue).NormalizeWhitespace().ToFullString();
        return ConstructedCoreBuiltinTypeNameOrNull(spreadValue.GetProperty("type")) switch
        {
            "Iter" => $"{CoreBuiltinTypeName("Iter_")}.to_array<{elementTypeName}>({spread})",
            _ => spread,
        };
    }

    private static bool IsArraySpreadElement(JsonElement item)
    {
        return string.Equals(
            item.GetProperty("kind").GetString(),
            "Spread",
            StringComparison.Ordinal
        );
    }

    private static ExpressionSyntax ConcatArraySegment(
        ExpressionSyntax current,
        string elementTypeName,
        List<string> values
    )
    {
        if (values.Count == 0)
            return current;

        var segment =
            $"new MoonBitArray<{elementTypeName}>(new {elementTypeName}[] {{ {string.Join(", ", values)} }})";
        return ParseExpression(
            $"ArrayUtility.Concat({current.NormalizeWhitespace().ToFullString()}, {segment})"
        );
    }

    private ExpressionSyntax EmitMapLiteral(JsonElement expr)
    {
        var type = expr.GetProperty("type");
        if (!IsBuiltinApply(type, "Map"))
            throw new NotSupportedException("map literal target type is not Map");

        var keyType = type.GetProperty("args")[0];
        var valueType = type.GetProperty("args")[1];
        var keyTypeName = EmitType(keyType).NormalizeWhitespace().ToFullString();
        var valueTypeName = EmitType(valueType).NormalizeWhitespace().ToFullString();
        var entryCount = expr.GetProperty("entries").GetArrayLength();
        var capacity = entryCount == 0 ? 0 : 8;
        var capacityMask = capacity == 0 ? -1 : capacity - 1;
        var growAt = capacity == 0 ? 0 : 6;
        var mapTypeName = CoreBuiltinTypeName("Map");
        var entryTypeName = CoreBuiltinTypeName("Entry");
        return ParseExpression(
            $"new {mapTypeName}<{keyTypeName}, {valueTypeName}>(new Option<{entryTypeName}<{keyTypeName}, {valueTypeName}>>[{capacity.ToString(CultureInfo.InvariantCulture)}], {entryCount.ToString(CultureInfo.InvariantCulture)}, {capacity.ToString(CultureInfo.InvariantCulture)}, {capacityMask.ToString(CultureInfo.InvariantCulture)}, {growAt.ToString(CultureInfo.InvariantCulture)}, Option<{entryTypeName}<{keyTypeName}, {valueTypeName}>>.None(), -1)"
        );
    }

